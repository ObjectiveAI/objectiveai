//! `agents mcp servers list` — list the upstream MCP servers the proxy has
//! connected for the live agent's `response_id`, with each server's metadata
//! (capabilities, name, version, description, instructions). Answered locally
//! by the proxy from its in-memory connection set — no MCP params, no upstream
//! round-trip.

use crate::cli::command::CommandRequest;

#[derive(Debug, Clone, serde::Serialize, serde::Deserialize, schemars::JsonSchema)]
#[schemars(rename = "cli.command.agents.mcp.servers.list.Request")]
pub struct Request {
    pub path_type: Path,
    pub response_id: String,
    #[serde(flatten)]
    pub base: crate::cli::command::RequestBase,
}

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize, schemars::JsonSchema)]
#[schemars(rename = "cli.command.agents.mcp.servers.list.Path")]
pub enum Path {
    #[serde(rename = "agents/mcp/servers/list")]
    AgentsMcpServersList,
}

impl CommandRequest for Request {
    fn request_base(&self) -> &crate::cli::command::RequestBase {
        &self.base
    }

    fn request_base_mut(&mut self) -> Option<&mut crate::cli::command::RequestBase> {
        Some(&mut self.base)
    }
}

pub type Response = crate::mcp::server::ListServersResult;

