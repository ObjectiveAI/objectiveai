"""install_command_execute.py

Generates the cli/command module's typed ``execute`` functions for the Python
SDK from the Rust SDK's CLI command tree — the Python port of
``objectiveai-sdk-js/scripts/install-command-execute.cjs``.

For every leaf execute-family function under
``objectiveai-sdk-rs/src/cli/command/**`` (``execute``, ``execute_transform``,
…, including the ones inside each leaf's nested ``request_schema`` /
``response_schema`` modules), this script emits an ``_execute.py`` beside that
scope's OWN generated types (e.g. ``cli/command/agents/get/_execute.py`` and the
nested ``cli/command/agents/get/request_schema/_execute.py``). The leading
underscore matters: the file is named ``_execute.py`` (not ``execute.py``) so the
``execute`` submodule never shadows the ``execute`` *function* surfaced through
the barrel — the same trick as ``request.py`` → ``Request`` (file name differs
from the exported symbol). Each leaf emits:

  - first parameter is ``executor: CommandExecutor`` (binary | plugin), then the
    leaf's own arguments minus ``agent_arguments`` (so: ``request``, and
    sometimes ``jq`` / ``transform``),
  - the same pre-call request mutations (jq set/clear, transform set/clear, the
    ``dangerous_advanced.stream`` flag) parsed from the Rust body via a bounded
    statement grammar that HARD-ERRORS on anything it doesn't recognize, so
    Rust-side drift fails generation loudly,
  - streaming fns return a ``CliStream`` of ``Union[CliError, <Item>]``
    synchronously; unary fns are ``async`` and return the first stream item,
  - the wire value is the leaf request itself: requests are self-describing via
    their single-variant ``Path`` field (e.g. ``"agents/get/request_schema"``),
    injected here so callers never depend on it.

Functions keep the Rust fn name (``execute`` / ``execute_transform``) — unlike
the JS flat surface, Python disambiguates by package path, exactly like the
generated classes (``Request`` is just ``Request`` in its leaf package). Each
function is surfaced through its leaf's ``_generated.py`` barrel (``from .execute
import ...``), so ``from objectiveai_sdk.cli.command.plugins.run import execute``
works — the same convention as the classes.

Skipping rules (reported, never silent): a fn is skipped when its scope has no
``Path`` discriminator yet, or when a referenced Request/Response type hasn't
been generated by ``install_pydantic.py`` yet (not registered in the Rust
``json_schemas()`` registry). Re-running after the Rust side lands picks them
up with no changes here.

Run order: ``install_pydantic.py`` first (it generates the types tree and the
``_generated.py`` barrels), then this script (it appends the execute imports).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Optional

# Reuse install_pydantic's title -> (module path, class name) mapping verbatim,
# so generated imports line up with the existing types tree exactly.
sys.path.insert(0, str(Path(__file__).resolve().parent))
import install_pydantic as ip  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
RUST_SRC_DIR = REPO_ROOT / "objectiveai-sdk-rs" / "src"
RUST_COMMAND_DIR = RUST_SRC_DIR / "cli" / "command"
SRC_DIR = ip.SRC_DIR  # objectiveai-sdk-py/objectiveai_sdk
SCHEMA_DIR = ip.SCHEMA_DIR

GENERATED_HEADER = (
    "# THIS FILE IS AUTO-GENERATED. DO NOT EDIT.\n"
    "# Generated by scripts/install_command_execute.py from "
    "objectiveai-sdk-rs/src/cli/command/.\n"
)

# Names already bound at the top of every generated execute.py — a payload
# class with one of these names is aliased to avoid shadowing.
_RESERVED = {
    "Request", "CliStream", "CommandExecutor", "TypeAdapter", "Field",
    "Union", "Annotated", "CliError", "Error", "JsonValue", "ensure_rebuilt",
}


# ── small helpers ────────────────────────────────────────────────────────────


def normalize(rust: str) -> str:
    """Strip ``//`` line comments and collapse whitespace runs."""
    rust = re.sub(r"//[^\n]*", " ", rust)
    rust = re.sub(r"\s+", " ", rust)
    return rust.strip()


def match_brace(text: str, open_idx: int, open_ch: str = "{", close_ch: str = "}") -> int:
    """Index of the brace that closes the one at ``open_idx``."""
    depth = 0
    for i in range(open_idx, len(text)):
        if text[i] == open_ch:
            depth += 1
        elif text[i] == close_ch:
            depth -= 1
            if depth == 0:
                return i
    raise ValueError(f"unbalanced {open_ch}{close_ch} starting at {open_idx}")


def split_top_level(text: str, sep: str = ",") -> list[str]:
    """Split on ``sep`` at angle/paren/brace depth zero."""
    parts: list[str] = []
    depth = 0
    current = ""
    for ch in text:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == sep and depth == 0:
            if current.strip():
                parts.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        parts.append(current.strip())
    return parts


# ── Rust source parsing ──────────────────────────────────────────────────────


def find_path_const(scope_source: str) -> Optional[dict]:
    """The scope's ``Path`` discriminator: a single-variant
    ``pub enum Path { #[serde(rename = "…")] Variant }`` plus a ``Request`` field
    of type ``Path`` (detected by TYPE so a rename tracks). Returns
    ``{"field", "value"}`` or ``None``."""
    enum_match = re.search(r"pub enum Path\s*\{", scope_source)
    if not enum_match:
        return None
    close = match_brace(scope_source, enum_match.end() - 1)
    body = scope_source[enum_match.end():close]
    renames = re.findall(r'#\[serde\(rename = "([^"]+)"\)\]', body)
    variant_count = len([p for p in split_top_level(normalize(body)) if p])
    if len(renames) != 1 or variant_count != 1:
        return None
    struct_match = re.search(r"pub struct Request\s*\{", scope_source)
    if not struct_match:
        return None
    struct_close = match_brace(scope_source, struct_match.end() - 1)
    struct_body = scope_source[struct_match.end():struct_close]
    field_match = re.search(r"pub (\w+)\s*:\s*Path\b", struct_body)
    if not field_match:
        return None
    return {"field": field_match.group(1), "value": renames[0]}


def find_type_aliases(scope_source: str) -> dict:
    return {m.group(1): m.group(2).strip()
            for m in re.finditer(r"pub type (\w+)\s*=\s*([^;]+);", scope_source)}


def find_local_defs(scope_source: str) -> set:
    return {m.group(1) for m in re.finditer(r"pub (?:struct|enum) (\w+)", scope_source)}


def find_reexports(scope_source: str) -> dict:
    """``pub use super::…`` re-exports → local name → e.g. ``super::get::Manifest``."""
    out: dict[str, str] = {}
    for m in re.finditer(r"pub use (super(?:::\w+)*)::\{([^}]+)\}\s*;", scope_source, re.S):
        for item in split_top_level(normalize(m.group(2))):
            as_match = re.match(r"^(\w+) as (\w+)$", item)
            if as_match:
                out[as_match.group(2)] = f"{m.group(1)}::{as_match.group(1)}"
            elif re.match(r"^\w+$", item):
                out[item] = f"{m.group(1)}::{item}"
    for m in re.finditer(r"pub use (super(?:::\w+)*)::(\w+)(?: as (\w+))?\s*;", scope_source):
        out[m.group(3) or m.group(2)] = f"{m.group(1)}::{m.group(2)}"
    return out


def find_execute_fns(scope_source: str) -> list[dict]:
    """Every ``pub async fn execute*``: name, params, return payload, body."""
    fns = []
    for m in re.finditer(r"pub async fn (execute\w*)\s*<", scope_source):
        generics_open = m.end() - 1
        generics_close = match_brace(scope_source, generics_open, "<", ">")
        paren_open = scope_source.index("(", generics_close)
        paren_close = match_brace(scope_source, paren_open, "(", ")")
        arrow = scope_source.index("->", paren_close)
        body_open = scope_source.index("{", arrow)
        body_close = match_brace(scope_source, body_open)
        fns.append({
            "name": m.group(1),
            "params": normalize(scope_source[paren_open + 1:paren_close]),
            "return_type": normalize(scope_source[arrow + 2:body_open]),
            "body": normalize(scope_source[body_open + 1:body_close]),
        })
    return fns


def parse_params(params: str, context: str) -> list[dict]:
    """JS-facing param list: drop ``executor`` / ``agent_arguments``; keep
    ``request`` (+ ``jq`` / ``transform``). Hard-errors on anything else."""
    out = []
    for raw in split_top_level(params):
        if not raw:
            continue
        p = re.sub(r"^mut ", "", raw)
        colon = p.index(":")
        name = p[:colon].strip()
        type_ = p[colon + 1:].strip()
        bare = name.lstrip("_")
        if bare in ("executor", "agent_arguments"):
            continue
        if bare == "request" and type_ == "Request":
            out.append({"name": "request"})
        elif bare == "jq" and type_ == "String":
            out.append({"name": "jq"})
        elif bare == "transform" and type_ in ("Transform", "crate::cli::command::Transform"):
            out.append({"name": "transform"})
        else:
            raise ValueError(f"{context}: unrecognized param `{raw}`")
    return out


def parse_body(body: str, context: str) -> dict:
    """The bounded body grammar. Returns the mutation set + which executor
    method finishes it. Hard-errors on residue."""
    mutations = {"jq": None, "transform": None, "stream": None}
    fragments = [
        (r"^request\.jq = None;\s*", lambda: mutations.update(jq="clear")),
        (r"^request\.jq = Some\(jq\);\s*", lambda: mutations.update(jq="set")),
        (r"^request\.base\.clear_transform\(\);\s*", lambda: mutations.update(transform="clear")),
        (r"^request\.base\.set_transform\(transform\);\s*", lambda: mutations.update(transform="set")),
        (r"^let mut advanced = request\.dangerous_advanced\.unwrap_or_default\(\); advanced\.stream = Some\(true\); request\.dangerous_advanced = Some\(advanced\);\s*",
         lambda: mutations.update(stream="set")),
        (r"^if let Some\(advanced\) = request\.dangerous_advanced\.as_mut\(\) \{ advanced\.stream = None; \}\s*",
         lambda: mutations.update(stream="clear")),
    ]
    rest = body
    progressed = True
    while progressed:
        progressed = False
        for pat, apply in fragments:
            m = re.match(pat, rest)
            if m:
                apply()
                rest = rest[m.end():]
                progressed = True
    trimmed = rest.strip()
    tail = re.match(
        r"^executor\.(execute|execute_one)\(request, agent_arguments\)\.await$", trimmed)
    if not tail:
        tail = re.match(
            r'^let resp\s*:\s*[\w:]+\s*=\s*executor\.(execute_one)\(request, agent_arguments\)'
            r'\.await\?;\s*Ok\(serde_json::to_value\(resp\)\.expect\("[^"]*"\)\)$', trimmed)
    if not tail:
        raise ValueError(
            f"{context}: unrecognized body residue `{trimmed}` — extend the statement "
            "grammar in install_command_execute.py")
    return {"mutations": mutations, "call": tail.group(1)}


# ── type resolution ──────────────────────────────────────────────────────────


def rust_module_title(segs: list[str]) -> str:
    """Title of a Rust type given its ``crate::``-relative path segments (type
    name last). Folder segments only — a type in ``src/agent/response.rs`` is
    ``agent.GetAgentResponse`` (file-module segment dropped)."""
    type_name = segs[-1]
    module_segs = segs[:-1]
    if module_segs and (RUST_SRC_DIR.joinpath(*module_segs).with_suffix(".rs")).exists():
        module_segs = module_segs[:-1]
    return ".".join([*module_segs, type_name])


def resolve_type(type_expr: str, scope: dict, module_path: list[str], context: str) -> dict:
    """Resolve a Rust type expression to ``{"kind": "json"|"string"|"schema",
    "title"?, "optional"?}``."""
    t = type_expr.strip()
    if t in ("serde_json::Value", "schemars::Schema"):
        return {"kind": "json"}
    if t == "String":
        return {"kind": "string"}
    opt = re.match(r"^Option<(.+)>$", t)
    if opt:
        inner = resolve_type(opt.group(1), scope, module_path, context)
        inner["optional"] = True
        return inner
    if t == "ResponseSchema" or t.endswith("::ResponseSchema"):
        return {"kind": "json"}
    if "::" in t:
        segs = [s.strip() for s in t.split("::")]
        if segs[0] == "crate":
            return {"kind": "schema", "title": rust_module_title(segs[1:])}
        if segs[0] == "super":
            base = module_path[:-1]
            i = 1
            while i < len(segs) and segs[i] == "super":
                base = base[:-1]
                i += 1
            return {"kind": "schema", "title": rust_module_title([*base, *segs[i:]])}
        raise ValueError(f"{context}: unsupported type path `{t}`")
    if t in scope["aliases"]:
        return resolve_type(scope["aliases"][t], scope, module_path, context)
    if t in scope["reexports"]:
        return resolve_type(scope["reexports"][t], scope, module_path, context)
    if t in scope["local_defs"]:
        return {"kind": "schema", "title": ".".join([*module_path, t])}
    raise ValueError(f"{context}: cannot resolve type `{t}`")


# ── python module / class mapping (via install_pydantic) ─────────────────────


def py_module(title: str) -> str:
    dir_path, file_name = ip.title_to_path(title)
    file_path = f"{dir_path}/{file_name}" if dir_path else file_name
    return "objectiveai_sdk." + file_path.replace("/", ".")


def py_class(title: str, global_names: dict) -> str:
    return global_names.get(title) or ip.title_to_class_name(title)


# ── generation ───────────────────────────────────────────────────────────────


def clean_generated_execute_files(directory: Path) -> None:
    """Remove previously-generated execute modules (header-gated), so a scope
    that no longer emits one leaves no stale file behind. Both the current
    ``_execute.py`` name and the legacy ``execute.py`` name are swept."""
    if not directory.exists():
        return
    for entry in directory.iterdir():
        if entry.is_dir():
            clean_generated_execute_files(entry)
        elif entry.name in ("_execute.py", "execute.py"):
            try:
                head = entry.read_text(encoding="utf-8")[:64]
            except OSError:
                continue
            if head.startswith("# THIS FILE IS AUTO-GENERATED"):
                entry.unlink()


def main() -> int:
    if not RUST_COMMAND_DIR.exists():
        print(f"install_command_execute: rust command dir missing: {RUST_COMMAND_DIR}",
              file=sys.stderr)
        return 2

    command_out_dir = SRC_DIR / "cli" / "command"
    clean_generated_execute_files(command_out_dir)

    # All generated schema titles + the title -> name mapping (verbatim from
    # install_pydantic, so import paths/classes match the types tree).
    all_titles: set[str] = set()
    for f in SCHEMA_DIR.glob("*.json"):
        content = json.loads(f.read_text(encoding="utf-8"))
        if "title" in content:
            all_titles.add(content["title"])
    ip.compute_colliding_paths(all_titles)
    global_names = ip.compute_global_class_names(all_titles)

    # The cli's JSONL error envelope title — from the schemars rename on
    # `crate::cli::Error`, so a rename tracks automatically.
    error_rs = (RUST_SRC_DIR / "cli" / "error.rs").read_text(encoding="utf-8")
    err_m = re.search(r'#\[schemars\(rename = "([^"]+)"\)\]\s*pub struct Error\b',
                      error_rs, re.S)
    if not err_m:
        print("install_command_execute: could not find schemars rename for crate::cli::Error",
              file=sys.stderr)
        return 2
    error_title = err_m.group(1)
    if error_title not in all_titles:
        print(f"install_command_execute: schema for `{error_title}` missing — "
              "run install_pydantic.py first", file=sys.stderr)
        return 2
    error_module = py_module(error_title)
    error_class = py_class(error_title, global_names)

    # Collect every SCOPE: a module defining both `pub struct Request` and a
    # `pub async fn execute*`. Key = path relative to the command dir.
    scopes: dict[str, str] = {}
    for rs in RUST_COMMAND_DIR.rglob("*.rs"):
        source = rs.read_text(encoding="utf-8")
        if not re.search(r"pub async fn execute\w*\s*<", source):
            continue
        if not re.search(r"pub struct Request\b", source):
            continue
        rel = rs.relative_to(RUST_COMMAND_DIR).as_posix()[:-3]  # drop ".rs"
        key = str(Path(rel).parent.as_posix()) if Path(rel).name == "mod" else rel
        if key == ".":
            continue  # command-root mod.rs is a dispatcher
        scopes[key] = source

    skipped: list[str] = []
    generated: list[str] = []
    # leaf scope dir -> list of (fn_name) surfaced, for _generated.py append.
    surfaced: dict[str, list[str]] = {}

    for key in sorted(scopes):
        scope_source = scopes[key]
        scope_segments = key.split("/")
        module_path = ["cli", "command", *scope_segments]
        scope = {
            "aliases": find_type_aliases(scope_source),
            "local_defs": find_local_defs(scope_source),
            "reexports": find_reexports(scope_source),
        }
        execute_fns = find_execute_fns(scope_source)
        if not execute_fns:
            continue

        path_const = find_path_const(scope_source)
        if path_const is None:
            skipped.append(f"{' '.join(scope_segments)} — no `Path` discriminator on Request yet")
            continue

        request_title = ".".join([*module_path, "Request"])
        if request_title not in all_titles:
            skipped.append(f"{' '.join(scope_segments)} — schema `{request_title}` not generated yet")
            continue
        request_module = py_module(request_title)
        request_class = py_class(request_title, global_names)

        # imports: module -> {local_name -> import_name}
        imports: dict[str, dict[str, str]] = {}

        def add_import(module: str, name: str, alias: Optional[str] = None) -> str:
            local = alias or name
            imports.setdefault(module, {})[local] = name
            return local

        add_import("objectiveai_sdk.cli.command.cli_stream", "CliStream")
        add_import("objectiveai_sdk.cli.command.executor", "CommandExecutor")
        cli_error_local = add_import(error_module, error_class, "CliError")
        request_local = add_import(request_module, request_class, "Request")

        fns_out: list[str] = []
        gen_fn_names: list[str] = []
        for fn in execute_fns:
            context = f"{'/'.join(scope_segments)} {fn['name']}"
            params = parse_params(fn["params"], context)
            parsed = parse_body(fn["body"], context)
            mutations, call = parsed["mutations"], parsed["call"]

            ret_m = re.match(r"^Result<(.+), E::Error>$", fn["return_type"])
            if not ret_m:
                raise ValueError(f"{context}: unrecognized return `{fn['return_type']}`")
            payload_expr = ret_m.group(1).strip()
            stream_m = re.match(r"^E::Stream<(.+)>$", payload_expr)
            streaming = stream_m is not None
            if streaming != (call == "execute"):
                raise ValueError(f"{context}: return shape and executor call disagree")
            if streaming:
                payload_expr = stream_m.group(1).strip()
            payload = resolve_type(payload_expr, scope, module_path, context)

            if payload["kind"] == "json":
                payload_ref = add_import("objectiveai_sdk.json_value", "JsonValue")
            elif payload["kind"] == "string":
                payload_ref = "str"
            else:
                title = payload["title"]
                if title not in all_titles:
                    skipped.append(f"{context} — schema `{title}` not generated yet")
                    continue
                cls = py_class(title, global_names)
                if title == error_title:
                    payload_ref = cli_error_local
                else:
                    alias = ("_" + cls) if cls in _RESERVED else None
                    payload_ref = add_import(py_module(title), cls, alias)
            if payload.get("optional") and payload["kind"] != "json":
                payload_ref = f"Optional[{payload_ref}]"

            union = f"Union[{cli_error_local}, {payload_ref}]"
            adapter_name = f"_{fn['name']}_adapter"
            doc_path = " ".join(scope_segments)

            # Wire value: mutations + injected discriminator.
            wire_lines = [
                'wire = request.model_dump(mode="json", by_alias=True, exclude_none=True)',
            ]
            if mutations["jq"] == "clear":
                wire_lines.append('wire.pop("jq", None)')
            if mutations["jq"] == "set":
                wire_lines.append('wire["jq"] = jq')
            if mutations["transform"] == "clear":
                wire_lines.append('wire.pop("jq", None)')
                wire_lines.append('wire.pop("python", None)')
            if mutations["transform"] == "set":
                wire_lines.append('wire.pop("jq", None)')
                wire_lines.append('wire.pop("python", None)')
                wire_lines.append("wire.update(transform)")
            if mutations["stream"] == "set":
                wire_lines.append('_adv = dict(wire.get("dangerous_advanced") or {}); '
                                  '_adv["stream"] = True; wire["dangerous_advanced"] = _adv')
            if mutations["stream"] == "clear":
                wire_lines.append('if wire.get("dangerous_advanced") is not None:\n'
                                  '        _adv = dict(wire["dangerous_advanced"]); '
                                  '_adv.pop("stream", None); wire["dangerous_advanced"] = _adv')
            wire_lines.append(f'wire["{path_const["field"]}"] = {json.dumps(path_const["value"])}')

            sig_params = ["executor: CommandExecutor"]
            for p in params:
                if p["name"] == "request":
                    sig_params.append(f"request: {request_local}")
                elif p["name"] == "transform":
                    sig_params.append("transform: dict")
                else:
                    sig_params.append("jq: str")
            sig = ", ".join(sig_params)
            body = "\n    ".join(wire_lines)
            gen_fn_names.append(fn["name"])

            if streaming:
                fns_out.append(
                    f"{adapter_name} = TypeAdapter(\n"
                    f'    Annotated[{union}, Field(union_mode="left_to_right")]\n'
                    f")\n\n\n"
                    f"def {fn['name']}({sig}) -> CliStream[{union}]:\n"
                    f'    """`{doc_path} {fn["name"]}` — streaming; mirror of the Rust fn '
                    f'of the same path."""\n'
                    f"    {body}\n"
                    f"    return CliStream(executor.execute(wire), {adapter_name})\n"
                )
            else:
                fns_out.append(
                    f"{adapter_name} = TypeAdapter(\n"
                    f'    Annotated[{union}, Field(union_mode="left_to_right")]\n'
                    f")\n\n\n"
                    f"async def {fn['name']}({sig}) -> {union}:\n"
                    f'    """`{doc_path} {fn["name"]}` — unary; first stream item, rest '
                    f'discarded."""\n'
                    f"    {body}\n"
                    f"    stream = CliStream(executor.execute(wire), {adapter_name})\n"
                    f"    first = await stream.first()\n"
                    f"    if first is None:\n"
                    f'        raise RuntimeError("{doc_path}: cli produced no output before '
                    f'the end marker")\n'
                    f"    return first\n"
                )

        if not fns_out:
            continue

        # Assemble the module.
        import_lines = [
            "from __future__ import annotations",
            "from typing import Annotated, Optional, Union",
            "from pydantic import Field, TypeAdapter",
            "from objectiveai_sdk._rebuild import ensure_rebuilt",
        ]
        for module in sorted(imports):
            names = imports[module]
            specs = ", ".join(
                (f"{imp} as {local}" if local != imp else imp)
                for local, imp in sorted(names.items())
            )
            import_lines.append(f"from {module} import {specs}")

        content = (
            GENERATED_HEADER
            + "\n".join(import_lines)
            + "\n\n# Resolve forward references before building the union adapters below.\n"
            + "ensure_rebuilt()\n\n\n"
            + "\n\n".join(fns_out)
        )
        out_path = command_out_dir.joinpath(*scope_segments) / "_execute.py"
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(content, encoding="utf-8")
        generated.append(out_path.relative_to(SRC_DIR).as_posix())
        surfaced[key] = sorted(set(gen_fn_names))

    # Surface each leaf's fns through its `_generated.py` barrel (mirror the JS
    # `export * from "./execute"` append). install_pydantic regenerates
    # `_generated.py` without these, so this re-adds them after it runs. Any
    # prior `from .execute`/`from ._execute import` line is stripped first, so
    # the append is idempotent regardless of the barrel's current state.
    stale_import = re.compile(r"^from \.(?:_)?execute import ")
    for key, fn_names in surfaced.items():
        gen_path = command_out_dir.joinpath(*key.split("/")) / "_generated.py"
        export_line = f"from ._execute import {', '.join(fn_names)}  # noqa: F401"
        if gen_path.exists():
            lines = [ln for ln in gen_path.read_text(encoding="utf-8").splitlines()
                     if not stale_import.match(ln)]
            lines.append(export_line)
            gen_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        else:
            gen_path.write_text(GENERATED_HEADER + export_line + "\n", encoding="utf-8")

    print(f"install_command_execute: generated {len(generated)} execute module(s)")
    if skipped:
        print(f"install_command_execute: SKIPPED {len(skipped)} scope(s)/fn(s):")
        for s in skipped:
            print(f"  - {s}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
