def title_to_pascal(title: str) -> str:
    """Convert a dot-separated title to PascalCase.

    "agent.Agent" → "AgentAgent"
    "agent.claude_agent_sdk.Agent" → "AgentClaudeAgentSdkAgent"
    """
    return "".join(
        s[0].upper() + s[1:] for s in re.split(r"[._]", title) if s
    )



_PY_KEYWORDS = {
    "False", "None", "True", "and", "as", "assert", "async", "await",
    "break", "class", "continue", "def", "del", "elif", "else", "except",
    "finally", "for", "from", "global", "if", "import", "in", "is",
    "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try",
    "while", "with", "yield",
}

# Top-level stdlib package names. If a schema title's TOP segment matches
# one of these, the generated `objectiveai_sdk/<name>/` package would
# shadow the stdlib package once pytest loads any test under it as a
# namespace package (e.g. `tests/http/__init__.py` ends up making
# `import http` resolve to the test dir, breaking
# `urllib.request → http.client`). Suffix-escape the top segment to
# dodge.
_PY_STDLIB_TOP = {
    "http", "urllib", "email", "json", "typing", "logging", "queue",
    "socket", "ssl", "subprocess", "io", "os", "sys", "re", "html",
    "xml", "csv", "math", "random", "time", "datetime", "test",
    "tests",
}


# Field names that must be aliased to `<name>_` (with the wire name preserved
# via Field(alias=...)). Two groups:
#   - keyword/builtin identifiers that appear in the wire schemas and would be
#     invalid or shadow a builtin as a bare attribute name (`from`, `type`, …);
#   - pydantic `BaseModel` public attributes/methods (the v1-era API still
#     present on v2). A field whose name matches one of these shadows it, which
#     pydantic v2 warns about at class-definition time ("Field name … shadows an
#     attribute in parent BaseModel") — printed to stderr on import (e.g. a
#     `schema` field shadows BaseModel.schema). Aliasing removes the warning
#     while keeping the wire format identical.
_RESERVED_FIELD_NAMES = frozenset(
    {
        "from", "type", "class", "import", "in", "is", "not", "and", "or",
        "schema", "schema_json", "dict", "json", "copy", "construct",
        "validate", "fields", "parse_obj", "parse_raw", "parse_file",
        "from_orm", "update_forward_refs",
    }
)


def _escape_py_keyword(segment: str) -> str:
    """If `segment` is a Python keyword, suffix it with `_` so it works as
    a module-name component (e.g. `del` → `del_`)."""
    return segment + "_" if segment in _PY_KEYWORDS else segment


def _escape_py_top_segment(segment: str) -> str:
    """Same as `_escape_py_keyword`, plus stdlib top-level package names —
    only applied to the FIRST title segment so we don't shadow stdlib."""
    return (segment + "_") if segment in _PY_KEYWORDS or segment in _PY_STDLIB_TOP else segment


def _safe_docstring(desc: str | None) -> str:
    """Escape a description so it can be wrapped in `\"\"\"...\"\"\"` safely.

    Replaces embedded `\"\"\"` with escaped form and escapes trailing `\"`
    runs so the closing triple-quote isn't ambiguous (e.g. without this
    `... \"it worked.\"\"\"\"` → SyntaxError). Python interprets `\\"`
    inside a triple-quoted string as a literal `\"`, so the runtime
    description value is preserved byte-for-byte."""
    if not desc:
        return ""
    safe = desc.replace('"""', '\\"\\"\\"')
    # Walk trailing quote run and escape each.
    i = len(safe)
    while i > 0 and safe[i - 1] == '"':
        i -= 1
    if i < len(safe):
        safe = safe[:i] + ''.join('\\"' for _ in range(len(safe) - i))
    return safe


# Paths (dir/file) that collide with a sibling directory of the same
# name. Computed once from the full title set; the affected titles get
# their content emitted as `<dir>/<file>/_root.py` instead of
# `<dir>/<file>.py`, so the `<file>` package's `_generated.py` re-exports
# the relocated classes.
_COLLIDING_PATHS: set[str] = set()


def _title_segments(title: str) -> list[str]:
    """Tokenize a title into module-path segments with keyword + stdlib
    escapes applied. The first segment additionally avoids stdlib
    shadowing; inner segments only need keyword escapes."""
    raw = title.split(".")
    head = _escape_py_top_segment(raw[0])
    middle = [_escape_py_keyword(p) for p in raw[1:-1]]
    tail = _escape_py_keyword(_to_snake(raw[-1]))
    return [head, *middle, tail]


def compute_colliding_paths(all_titles: set[str]) -> None:
    """Populate `_COLLIDING_PATHS` with file paths that collide with
    package directories from other titles."""
    # Determine the set of directory paths used by any title.
    dir_paths: set[str] = set()
    file_paths: set[str] = set()
    for title in all_titles:
        parts = _title_segments(title)
        # Each prefix of `parts[:-1]` is a directory.
        for i in range(1, len(parts)):
            dir_paths.add("/".join(parts[:i]))
        file_paths.add("/".join(parts))
    _COLLIDING_PATHS.clear()
    _COLLIDING_PATHS.update(file_paths & dir_paths)


def title_to_path(title: str) -> tuple[str, str]:
    """Map a schema title to (directory, filename) relative to SRC_DIR.

    "agent.Agent" → ("agent", "agent")
    "ResponseError" → ("", "response_error")
    "agent.completions.message.File" → ("agent/completions/message", "file")

    If the natural file path collides with a sibling directory (some
    other title has that directory as a prefix), the file is suffixed
    with `_` (e.g. `request.py` → `request_.py`) so Python's package
    resolver doesn't pick up the sub-package directory in place of the
    module."""
    parts = _title_segments(title)
    file_name = parts[-1]
    dir_path = "/".join(parts[:-1])
    natural = f"{dir_path}/{file_name}" if dir_path else file_name
    if natural in _COLLIDING_PATHS:
        file_name = file_name + "_"
    return dir_path, file_name


def _to_snake(name: str) -> str:
    """Convert PascalCase or camelCase to snake_case.

    Dots (from dotted schema titles like
    `client_objectiveai_mcp.client_response.Response.Ok`) are
    treated as word boundaries: collapsed to underscores so the
    result is a valid Python identifier / module-name component.
    """
    s = name.replace(".", "_")
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return s.lower()


def _is_snake(name: str) -> bool:
    return name == _to_snake(name)


def title_to_class_name(title: str) -> str:
    """Extract the class name from a title (last segment).

    "agent.completions.response.streaming.AgentCompletionChunk" → "AgentCompletionChunk"
    "ResponseError" → "ResponseError"
    """
    return title.split(".")[-1]


def compute_global_class_names(all_titles: set[str]) -> dict[str, str]:
    """Compute the definitive class name for each title.

    When multiple titles in the same file would produce the same short class
    name, they all get long pascal names to avoid within-file collisions.
    """
    # Group titles by output file
    file_groups: dict[str, list[str]] = {}
    for title in all_titles:
        dir_path, file_name = title_to_path(title)
        file_path = f"{dir_path}/{file_name}" if dir_path else file_name
        file_groups.setdefault(file_path, []).append(title)

    result: dict[str, str] = {}
    for titles in file_groups.values():
        short_to_titles: dict[str, list[str]] = {}
        for t in titles:
            short = title_to_class_name(t)
            short_to_titles.setdefault(short, []).append(t)
        for short, group in short_to_titles.items():
            if len(group) == 1:
                result[group[0]] = short
            else:
                # Collision: use full pascal name for disambiguation
                for t in group:
                    result[t] = title_to_pascal(t)

    return result


# Module-level name map for the file currently being generated.
# Maps title → class name to use in this file's type annotations.
_current_name_map: dict[str, str] = {}


# Accumulates helper class code and refs generated during type conversion.
# Reset per-file before generate_model is called.
_generated_helpers: list[str] = []
_generated_helper_refs: set[str] = set()

# All schemas dict, set per-file for access during type conversion.
_all_schemas: dict[str, dict] = {}

# Current naming context stack for inline type generation.
# Pushed/popped as we descend into properties, items, etc.
# E.g., ["Swarm", "Agents", "Item"] → "SwarmAgentsItem"
_naming_context: list[str] = []



def _generate_inline_type(schema: dict, self_title: str, all_titles: set[str]) -> str:
    """Generate a helper class for an inline schema that needs its own type.

    Used for $ref + properties (inline inheritance).
    Names the class based on the current naming context.
    """
    class_name = "".join(_naming_context)
    refs: set[str] = set()

    ref_target = schema["$ref"]
    if ref_target == "#":
        ref_target = self_title
    desc = schema.get("description", "")
    safe_desc = _safe_docstring(desc)
    code = _generate_flattened_ref_model(
        self_title, schema, refs, all_titles,
        class_name, safe_desc, ref_target, all_schemas=_all_schemas,
    )

    _generated_helpers.append(code)
    _generated_helper_refs.update(refs)
    return class_name


def _generate_inline_anyof(any_of: list[dict], self_title: str, all_titles: set[str],
                           *, description: str | None = None) -> str:
    """Generate an inline RootModel for an anyOf that has described variants.

    Creates variant wrapper classes with docstrings to preserve descriptions.
    """
    class_name = "".join(_naming_context)
    safe_desc = _safe_docstring(description)
    refs: set[str] = set()
    variant_codes: list[str] = []
    union_members: list[str] = []

    for i, v in enumerate(any_of, 1):
        if v.get("type") == "null":
            union_members.append("None")
            continue

        var_code, var_name, var_refs = _generate_variant_class(
            v, class_name, i, self_title, all_titles,
            all_schemas=_all_schemas,
        )
        variant_codes.append(var_code)
        union_members.append(var_name)
        refs.update(var_refs)

    root_type = _union_type(union_members)
    main_code = _make_root_model(class_name, safe_desc, root_type)
    code = "\n\n".join(variant_codes + [main_code])

    _generated_helpers.append(code)
    _generated_helper_refs.update(refs)
    return class_name


def resolve_ref_name(title: str) -> str:
    """Resolve a $ref title to the class name used in the current file."""
    if title in _current_name_map:
        return _current_name_map[title]
    return title_to_class_name(title)


