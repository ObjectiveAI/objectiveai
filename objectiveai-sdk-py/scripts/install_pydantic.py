def main() -> None:
    clean_generated(SRC_DIR)
    clean_generated(TESTS_DIR)

    # Read all schema files
    schema_files = sorted(SCHEMA_DIR.glob("*.json"))
    schemas: dict[str, dict] = {}
    for f in schema_files:
        content = json.loads(f.read_text(encoding="utf-8"))
        if "title" in content:
            schemas[content["title"]] = content

    print(f"Read {len(schemas)} schemas")

    all_titles = set(schemas.keys())

    # Detect file/dir collisions before any title_to_path call so that
    # collision-relocated titles use the same path everywhere.
    compute_colliding_paths(all_titles)

    # Auto-detect generic prefixes from schema titles


    # Group schemas by output file path
    file_groups: dict[str, list[dict]] = {}
    for title, schema in schemas.items():
        dir_path, file_name = title_to_path(title)
        file_path = f"{dir_path}/{file_name}" if dir_path else file_name
        file_groups.setdefault(file_path, []).append(
            {"title": title, "schema": schema}
        )

    print(f"Generating {len(file_groups)} .py files")

    # Build file dependency graph and collect raw refs per file
    file_refs: dict[str, set[str]] = {}
    file_raw_refs: dict[str, set[str]] = {}
    for file_path, entries in file_groups.items():
        refs: set[str] = set()
        for entry in entries:
            collect_refs(entry["schema"], refs)
        file_raw_refs[file_path] = refs
        dep_files: set[str] = set()
        for ref in refs:
            ref_dir, ref_file = title_to_path(ref)
            ref_path = f"{ref_dir}/{ref_file}" if ref_dir else ref_file
            if ref_path != file_path:
                dep_files.add(ref_path)
        file_refs[file_path] = dep_files

    # Detect cycles
    files_in_cycles = find_files_in_cycles(file_groups, file_refs)
    if files_in_cycles:
        print(f"Found {len(files_in_cycles)} file(s) in dependency cycles")

    # --- Compute global title → class name mapping ---
    # This handles within-file collisions: when multiple types in the same
    # file share the same short class name, they all get long pascal names
    # (with the generic prefix stripped to avoid redundancy).
    global_class_names = compute_global_class_names(all_titles)

    # Track all directories and their exports for __init__.py generation
    all_dirs: set[str] = set()
    # dir_path → list of (module_name, [class_names])
    dir_exports: dict[str, list[tuple[str, list[str]]]] = {}

    # Generate each .py file
    for file_path, entries in file_groups.items():
        file_in_cycle = file_path in files_in_cycles

        # --- Compute per-file name map ---
        # Self-defined class names use the global mapping
        self_titles = {entry["title"] for entry in entries}
        self_class_names: dict[str, str] = {
            t: global_class_names[t] for t in self_titles
        }

        # External refs — detect collisions with self-defined names and each other
        external_refs = file_raw_refs.get(file_path, set()) - self_titles
        # Group external refs by their desired local name
        # Use global_class_names to get each ref's ACTUAL class name in its source file
        short_to_refs: dict[str, list[str]] = {}
        for ref in external_refs:
            # The name we'd ideally use for this ref in this file
            short = global_class_names.get(ref, title_to_class_name(ref))
            short_to_refs.setdefault(short, []).append(ref)

        name_map: dict[str, str] = dict(self_class_names)
        self_name_set = set(self_class_names.values())

        for short, ref_titles in short_to_refs.items():
            if short in self_name_set:
                # Collision with self-defined type — all external refs need alias
                for t in ref_titles:
                    name_map[t] = title_to_pascal(t)
            elif len(ref_titles) == 1:
                name_map[ref_titles[0]] = short
            else:
                # Multiple external refs share short name — alias all
                for t in ref_titles:
                    name_map[t] = title_to_pascal(t)

        # Set module-level name map for convert_to_type
        global _current_name_map
        _current_name_map = name_map

        # --- Generate model code ---
        global _generated_helpers, _generated_helper_refs, _all_schemas
        _generated_helpers = []
        _generated_helper_refs = set()
        _all_schemas = schemas
        all_refs: set[str] = set()
        model_codes: list[str] = []

        for entry in entries:
            _naming_context.clear()
            code, refs = generate_model(
                entry["title"],
                entry["schema"],
                all_titles,
                all_schemas=schemas,
            )
            model_codes.append(code)
            all_refs |= refs

        # Prepend inline helper classes (generated during type conversion)
        if _generated_helpers:
            model_codes = _generated_helpers + model_codes
            all_refs |= _generated_helper_refs

        # --- Detect base class refs (inheritance, can't be deferred) ---
        # Scan generated code for `class Foo(Bar):` where Bar is not
        # BaseModel/RootModel — those refs must be eagerly imported.
        base_class_names: set[str] = set()
        for line in "\n".join(model_codes).split("\n"):
            if line.startswith("class ") and "(" in line:
                base = line.split("(")[1].split(")")[0].strip()
                if base not in ("BaseModel", "RootModel"):
                    base_class_names.add(base)

        # --- Build imports ---
        import_lines: list[str] = []

        full_code = "\n".join(model_codes)
        typing_imports: list[str] = []
        if "Annotated[" in full_code:
            typing_imports.append("Annotated")
        if "Literal[" in full_code:
            typing_imports.append("Literal")
        if "Optional[" in full_code:
            typing_imports.append("Optional")
        if "Union[" in full_code:
            typing_imports.append("Union")

        # Always add future annotations for forward reference support
        import_lines.append("from __future__ import annotations")

        # Standard library imports
        if ": datetime" in full_code or "[datetime" in full_code:
            import_lines.append("from datetime import datetime")
        if ": UUID" in full_code or "[UUID" in full_code:
            import_lines.append("from uuid import UUID")

        if typing_imports:
            import_lines.append(f"from typing import {', '.join(sorted(typing_imports))}")

        # JsonValue import (for bare {} schemas / serde_json::Value)
        if "JsonValue" in full_code:
            import_lines.append("from objectiveai_sdk.json_value import JsonValue")

        # Determine pydantic imports
        pydantic_imports: list[str] = []
        if "BaseModel" in full_code:
            pydantic_imports.append("BaseModel")
        if "ConfigDict" in full_code:
            pydantic_imports.append("ConfigDict")
        if "Field(" in full_code:
            pydantic_imports.append("Field")
        if "RootModel" in full_code:
            pydantic_imports.append("RootModel")

        if pydantic_imports:
            import_lines.append(
                f"from pydantic import {', '.join(sorted(pydantic_imports))}"
            )

        # Group refs by their target file
        refs_by_file: dict[str, list[str]] = {}
        for ref in all_refs:
            ref_dir, ref_file = title_to_path(ref)
            ref_path = f"{ref_dir}/{ref_file}" if ref_dir else ref_file
            if ref_path == file_path:
                continue
            refs_by_file.setdefault(ref_path, []).append(ref)

        # Split imports: regular (top of file) vs deferred (bottom of file).
        # Cyclic imports are placed AFTER class definitions. With
        # `from __future__ import annotations`, annotations are strings and
        # don't need the referenced types at class-definition time. By placing
        # the cyclic imports at the bottom, we avoid circular import deadlocks
        # while still making the names available for Pydantic model_rebuild.
        regular_imports: list[str] = []
        deferred_imports: list[str] = []

        for ref_path in sorted(refs_by_file.keys()):
            ref_titles = refs_by_file[ref_path]
            module_path = "objectiveai_sdk." + ref_path.replace("/", ".")
            is_cyclic = file_in_cycle and ref_path in files_in_cycles

            # Build import items: "ClassName" or "ClassName as AliasName"
            import_items: list[str] = []
            seen_names: set[str] = set()
            for t in sorted(ref_titles):
                # class_name = actual name in the source file
                class_name = global_class_names.get(t, title_to_class_name(t))
                local_name = name_map.get(t, class_name)
                if class_name in seen_names:
                    continue
                seen_names.add(class_name)
                if local_name != class_name:
                    import_items.append(f"{class_name} as {local_name}")
                else:
                    import_items.append(class_name)

            # Split items: base class refs must be eager even in cycles
            eager_items = []
            deferred_items = []
            for item in sorted(import_items):
                # Extract the local name (after "as" if aliased)
                local = item.split(" as ")[-1].strip()
                if is_cyclic and local not in base_class_names:
                    deferred_items.append(item)
                else:
                    eager_items.append(item)

            if eager_items:
                regular_imports.append(
                    f"from {module_path} import {', '.join(eager_items)}"
                )
            if deferred_items:
                deferred_imports.append(
                    f"from {module_path} import {', '.join(deferred_items)}  # noqa: E402"
                )

        import_lines.extend(regular_imports)

        # Assemble the file
        content = GENERATED_HEADER
        if import_lines:
            content += "\n".join(import_lines) + "\n"

        content += "\n\n" + "\n\n".join(model_codes) + "\n"

        # Deferred cyclic imports at the bottom (after all class definitions)
        if deferred_imports:
            content += "\n# Deferred imports to break circular dependencies\n"
            content += "\n".join(deferred_imports) + "\n"

            pass

        # Write the file
        full_path = SRC_DIR / (file_path.replace("/", os.sep) + ".py")
        full_path.parent.mkdir(parents=True, exist_ok=True)
        full_path.write_text(content, encoding="utf-8")

        # Track directories and exports
        parts = file_path.split("/")
        for i in range(1, len(parts)):
            all_dirs.add("/".join(parts[:i]))

        # Record exports for __init__.py re-exports (including variant classes)
        dir_part = "/".join(parts[:-1]) if len(parts) > 1 else ""
        module_name = parts[-1]  # file name without .py
        # Collect all class names from generated code (main + variant classes)
        class_names: list[str] = []
        for line in "\n".join(model_codes).split("\n"):
            if line.startswith("class "):
                cls_name = line.split("(")[0].replace("class ", "").strip()
                class_names.append(cls_name)
        dir_exports.setdefault(dir_part, []).append((module_name, class_names))

    # Generate _generated.py + stub __init__.py for each package
    all_dirs.add("")  # root package
    generated_count = 0
    init_count = 0

    for dir_path in sorted(all_dirs, key=len, reverse=True):
        abs_dir = SRC_DIR / dir_path.replace("/", os.sep) if dir_path else SRC_DIR
        if not abs_dir.exists():
            continue

        # Always write _generated.py (auto-generated barrel exports)
        generated_path = abs_dir / "_generated.py"
        generated_content = GENERATED_HEADER
        exports = dir_exports.get(dir_path, [])
        if exports:
            for module_name, class_names in sorted(exports):
                names_str = ", ".join(sorted(set(class_names)))
                generated_content += (
                    f"from .{module_name} import {names_str}"
                    "  # noqa: F401\n"
                )


        generated_path.write_text(generated_content, encoding="utf-8")
        generated_count += 1

        # Only create __init__.py if it doesn't exist yet (user may have
        # a hand-written one without the auto-generated marker).
        # Uses lazy __getattr__ to avoid circular imports caused by
        # eager barrel exports.  Individual modules import from sibling
        # files directly; the package init is only triggered when user
        # code does `from objectiveai_sdk.pkg import SomeClass`.
        init_path = abs_dir / "__init__.py"
        if not init_path.exists():
            init_content = (
                GENERATED_HEADER
                + "\n"
                + "def __getattr__(name):\n"
                + "    from objectiveai_sdk._rebuild import ensure_rebuilt\n"
                + "    ensure_rebuilt()\n"
                + "    import importlib\n"
                + "    _generated = importlib.import_module(__name__ + '._generated')\n"
                + "    return getattr(_generated, name)\n"
            )
            init_path.write_text(init_content, encoding="utf-8")
            init_count += 1

    print(f"Generated _generated.py for {generated_count} directories")
    if init_count:
        print(f"Created {init_count} new __init__.py stubs")

    # -----------------------------------------------------------------------
    # Auto-generate test files
    # -----------------------------------------------------------------------
    # One test per class, importing from the package (not the submodule).
    # This validates the __init__.py export chain.
    test_count = 0
    for dir_path, modules in sorted(dir_exports.items()):
        # dir_path e.g. "agent/completions/response/streaming"
        # module import path e.g. "objectiveai_sdk.agent.completions.response.streaming"
        if dir_path:
            import_path = "objectiveai_sdk." + dir_path.replace("/", ".")
        else:
            import_path = "objectiveai_sdk"

        for _module_name, class_names in sorted(modules):
            for class_name in sorted(set(class_names)):
                test_file_name = "test_" + _to_snake(class_name) + ".py"
                test_dir = TESTS_DIR / dir_path.replace("/", os.sep) if dir_path else TESTS_DIR
                test_dir.mkdir(parents=True, exist_ok=True)
                test_path = test_dir / test_file_name

                test_content = (
                    GENERATED_HEADER
                    + "\n\n"
                    + f"def test_{_to_snake(class_name)}():\n"
                    + f"    from {import_path} import {class_name}\n"
                    + f"    schema = {class_name}.model_json_schema()\n"
                )
                test_path.write_text(test_content, encoding="utf-8")
                test_count += 1

                # Ensure __init__.py exists in every test directory (and
                # all parent dirs up to TESTS_DIR) so pytest can
                # distinguish same-named files across packages.
                for parent in [test_dir, *test_dir.parents]:
                    if parent == TESTS_DIR or parent == TESTS_DIR.parent:
                        break
                    p_init = parent / "__init__.py"
                    if not p_init.exists():
                        p_init.write_text(GENERATED_HEADER, encoding="utf-8")

    print(f"Generated {test_count} test files")

    # -----------------------------------------------------------------------
    # Generate _module_list.py — list of all generated module paths.
    # Used by _rebuild.py to load all modules and resolve forward references.
    # -----------------------------------------------------------------------
    module_list_lines = [GENERATED_HEADER, "MODULES = ["]
    for file_path in sorted(file_groups.keys()):
        module_path = "objectiveai_sdk." + file_path.replace("/", ".")
        module_list_lines.append(f"    {module_path!r},")
    module_list_lines.append("]")

    module_list_path = SRC_DIR / "_module_list.py"
    module_list_path.write_text("\n".join(module_list_lines) + "\n", encoding="utf-8")
    print(f"Generated _module_list.py with {len(file_groups)} modules")

    print("Done!")


if __name__ == "__main__":
    main()
