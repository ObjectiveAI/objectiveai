def collect_refs(schema: dict | list | None, refs: set[str]) -> None:
    """Recursively collect all $ref titles from a schema."""
    if schema is None or not isinstance(schema, (dict, list)):
        return
    if isinstance(schema, list):
        for item in schema:
            collect_refs(item, refs)
        return
    if "$ref" in schema:
        if schema["$ref"] != "#":
            refs.add(schema["$ref"])
        for key, value in schema.items():
            if key != "$ref":
                collect_refs(value, refs)
        return
    for value in schema.values():
        collect_refs(value, refs)


def has_self_ref(schema: dict | list | None) -> bool:
    """Check if a schema contains a self-reference ($ref: '#')."""
    if schema is None or not isinstance(schema, (dict, list)):
        return False
    if isinstance(schema, list):
        return any(has_self_ref(s) for s in schema)
    if schema.get("$ref") == "#":
        return True
    return any(has_self_ref(v) for v in schema.values())


def _is_nullable(prop_schema: dict) -> bool:
    """Check if a property schema is nullable (has a null variant in anyOf, possibly nested).

    In the ObjectiveAI JSON Schema convention, nullable = optional:
    if a field's type includes null, the key can be omitted from the object.

    Recurses into nested anyOf to find null at any depth, matching the
    JS SDK's isNullableSchema() behavior.
    """
    any_of = prop_schema.get("anyOf", [])
    return any(
        isinstance(v, dict) and (v.get("type") == "null" or _is_nullable(v))
        for v in any_of
    )


def _is_directly_nullable(prop_schema: dict) -> bool:
    """Check if a property schema has null directly in its top-level anyOf."""
    any_of = prop_schema.get("anyOf", [])
    return any(
        isinstance(v, dict) and v.get("type") == "null"
        for v in any_of
    )


def _is_type_alias_schema(schema: dict) -> bool:
    """Check if a schema would generate a type alias (not a BaseModel class).

    Note: With the new approach, all non-BaseModel types become RootModel,
    but this is still used for cycle detection purposes.
    """
    if "properties" in schema:
        return False
    if schema.get("type") == "object":
        return False
    return True


def generate_model(
    title: str,
    schema: dict,
    all_titles: set[str],
    all_schemas: dict[str, dict] | None = None,
) -> tuple[str, set[str]]:
    """Generate a Pydantic model for a schema.

    All non-BaseModel types become RootModel subclasses (never plain type aliases).
    This ensures every type has model_config for storing metadata needed for
    lossless JSON Schema roundtrip.

    Returns (code_string, set_of_ref_titles).
    """
    refs: set[str] = set()
    pascal_name = resolve_ref_name(title)

    has_properties = "properties" in schema
    has_any_of = "anyOf" in schema
    type_ = schema.get("type")

    description = schema.get("description", "")
    safe_desc = _safe_docstring(description)

    # Case 1a: Object with properties AND anyOf (serde flatten)
    if has_properties and has_any_of:
        code = _generate_flattened_model(title, schema, refs, all_titles, pascal_name, safe_desc, all_schemas=all_schemas, schema_title=title)
        return code, refs

    # Case 1b: Object with $ref (with or without properties)
    if "$ref" in schema and (has_properties or type_ == "object"):
        ref_target = schema["$ref"]
        if ref_target == "#":
            ref_target = title
        code = _generate_flattened_ref_model(title, schema, refs, all_titles, pascal_name, safe_desc, ref_target, all_schemas=all_schemas, schema_title=title)
        return code, refs

    # Case 2: Simple object with properties → Pydantic BaseModel
    if has_properties or type_ == "object":
        code = _generate_object_model(title, schema, refs, all_titles, pascal_name, safe_desc, schema_title=title)
        return code, refs

    # Case 3: anyOf without properties → variant types or simple nullable
    if has_any_of:
        variants_schema = schema.get("anyOf", [])

        if _needs_variant_types(variants_schema):
            # Generate dedicated variant types for each non-null variant
            variant_codes: list[str] = []
            union_members: list[str] = []
            for i, v in enumerate(variants_schema, 1):
                if _is_simple_null_variant(v):
                    union_members.append("None")
                    continue
                var_code, var_name, var_refs = _generate_variant_class(
                    v, pascal_name, i, title, all_titles, all_schemas=all_schemas,
                )
                variant_codes.append(var_code)
                union_members.append(var_name)
                refs.update(var_refs)

            root_type = _union_type(union_members)
            main_code = _make_root_model(pascal_name, safe_desc, root_type, schema_title=title)
            code = "\n\n".join(variant_codes + [main_code])
            return code, refs
        else:
            # Simple nullable (2 variants, one null) — Optional[X]
            non_null = [v for v in variants_schema if not _is_simple_null_variant(v)]
            collect_refs(non_null[0], refs)
            inner_type = _convert_inner_type(non_null[0], title, all_titles)
            root_type = f"Optional[{inner_type}]"
            code = _make_root_model(pascal_name, safe_desc, root_type, schema_title=title)
            return code, refs

    # Case 4: enum → RootModel with Literal
    if "enum" in schema:
        literals = ", ".join(repr(v) for v in schema["enum"])
        root_type = f"Literal[{literals}]"
        code = _make_root_model(pascal_name, safe_desc, root_type, schema_title=title)
        return code, refs

    # Case 5: Primitive type → RootModel
    type_str = convert_to_type(schema, title, all_titles)
    collect_refs(schema, refs)
    code = _make_root_model(pascal_name, safe_desc, type_str, schema_title=title)
    return code, refs


def _is_simple_null_variant(v: dict) -> bool:
    """Check if a variant is just {"type": "null"} with no other content."""
    return v == {"type": "null"}


def _needs_variant_types(any_of: list[dict]) -> bool:
    """Check if an anyOf needs variant type generation.

    Returns True for >2 variants, or 2 variants where neither is null.
    Returns False for exactly 2 variants where one is null (simple nullable).
    """
    if len(any_of) > 2:
        return True
    if len(any_of) == 2:
        return not any(_is_simple_null_variant(v) for v in any_of)
    return False


def _generate_variant_class(
    variant_schema: dict,
    parent_name: str,
    variant_index: int,
    self_title: str,
    all_titles: set[str],
    all_schemas: dict[str, dict] | None = None,
) -> tuple[str, str, set[str]]:
    """Generate a Pydantic class for a single anyOf variant.

    Returns (code, class_name, refs).
    """
    variant_title = variant_schema["title"]
    # Variant titles can carry dotted schema paths (e.g.
    # `client_objectiveai_mcp.client_response.Response.Ok`).
    # Strip dots when interpolating into a Python identifier so
    # `class_name` is a valid Python class name.
    class_name = f"{parent_name}{variant_title.replace('.', '')}"
    refs: set[str] = set()
    desc = variant_schema.get("description", "")
    safe_desc = _safe_docstring(desc)

    has_properties = "properties" in variant_schema
    has_any_of = "anyOf" in variant_schema
    has_ref = "$ref" in variant_schema

    # $ref + properties → inheritance or union expansion
    if has_ref and has_properties:
        ref_target = variant_schema["$ref"]
        if ref_target == "#":
            ref_target = self_title
        code = _generate_flattened_ref_model(
            self_title, variant_schema, refs, all_titles,
            class_name, safe_desc, ref_target, all_schemas=all_schemas,
            variant_title=variant_title,
        )
        return code, class_name, refs

    # Object with properties → BaseModel
    if has_properties:
        code = _generate_object_model(
            self_title, variant_schema, refs, all_titles,
            class_name, safe_desc, variant_title=variant_title,
        )
        return code, class_name, refs

    # Nested anyOf → recursively generate sub-variant types or nullable
    if has_any_of:
        inner_variants = variant_schema["anyOf"]
        if _needs_variant_types(inner_variants):
            sub_codes: list[str] = []
            union_members: list[str] = []
            for j, sv in enumerate(inner_variants, 1):
                if _is_simple_null_variant(sv):
                    union_members.append("None")
                    continue
                sub_code, sub_name, sub_refs = _generate_variant_class(
                    sv, class_name, j, self_title, all_titles, all_schemas=all_schemas,
                )
                sub_codes.append(sub_code)
                union_members.append(sub_name)
                refs.update(sub_refs)

            root_type = _union_type(union_members)
            main_code = _make_root_model(class_name, safe_desc, root_type, variant_title=variant_title)
            code = "\n\n".join(sub_codes + [main_code])
            return code, class_name, refs
        else:
            # Simple nullable inner anyOf → Optional[X]
            non_null = [v for v in inner_variants if not _is_simple_null_variant(v)]
            collect_refs(non_null[0], refs)
            inner_type = _convert_inner_type(non_null[0], self_title, all_titles)
            root_type = f"Optional[{inner_type}]"
            code = _make_root_model(class_name, safe_desc, root_type, variant_title=variant_title)
            return code, class_name, refs

    # Empty `{"type": "object"}` schema → empty BaseModel (matches Rust
    # `Variant {}` empty struct, which schemars emits as `{"type":
    # "object"}` with no `additionalProperties`). RootModel[dict[str,
    # JsonValue]] would round-trip with `additionalProperties: true`,
    # which differs from the source schema.
    if (
        variant_schema.get("type") == "object"
        and not has_properties
        and not has_any_of
        and not has_ref
        and "additionalProperties" not in variant_schema
        and "enum" not in variant_schema
    ):
        lines = [f"class {class_name}(BaseModel):"]
        if safe_desc:
            lines.append(f'    """{safe_desc}"""')
        config_parts = []
        extra: dict = {}
        if variant_title:
            extra["_variant_title"] = variant_title
        if extra:
            config_parts.append(f"json_schema_extra={extra!r}")
        if config_parts:
            lines.append(f"    model_config = ConfigDict({', '.join(config_parts)})")
        else:
            lines.append("    pass")
        return "\n".join(lines) + "\n", class_name, refs

    # Pure $ref
    if has_ref:
        ref_type = _convert_inner_type(variant_schema, self_title, all_titles)
        collect_refs(variant_schema, refs)
        # Preserve schemars's `type: "object"` stamp alongside the $ref.
        outer_object = variant_schema.get("type") == "object"
        code = _make_root_model(
            class_name, safe_desc, ref_type,
            variant_title=variant_title,
            variant_outer_object=outer_object,
        )
        return code, class_name, refs

    # enum (Literal)
    if "enum" in variant_schema:
        literals = ", ".join(repr(v) for v in variant_schema["enum"])
        root_type = f"Literal[{literals}]"
        code = _make_root_model(class_name, safe_desc, root_type, variant_title=variant_title)
        return code, class_name, refs

    # Simple type (string, integer, number, boolean, array, etc.)
    type_str = _convert_inner_type(variant_schema, self_title, all_titles)
    collect_refs(variant_schema, refs)
    code = _make_root_model(class_name, safe_desc, type_str, variant_title=variant_title)
    return code, class_name, refs


def _make_root_model(
    pascal_name: str,
    safe_desc: str,
    root_type: str,
    *,
    schema_title: str | None = None,
    expanded_ref: str | None = None,
    expanded_ref_props: list[str] | None = None,
    variant_title: str | None = None,
    variant_outer_object: bool = False,
) -> str:
    """Generate a plain RootModel."""
    lines = [f"class {pascal_name}(RootModel):"]
    if safe_desc:
        lines.append(f'    """{safe_desc}"""')
    config_parts: list[str] = []
    if schema_title:
        config_parts.append(f"title={schema_title!r}")
    extra: dict = {}
    if expanded_ref:
        extra["_expanded_ref"] = expanded_ref
        if expanded_ref_props:
            extra["_expanded_ref_props"] = expanded_ref_props
    if variant_title:
        extra["_variant_title"] = variant_title
    if variant_outer_object:
        # Source schema had `type: "object"` next to the variant's `$ref`
        # (schemars stamps this when the outer schema is committed to being
        # an object — a struct that flattens an untagged enum, or an
        # internally-tagged enum). Roundtrip harness reads this marker to
        # emit `type: "object"` alongside the `$ref` it produces.
        extra["_outer_object"] = True
    if extra:
        config_parts.append(f"json_schema_extra={extra!r}")
    if config_parts:
        lines.append(f"    model_config = ConfigDict({', '.join(config_parts)})")
        lines.append("")
    lines.append(f"    root: {root_type}")
    return "\n".join(lines) + "\n"


def _extract_field_metadata(prop_schema: dict) -> dict:
    """Extract Field() keyword arguments from a property schema.

    Returns a dict of keyword arguments to pass to Field().
    Handles description and direct constraints (minimum/maximum/pattern/format).

    For nullable properties (anyOf with null variant), constraints are
    embedded in the inner type via Annotated[] by convert_to_type, so
    we DON'T extract them here — only the description.

    For non-nullable properties, constraints are at the top level and
    go into Field(ge=..., le=...) since Pydantic merges them into metadata.
    """
    kwargs: dict = {}

    desc = prop_schema.get("description")
    if desc:
        kwargs["description"] = desc

    # omitempty is a property-level attribute, not a type constraint
    if prop_schema.get("omitempty") is True:
        kwargs.setdefault("json_schema_extra", {})["omitempty"] = True

    # For nullable properties, constraints are inside the non-null variant.
    # Those are handled by Annotated[] in the type, not by Field().
    if _is_nullable(prop_schema):
        return kwargs

    # Direct constraints (on non-nullable typed properties)
    if "minimum" in prop_schema:
        kwargs["ge"] = prop_schema["minimum"]
    if "maximum" in prop_schema:
        kwargs["le"] = prop_schema["maximum"]

    # Pattern (string properties only)
    if "pattern" in prop_schema and prop_schema.get("type") == "string":
        kwargs["pattern"] = prop_schema["pattern"]

    # additionalProperties: true (explicit, distinct from absent)
    if prop_schema.get("additionalProperties") is True:
        kwargs.setdefault("json_schema_extra", {})["additionalProperties"] = True

    return kwargs


def _generate_field_line(
    prop_name: str,
    prop_schema: dict,
    prop_type: str,
    is_required: bool,
    *,
    inherited_nullable: bool = False,
) -> str:
    """Generate a single field line for a BaseModel class."""
    field_name = _to_snake(prop_name) if not _is_snake(prop_name) else prop_name
    # Strip leading characters that are invalid in Python identifiers
    if field_name and not field_name[0].isalpha() and field_name[0] != "_":
        field_name = field_name.lstrip("$")
    # Pydantic forbids leading-underscore field names — those are reserved for
    # private attributes. Strip the underscore and re-route serialization via
    # an alias so the wire format keeps the original name (e.g. `_meta`).
    needs_underscore_alias = field_name.startswith("_")
    if needs_underscore_alias:
        field_name = field_name.lstrip("_") or "field"
    if field_name in _RESERVED_FIELD_NAMES:
        alias = prop_name
        field_name = field_name + "_"
    elif needs_underscore_alias:
        alias = prop_name
    else:
        alias = prop_name if prop_name != field_name else None

    meta = _extract_field_metadata(prop_schema)

    # Mark fields whose nullability was uplifted from a nested anyOf.
    # The roundtrip converter uses this to avoid adding an outer null wrapper.
    if inherited_nullable:
        meta.setdefault("json_schema_extra", {})["_nullable"] = False

    # A property with an explicit default is never "required" in our generation,
    # even if it's not nullable.
    has_default = "default" in prop_schema
    if is_required and not has_default:
        if alias or meta:
            args = _build_field_call("...", alias, meta)
            return f"{field_name}: {prop_type} = {args}"
        return f"{field_name}: {prop_type}"
    else:
        if "default" in prop_schema:
            default = prop_schema["default"]
            if default is None:
                # default: null → need Optional wrapper + None default,
                # except when the type already accepts null (e.g. JsonValue).
                if not prop_type.startswith("Optional[") and prop_type != "JsonValue":
                    prop_type = f"Optional[{prop_type}]"
                default_repr = "None"
            else:
                default_repr = repr(default)
            if alias or meta:
                args = _build_field_call(default_repr, alias, meta)
                return f"{field_name}: {prop_type} = {args}"
            return f"{field_name}: {prop_type} = {default_repr}"
        else:
            if not prop_type.startswith("Optional["):
                prop_type = f"Optional[{prop_type}]"
            if alias or meta:
                args = _build_field_call("None", alias, meta)
                return f"{field_name}: {prop_type} = {args}"
            return f"{field_name}: {prop_type} = None"


def _build_field_call(default_expr: str, alias: str | None, meta: dict) -> str:
    """Build a Field(...) call string from default, alias, and metadata."""
    parts = [default_expr]
    if alias:
        parts.append(f"alias={alias!r}")
    if "description" in meta:
        parts.append(f"description={meta['description']!r}")
    if "ge" in meta:
        parts.append(f"ge={meta['ge']!r}")
    if "le" in meta:
        parts.append(f"le={meta['le']!r}")
    if "pattern" in meta:
        parts.append(f"pattern={meta['pattern']!r}")
    if "json_schema_extra" in meta:
        parts.append(f"json_schema_extra={meta['json_schema_extra']!r}")
    return f"Field({', '.join(parts)})"


def _generate_object_model(
    title: str,
    schema: dict,
    refs: set[str],
    all_titles: set[str],
    pascal_name: str,
    safe_desc: str,
    *,
    schema_title: str | None = None,
    variant_title: str | None = None,
) -> str:
    """Generate a Pydantic BaseModel for an object schema."""
    properties = schema.get("properties", {})

    lines = [f"class {pascal_name}(BaseModel):"]
    if safe_desc:
        lines.append(f'    """{safe_desc}"""')

    config_parts: list[str] = []
    if schema_title:
        config_parts.append(f"title={schema_title!r}")
    if variant_title:
        config_parts.append(f"json_schema_extra={{'_variant_title': {variant_title!r}}}")
    if schema.get("additionalProperties") is False:
        config_parts.append("extra='forbid'")
    elif schema.get("additionalProperties") is True:
        config_parts.append("extra='allow'")

    if not properties:
        if config_parts:
            lines.append(f"    model_config = ConfigDict({', '.join(config_parts)})")
        else:
            lines.append("    pass")
        return "\n".join(lines) + "\n"

    if config_parts:
        lines.append(f"    model_config = ConfigDict({', '.join(config_parts)})")
        lines.append("")

    for prop_name, prop_schema in properties.items():
        collect_refs(prop_schema, refs)
        # Push naming context for inline type generation
        _naming_context.append(pascal_name)
        _naming_context.append(prop_name[0].upper() + prop_name[1:] if prop_name else "")
        prop_type = convert_to_type(prop_schema, title, all_titles)
        _naming_context.pop()
        _naming_context.pop()
        nullable = _is_nullable(prop_schema)
        is_required = not nullable
        inherited = nullable and not _is_directly_nullable(prop_schema)
        line = _generate_field_line(prop_name, prop_schema, prop_type, is_required, inherited_nullable=inherited)
        lines.append(f"    {line}")

    return "\n".join(lines) + "\n"


def _generate_flattened_model(
    title: str,
    schema: dict,
    refs: set[str],
    all_titles: set[str],
    pascal_name: str,
    safe_desc: str,
    *,
    all_schemas: dict[str, dict] | None = None,
    schema_title: str | None = None,
) -> str:
    """Generate a model for schemas with properties AND anyOf (serde flatten).

    Generates variant types for the anyOf entries alongside the BaseModel.
    The converter discovers them by naming convention.
    """
    properties = schema.get("properties", {})
    any_of = schema.get("anyOf", [])

    # Generate variant types for the anyOf entries
    variant_codes: list[str] = []
    for i, v in enumerate(any_of, 1):
        var_code, _, var_refs = _generate_variant_class(
            v, pascal_name, i, title, all_titles, all_schemas=all_schemas,
        )
        variant_codes.append(var_code)
        refs.update(var_refs)

    # Generate the BaseModel with properties
    lines = [f"class {pascal_name}(BaseModel):"]
    if safe_desc:
        lines.append(f'    """{safe_desc}"""')
    if schema_title:
        lines.append(f"    model_config = ConfigDict(title={schema_title!r})")
        lines.append("")

    for prop_name, prop_schema in properties.items():
        collect_refs(prop_schema, refs)
        # Push naming context for inline type generation
        _naming_context.append(pascal_name)
        _naming_context.append(prop_name[0].upper() + prop_name[1:] if prop_name else "")
        prop_type = convert_to_type(prop_schema, title, all_titles)
        _naming_context.pop()
        _naming_context.pop()
        nullable = _is_nullable(prop_schema)
        is_required = not nullable
        inherited = nullable and not _is_directly_nullable(prop_schema)
        line = _generate_field_line(prop_name, prop_schema, prop_type, is_required, inherited_nullable=inherited)
        lines.append(f"    {line}")

    if not properties:
        lines.append("    pass")

    main_code = "\n".join(lines) + "\n"
    return "\n\n".join(variant_codes + [main_code])


def _is_root_model_schema(schema: dict, all_schemas: dict[str, dict] | None = None) -> bool:
    """Check if a schema would generate a RootModel (not a BaseModel).

    RootModels are generated for anyOf unions, enums, and primitive types.
    BaseModels are generated for objects with properties — UNLESS the schema
    has $ref + properties where the $ref target is a RootModel union, in which
    case _generate_expanded_union_ref produces a RootModel.
    """
    if "properties" in schema:
        # $ref + properties where the $ref target is a RootModel → also a RootModel
        ref_target = schema.get("$ref")
        if ref_target and all_schemas:
            ref_schema = all_schemas.get(ref_target)
            if ref_schema and _is_root_model_schema(ref_schema, all_schemas):
                return True
        return False
    if schema.get("type") == "object":
        return False
    return True


def _generate_flattened_ref_model(
    title: str,
    schema: dict,
    refs: set[str],
    all_titles: set[str],
    pascal_name: str,
    safe_desc: str,
    ref_target: str,
    *,
    all_schemas: dict[str, dict] | None = None,
    schema_title: str | None = None,
    variant_title: str | None = None,
) -> str:
    """Generate a model for schemas with properties AND a $ref.

    If the $ref target is a BaseModel, uses inheritance (class Foo(Bar)).
    If the $ref target is a RootModel (union), expands the union: creates
    a new variant for each of the $ref's variants, each inheriting from
    that variant's BaseModel and adding the local properties.
    """
    properties = schema.get("properties", {})
    refs.add(ref_target)

    # Check if the $ref target would be a RootModel
    ref_schema = (all_schemas or {}).get(ref_target)
    if ref_schema and _is_root_model_schema(ref_schema, all_schemas):
        return _generate_expanded_union_ref(
            title, schema, refs, all_titles, pascal_name, safe_desc,
            ref_target, ref_schema, all_schemas=all_schemas, schema_title=schema_title,
            variant_title=variant_title,
        )

    # BaseModel target: simple inheritance
    base_class = resolve_ref_name(ref_target)
    lines = [f"class {pascal_name}({base_class}):"]
    if safe_desc:
        lines.append(f'    """{safe_desc}"""')
    config_parts: list[str] = []
    if schema_title:
        config_parts.append(f"title={schema_title!r}")
    if variant_title:
        config_parts.append(f"json_schema_extra={{'_variant_title': {variant_title!r}}}")
    if config_parts:
        lines.append(f"    model_config = ConfigDict({', '.join(config_parts)})")
        lines.append("")

    if properties:
        for prop_name, prop_schema in properties.items():
            collect_refs(prop_schema, refs)
            prop_type = convert_to_type(prop_schema, title, all_titles)
            is_required = not _is_nullable(prop_schema)
            line = _generate_field_line(prop_name, prop_schema, prop_type, is_required)
            lines.append(f"    {line}")
    else:
        lines.append("    pass")

    return "\n".join(lines) + "\n"


def _generate_expanded_union_ref(
    title: str,
    schema: dict,
    refs: set[str],
    all_titles: set[str],
    pascal_name: str,
    safe_desc: str,
    ref_target: str,
    ref_schema: dict,
    *,
    all_schemas: dict[str, dict] | None = None,
    schema_title: str | None = None,
    variant_title: str | None = None,
) -> str:
    """Expand a $ref to a RootModel union by creating new variants.

    For each variant of the union, generates a new class that inherits from
    that variant's inner type and adds the local properties. The result is
    a RootModel union of the expanded variants.
    """
    properties = schema.get("properties", {})
    # Save original property names for _expanded_ref_props metadata
    original_prop_names = list(properties.keys()) if properties else None
    any_of = ref_schema.get("anyOf", [])

    # If no direct anyOf, follow the $ref chain to find it,
    # accumulating properties from intermediate schemas.
    if not any_of and all_schemas:
        intermediate_props = dict(ref_schema.get("properties", {}))
        inner_ref = ref_schema.get("$ref")
        while inner_ref and not any_of:
            inner_schema = all_schemas.get(inner_ref)
            if inner_schema is None:
                break
            any_of = inner_schema.get("anyOf", [])
            if not any_of:
                for k, v in inner_schema.get("properties", {}).items():
                    intermediate_props.setdefault(k, v)
                inner_ref = inner_schema.get("$ref")
        if any_of:
            # Merge intermediate properties under our own properties
            merged = dict(intermediate_props)
            merged.update(properties)
            properties = merged

    if not any_of:
        # Not a union — fall back to wrapping as a field
        base_class = resolve_ref_name(ref_target)
        lines = [f"class {pascal_name}(BaseModel):"]
        if safe_desc:
            lines.append(f'    """{safe_desc}"""')
        if schema_title:
            lines.append(f"    model_config = ConfigDict(title={schema_title!r})")
            lines.append("")
        lines.append("    pass")
        return "\n".join(lines) + "\n"

    # For each variant, generate a new class that combines the variant
    # with the local properties
    variant_codes: list[str] = []
    union_members: list[str] = []

    # Use a recursive helper to flatten through nested RootModel unions

    def _expand_variants(
        any_of_list: list[dict],
        props: dict,
        title_prefix: str = "",
    ) -> None:
        for variant_schema in any_of_list:
            if _is_simple_null_variant(variant_schema):
                union_members.append("None")
                continue

            variant_title = variant_schema.get("title", "")
            composed_title = title_prefix + variant_title

            # Resolve the variant to a BaseModel by unwrapping $ref chains
            resolved_ref, resolved_schema = _resolve_to_base_model(
                variant_schema, all_schemas,
            )

            if resolved_ref and resolved_schema and not _is_root_model_schema(resolved_schema, all_schemas):
                # BaseModel — inherit and add properties.
                var_name = f"{pascal_name}{composed_title}"
                # Use title_to_pascal for the base class name to avoid collisions
                # when multiple variants resolve to types with the same short name.
                refs.add(resolved_ref)
                inner_class = title_to_pascal(resolved_ref)
                # Register in the name map so imports use the correct alias
                _current_name_map[resolved_ref] = inner_class
                var_code = _generate_variant_with_properties(
                    var_name, inner_class, props, title, refs, all_titles,
                )
                variant_codes.append(var_code)
                union_members.append(var_name)
            elif resolved_ref and resolved_schema and _is_root_model_schema(resolved_schema, all_schemas):
                # RootModel union — recursively expand its variants,
                # carrying our properties down to each leaf BaseModel.
                # Collect properties and follow $ref to find the anyOf.
                inner_props = dict(resolved_schema.get("properties", {}))
                inner_props.update(props)
                inner_any_of = resolved_schema.get("anyOf", [])
                # If no direct anyOf, follow the $ref chain to find it
                if not inner_any_of:
                    inner_ref = resolved_schema.get("$ref")
                    while inner_ref and not inner_any_of and all_schemas:
                        ref_s = all_schemas.get(inner_ref)
                        if ref_s is None:
                            break
                        # Accumulate properties from intermediate schemas
                        for k, v in ref_s.get("properties", {}).items():
                            inner_props.setdefault(k, v)
                        inner_any_of = ref_s.get("anyOf", [])
                        inner_ref = ref_s.get("$ref") if not inner_any_of else None
                if inner_any_of:
                    _expand_variants(inner_any_of, inner_props, title_prefix=composed_title)
                else:
                    # RootModel without anyOf — fallback
                    var_code, var_name_out, var_refs = _generate_variant_class(
                        variant_schema, pascal_name, 0, title, all_titles,
                        all_schemas=all_schemas,
                    )
                    refs.update(var_refs)
                    variant_codes.append(var_code)
                    union_members.append(var_name_out)
            elif "properties" in variant_schema:
                # Inline object variant — generate as BaseModel with merged properties
                var_name = f"{pascal_name}{composed_title}"
                merged_props = dict(variant_schema.get("properties", {}))
                merged_props.update(props)
                merged_schema = dict(variant_schema)
                merged_schema["properties"] = merged_props
                var_code = _generate_object_model(
                    title, merged_schema, refs, all_titles, var_name, "",
                )
                variant_codes.append(var_code)
                union_members.append(var_name)
            else:
                # Other variant type — just generate as-is with properties
                var_code, var_name_out, var_refs = _generate_variant_class(
                    variant_schema, pascal_name, 0, title, all_titles,
                    all_schemas=all_schemas,
                )
                refs.update(var_refs)
                variant_codes.append(var_code)
                union_members.append(var_name_out)

    _expand_variants(any_of, properties)

    # Generate the main RootModel union
    root_type = _union_type(union_members)
    main_code = _make_root_model(pascal_name, safe_desc, root_type, schema_title=schema_title, expanded_ref=ref_target, expanded_ref_props=original_prop_names, variant_title=variant_title)
    return "\n\n".join(variant_codes + [main_code])


def _resolve_to_base_model(
    variant_schema: dict,
    all_schemas: dict[str, dict] | None,
) -> tuple[str | None, dict | None]:
    """Follow $ref chains until we reach a BaseModel (has properties) or dead end.

    Returns (ref_title, schema) of the resolved BaseModel, or (None, None).
    """
    seen: set[str] = set()
    current = variant_schema
    current_ref = current.get("$ref")

    while current_ref and current_ref not in seen:
        seen.add(current_ref)
        target_schema = (all_schemas or {}).get(current_ref)
        if target_schema is None:
            return current_ref, None

        if not _is_root_model_schema(target_schema, all_schemas):
            # Found a BaseModel
            return current_ref, target_schema

        # RootModel — check if it's a simple $ref wrapper (anyOf with single $ref variants)
        any_of = target_schema.get("anyOf", [])
        # If this is a union, we can't unwrap further — return the ref as-is
        if len(any_of) != 1:
            return current_ref, target_schema

        # Single-variant union — unwrap
        inner = any_of[0]
        current_ref = inner.get("$ref")
        current = inner

    return current_ref, (all_schemas or {}).get(current_ref) if current_ref else (None, None)


def _generate_variant_with_properties(
    var_name: str,
    base_class: str,
    properties: dict,
    title: str,
    refs: set[str],
    all_titles: set[str],
) -> str:
    """Generate a variant class that inherits from base_class and adds properties."""
    lines = [f"class {var_name}({base_class}):"]

    if properties:
        for prop_name, prop_schema in properties.items():
            collect_refs(prop_schema, refs)
            prop_type = convert_to_type(prop_schema, title, all_titles)
            is_required = not _is_nullable(prop_schema)
            line = _generate_field_line(prop_name, prop_schema, prop_type, is_required)
            lines.append(f"    {line}")
    else:
        lines.append("    pass")

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Cycle detection
# ---------------------------------------------------------------------------


def find_files_in_cycles(
    file_groups: dict[str, list],
    file_refs: dict[str, set[str]],
) -> set[str]:
    """Find all files that participate in dependency cycles."""
    files_in_cycles: set[str] = set()
    for f in file_groups:
        visited: set[str] = set()
        queue = list(file_refs.get(f, set()) - {f})
        while queue:
            v = queue.pop(0)
            if v == f:
                files_in_cycles.add(f)
                break
            if v in visited:
                continue
            visited.add(v)
            queue.extend(file_refs.get(v, set()))
    return files_in_cycles


# ---------------------------------------------------------------------------
# Clean previously generated files
# ---------------------------------------------------------------------------


def clean_generated(directory: Path) -> None:
    """Recursively delete auto-generated files and empty __init__.py stubs,
    then prune empty directories bottom-up."""
    if not directory.exists():
        return
    for entry in list(directory.iterdir()):
        if entry.is_dir():
            clean_generated(entry)
        elif entry.is_file() and entry.suffix == ".py":
            try:
                content = entry.read_text(encoding="utf-8")
                # Delete auto-generated files (have the marker)
                if "THIS FILE IS AUTO-GENERATED" in content[:128]:
                    entry.unlink()
                elif entry.name == "__init__.py" and content.strip() == "":
                    entry.unlink()
            except (OSError, UnicodeDecodeError):
                pass
    try:
        if directory.exists() and not any(directory.iterdir()):
            directory.rmdir()
    except OSError:
        pass


def _is_generated(path: Path) -> bool:
    try:
        return "THIS FILE IS AUTO-GENERATED" in path.read_text(encoding="utf-8")[:128]
    except (OSError, UnicodeDecodeError):
        return False


