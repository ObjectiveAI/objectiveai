/**
 * Typed consumer of the cli daemon's `/listen` broadcast over a
 * NATIVE WebSocket — the JS mirror of the Rust SDK's
 * `cli::websocket_listener::WebSocketListener`, identical in
 * construction and semantics: connect to the daemon's published
 * `/listen` URL (optional signature auth), receive one envelope per
 * announced run, reconnection is the caller's loop. Usable anywhere a
 * `WebSocket` can reach the daemon — the main viewer window, Node
 * 22+, any browser context with network access.
 *
 * The daemon broadcasts every CLI run as one request frame
 * (`{…context, id, value: <Request>}`), then bare `{id, value: <item>}`
 * response frames (no type tag — the id is the whole routing story),
 * then exactly one terminator (`{id, end: true}`).
 * [`WebSocketListener`] turns those frames into the generated
 * [`CliCommandListenerExecution`] tree — the mirror of the Rust
 * `cli::command::ListenerExecution` — and IS a stream of that root
 * union: `{request, agentArguments, response}` per run, discriminated
 * purely off the request's path. Unary leaves pair the request with a
 * `Promise`, streaming leaves with a [`ResponseItemStream`];
 * multi-variant leaves narrow further via the request's
 * `dangerous_advanced.stream` flag, matching their
 * `…ListenerExecutionVariant` union.
 *
 * Auth is the first-message preamble shared by every daemon WebSocket
 * route (headers are never used — browser WebSocket clients can't set
 * them): the connection's first outbound text frame is
 * `{"signature": "sha256=<hex>"}` (or `{"signature": null}`); a
 * secret-bearing daemon closes the connection on a missing/invalid
 * signature.
 *
 * Delivery is LIVE-ONLY — the listener multiplexes but never retains.
 * A subscriber (root iterator or response-stream iterator) receives
 * only what arrives after it subscribes; anything delivered while
 * nobody is subscribed is dropped. Buffering, if wanted, is the
 * caller's to implement — a long-lived viewer sees unboundedly many
 * runs, so retention here would be a memory leak.
 *
 * Rust-parity lifecycle: one listener = one connection. When the
 * socket closes (daemon exit, network drop, [`WebSocketListener.close`]),
 * every open run's feed closes (unary responses settle with the
 * synthesized "run ended" error, streams end) and every root iterator
 * ENDS.
 *
 * No validation: the types are structural claims over the wire; frame
 * bodies pass through as-is (in-band `CliError` lines arrive as items
 * of the same union the execute functions yield). An execution whose
 * `path_type` this build predates is SKIPPED entirely: no envelope,
 * its frames dropped. Items are always the typed PRE-transform
 * response items — the CLI's broadcast tee sits below its jq/python
 * output transform, so transform-bearing requests land on their
 * normal typed leaves.
 *
 * The `CliCommandListenerExecution` tree and the mode table are
 * generated by `scripts/install-listener-execution.cjs`, following the
 * same per-scope conventions as the generated execute functions.
 */

import {
  CLI_COMMAND_LISTENER_EXECUTION_MODES,
  type CliCommandListenerExecution,
} from "./command/listenerExecution";

/** One live subscriber: a per-iterator pending queue's feed side. */
type Subscriber<T> = {
  push: (item: T) => void;
  end: () => void;
};

/**
 * Live-only async-iterable for one run's streaming response — the JS
 * mirror of the Rust `websocket_listener::ResponseItemStream`. Items
 * fan out to every CURRENT iterator; nothing is retained, so an
 * iterator sees only items pushed after it subscribed (subscription
 * happens when the iterator is created), and items pushed while no
 * iterator exists are dropped. Each iterator's undelivered items queue
 * only until that iterator consumes them or detaches.
 */
export class ResponseItemStream<T> implements AsyncIterable<T> {
  #done = false;
  #subscribers = new Set<Subscriber<T>>();

  /** Whether the run's terminator has arrived. */
  get done(): boolean {
    return this.#done;
  }

  /** @internal — feed side. */
  _push(item: T): void {
    if (this.#done) return;
    for (const subscriber of [...this.#subscribers]) {
      subscriber.push(item);
    }
  }

  /** @internal — feed side. */
  _end(): void {
    if (this.#done) return;
    this.#done = true;
    const subscribers = [...this.#subscribers];
    this.#subscribers.clear();
    for (const subscriber of subscribers) {
      subscriber.end();
    }
  }

  [Symbol.asyncIterator](): AsyncIterator<T> {
    const queue: T[] = [];
    let ended = this.#done;
    let wake: (() => void) | null = null;
    const subscriber: Subscriber<T> = {
      push: (item) => {
        queue.push(item);
        wake?.();
      },
      end: () => {
        ended = true;
        wake?.();
      },
    };
    if (!ended) {
      this.#subscribers.add(subscriber);
    }
    const detach = () => this.#subscribers.delete(subscriber);
    return {
      next: async (): Promise<IteratorResult<T>> => {
        for (;;) {
          if (queue.length > 0) {
            return { value: queue.shift() as T, done: false };
          }
          if (ended) {
            return { value: undefined, done: true };
          }
          await new Promise<void>((resolve) => {
            wake = resolve;
          });
          wake = null;
        }
      },
      return: async (): Promise<IteratorResult<T>> => {
        detach();
        return { value: undefined, done: true };
      },
      throw: async (e?: unknown): Promise<IteratorResult<T>> => {
        detach();
        throw e;
      },
    };
  }

  /** Every item from subscription (now) until the run's terminator. */
  async toArray(): Promise<T[]> {
    const out: T[] = [];
    for await (const item of this) out.push(item);
    return out;
  }
}

/** A run's live feed-side handles, keyed by broadcast id. */
type LiveFeed = {
  pathType: string;
  stream?: ResponseItemStream<unknown>;
  resolve?: (value: unknown) => void;
  settled?: boolean;
};

export interface WebSocketListenerOptions {
  /** The pre-derived `sha256=<hex(SHA256(DAEMON_SECRET))>`, sent
   * verbatim in the auth preamble. Without it the daemon must be
   * running without a secret. */
  signature?: string | null;
}

/**
 * The connected `/listen` consumer — construct via
 * [`WebSocketListener.connect`]. IS a stream of the root
 * [`CliCommandListenerExecution`] union:
 *
 * ```ts
 * const listener = await WebSocketListener.connect(
 *   "ws://127.0.0.1:49152/listen",
 *   { signature },
 * );
 * for await (const run of listener) {
 *   if (run.request.path_type === "plugins/run") {
 *     for await (const item of run.response) { … }
 *   }
 * }
 * ```
 *
 * Delivery is live-only: an iterator receives runs announced after it
 * was created; nothing is retained (see the module docs). The nested
 * `response` never rides the root stream — it lives inside each
 * envelope, as a `Promise` or a [`ResponseItemStream`], and is itself
 * live-only: subscribe to it before yielding back to the event loop
 * or its early frames are dropped. Every iterator ends when the
 * connection does; reconnection is the caller's loop.
 */
export class WebSocketListener {
  #ws: WebSocket;
  #closed = false;
  #live = new Map<string, LiveFeed>();
  #skipped = new Set<string>();
  #subscribers = new Set<Subscriber<CliCommandListenerExecution>>();

  private constructor(ws: WebSocket) {
    this.#ws = ws;
    ws.onmessage = (event: MessageEvent) => {
      if (typeof event.data !== "string") return;
      let frame: unknown;
      try {
        frame = JSON.parse(event.data);
      } catch {
        return;
      }
      this.#onFrame(frame);
    };
    ws.onclose = () => this.#onClose();
  }

  /**
   * Open the connection, send the auth preamble, and resolve once the
   * socket is established (rejects when the daemon is unreachable or
   * closes during the handshake — e.g. it refused the auth).
   * `url` is the daemon's full `/listen` URL.
   */
  static connect(
    url: string,
    options?: WebSocketListenerOptions,
  ): Promise<WebSocketListener> {
    return new Promise((resolve, reject) => {
      let ws: WebSocket;
      try {
        ws = new WebSocket(url);
      } catch (e) {
        reject(new Error(`connect daemon listen websocket: ${String(e)}`));
        return;
      }
      ws.onopen = () => {
        // The auth preamble — always the connection's first text
        // frame, `{"signature": null}` against a secretless daemon.
        ws.send(JSON.stringify({ signature: options?.signature ?? null }));
        resolve(new WebSocketListener(ws));
      };
      ws.onclose = (event: CloseEvent) => {
        reject(
          new Error(
            `connect daemon listen websocket: connection closed` +
              `${event.code ? ` (code ${event.code})` : ""}`,
          ),
        );
      };
    });
  }

  /** Drop the connection: every open run's feed closes and every root
   * iterator ends. */
  close(): void {
    if (this.#closed) return;
    this.#ws.close();
    // The browser fires onclose asynchronously; end deterministically.
    this.#onClose();
  }

  /**
   * Iterate the runs announced from this call onward. Multiple
   * iterators are independent; `return()`/`break` detaches cleanly;
   * every iterator ends when the connection does.
   */
  runs(): AsyncIterableIterator<CliCommandListenerExecution> {
    const queue: CliCommandListenerExecution[] = [];
    let ended = this.#closed;
    let wake: (() => void) | null = null;
    const subscriber: Subscriber<CliCommandListenerExecution> = {
      push: (run) => {
        queue.push(run);
        wake?.();
      },
      end: () => {
        ended = true;
        wake?.();
      },
    };
    if (!ended) {
      this.#subscribers.add(subscriber);
    }
    const detach = () => this.#subscribers.delete(subscriber);
    return {
      next: async (): Promise<IteratorResult<CliCommandListenerExecution>> => {
        for (;;) {
          if (queue.length > 0) {
            return {
              value: queue.shift() as CliCommandListenerExecution,
              done: false,
            };
          }
          if (ended) {
            return { value: undefined, done: true };
          }
          await new Promise<void>((resolve) => {
            wake = resolve;
          });
          wake = null;
        }
      },
      return: async (): Promise<
        IteratorResult<CliCommandListenerExecution>
      > => {
        detach();
        return { value: undefined, done: true };
      },
      throw: async (
        e?: unknown,
      ): Promise<IteratorResult<CliCommandListenerExecution>> => {
        detach();
        throw e;
      },
      [Symbol.asyncIterator]() {
        return this;
      },
    };
  }

  [Symbol.asyncIterator](): AsyncIterableIterator<CliCommandListenerExecution> {
    return this.runs();
  }

  /** Connection over: close every still-open run (unresolved unary
   * responses settle with the synthesized "run ended" error; streams
   * end) and end every root iterator. */
  #onClose(): void {
    if (this.#closed) return;
    this.#closed = true;
    for (const id of [...this.#live.keys()]) {
      this.#onEnd(id);
    }
    this.#skipped.clear();
    const subscribers = [...this.#subscribers];
    this.#subscribers.clear();
    for (const subscriber of subscribers) {
      subscriber.end();
    }
  }

  #onFrame(frame: unknown): void {
    if (typeof frame !== "object" || frame === null) return;
    const f = frame as { id?: unknown; end?: unknown; value?: unknown };
    if (typeof f.id !== "string") return;

    // Frames carry no type tag — the id is the whole routing story:
    // terminator by `end: true`, response when the id is live (or
    // skipped), request otherwise.
    if (f.end === true) {
      this.#onEnd(f.id);
    } else if (this.#live.has(f.id)) {
      this.#onResponse(f.id, f.value);
    } else if (this.#skipped.has(f.id)) {
      // A run we chose not to open — drop its frames.
    } else {
      this.#onRequest(f.id, frame as Record<string, unknown>);
    }
  }

  #onRequest(id: string, frame: Record<string, unknown>): void {
    const request = frame["value"];
    if (typeof request !== "object" || request === null) {
      this.#skipped.add(id);
      return;
    }
    const req = request as {
      path_type?: unknown;
      jq?: unknown;
      python?: unknown;
      dangerous_advanced?: { stream?: unknown } | null;
    };
    // A request always carries its `path_type`; tag-less frames that
    // reach here without one are not requests.
    if (typeof req.path_type !== "string") {
      this.#skipped.add(id);
      return;
    }
    const agentArguments = extractAgentArguments(frame);

    // Mode off the request alone — the same rules as the Rust
    // dispatch: the multi-variant leaves pick per-request off the
    // stream flag; an unmapped path skips the execution.
    const mode = CLI_COMMAND_LISTENER_EXECUTION_MODES[req.path_type];
    if (mode === undefined) {
      this.#skipped.add(id);
      return;
    }
    const resolved =
      mode === "both"
        ? req.dangerous_advanced?.stream === true
          ? "stream"
          : "unary"
        : mode;

    let response: ResponseItemStream<unknown> | Promise<unknown>;
    const feed: LiveFeed = { pathType: req.path_type };
    if (resolved === "stream") {
      feed.stream = new ResponseItemStream<unknown>();
      response = feed.stream;
    } else {
      response = new Promise<unknown>((resolve) => {
        feed.resolve = resolve;
      });
    }
    this.#live.set(id, feed);

    // The runtime can't prove the request↔response pairing the
    // generated tree declares — the mode lookup IS that pairing.
    const envelope = {
      request,
      agentArguments,
      response,
    } as CliCommandListenerExecution;
    for (const subscriber of [...this.#subscribers]) {
      subscriber.push(envelope);
    }
  }

  #onResponse(id: string, value: unknown): void {
    const feed = this.#live.get(id);
    if (!feed) return;
    if (feed.stream) {
      feed.stream._push(value);
    } else if (!feed.settled) {
      feed.settled = true;
      feed.resolve?.(value);
    }
  }

  #onEnd(id: string): void {
    this.#skipped.delete(id);
    const feed = this.#live.get(id);
    if (!feed) return;
    this.#live.delete(id);
    if (feed.stream) {
      feed.stream._end();
    } else if (!feed.settled) {
      // A unary run that ended without any response frame settles with
      // a synthesized in-band error — the same union member the
      // execute functions yield.
      feed.settled = true;
      feed.resolve?.({
        type: "error",
        level: "error",
        fatal: null,
        message: `${feed.pathType}: run ended before any response item`,
      });
    }
  }
}

/** Pick the agent-argument fields off a request frame's context.
 * `mcp_session_id` is never teed onto the broadcast; the frame's
 * `plugin_*` coordinates are not agent arguments and are dropped. */
function extractAgentArguments(
  frame: Record<string, unknown>,
): Record<string, string | null> {
  const agentArguments: Record<string, string | null> = {};
  for (const key of [
    "agent_instance_hierarchy",
    "agent_id",
    "agent_full_id",
    "agent_remote",
    "response_id",
    "response_ids",
  ] as const) {
    const value = frame[key];
    if (typeof value === "string" || value === null) {
      agentArguments[key] = value;
    }
  }
  return agentArguments;
}
