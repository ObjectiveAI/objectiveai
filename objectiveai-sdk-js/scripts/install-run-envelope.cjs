#!/usr/bin/env node
// Generates the viewer subpath's typed run-envelope union + runtime map
// from the Rust SDK's CLI command tree.
//
// The daemon broadcasts every CLI run as one request frame
// (`{…context, id, value: <Request>}`) followed by bare
// `{id, value: <item>}` response frames (no type tag — the id is the
// routing) and one terminator (`{id, end: true}`). The viewer routes a
// plugin's `plugins/run` frames into its iframe; the two listeners in
// this subpath turn those frames into typed envelopes — and THIS
// script generates the type-level and runtime knowledge they need:
//
//   - one envelope type per leaf command, keyed by the request's
//     `path_type` literal: unary leaves pair the request with a
//     `Promise<CliError | Response>`, streaming leaves with a
//     `RunStream<CliError | ResponseItem>` — mirroring the return
//     types of the generated execute functions;
//   - multi-variant leaves (a unary `execute` plus an
//     `execute_streaming` gated on `dangerous_advanced.stream: true`,
//     e.g. `agents spawn`) emit BOTH envelope shapes; the runtime
//     picks per-request off the stream flag;
//   - `PluginRun`, the `{request, context, response}` union consumed
//     by `PluginRunListener` (src/viewer/pluginRuns.ts), plus an
//     unknown-path_type fallback (`RunStream<JsonValue>`);
//   - `Run`, the `{request, agentArguments, response}` union consumed
//     by `RunListener` (src/viewer/runListener.ts) — the mirror of the
//     Rust SDK's `cli::websocket_listener::Run`: per-leaf variants, a
//     `TransformedRun` fallback for jq/python requests, NO unknown
//     fallback (unknown runs are skipped), and no validation — the
//     types are structural claims over the wire, discriminated purely
//     off the request's path;
//   - `RUN_ENVELOPE_MAP`, the runtime `path_type → {mode, schemas}`
//     table (RunListener uses only `mode`; PluginRunListener also
//     validates with the schemas).
//
// Discovery mirrors scripts/install-command-execute.cjs (same scope
// detection, same `Path` discriminator + schema-module rules, same
// streaming detection via the Rust `E::Stream<…>` return); the shared
// helpers are duplicated because each codegen script is self-contained
// by convention. Runs AFTER install-zod.cjs (whose clean pass deletes
// this header-stamped output) and after install-command-execute.cjs in
// the package build script. Skips are reported, never silent.

const fs = require("fs");
const path = require("path");

const REPO_ROOT = path.resolve(__dirname, "../..");
const RUST_SRC_DIR = path.join(REPO_ROOT, "objectiveai-sdk-rs/src");
const RUST_COMMAND_DIR = path.join(RUST_SRC_DIR, "cli/command");
const SRC_DIR = path.resolve(__dirname, "../src");
const OUT_FILE_SRC_REL = "viewer/runEnvelope.ts";

const GENERATED_HEADER =
  "// THIS FILE IS AUTO-GENERATED. DO NOT EDIT.\n" +
  "// Generated by scripts/install-run-envelope.cjs from objectiveai-sdk-rs/src/cli/command/.\n";

// ── small helpers (mirrors of install-command-execute.cjs) ──────────

function snakeToCamel(s) {
  return s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
}

function snakeToPascal(s) {
  const c = snakeToCamel(s);
  return c[0].toUpperCase() + c.slice(1);
}

function titleToPascal(title) {
  return title
    .split(/[._]/)
    .filter(Boolean)
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join("");
}

function titleToPath(title) {
  const parts = title.split(".");
  const typeName = parts.pop();
  const dir = parts.join("/");
  const file = typeName[0].toLowerCase() + typeName.slice(1);
  return { dir, file };
}

function relativeImport(fromFile, toFile) {
  const fromDir = path.posix.dirname(fromFile);
  let rel = path.posix.relative(fromDir, toFile);
  if (!rel.startsWith(".")) rel = "./" + rel;
  return rel;
}

function normalize(rust) {
  return rust
    .replace(/\/\/[^\n]*/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function matchBrace(text, openIdx, open = "{", close = "}") {
  let depth = 0;
  for (let i = openIdx; i < text.length; i++) {
    if (text[i] === open) depth++;
    else if (text[i] === close) {
      depth--;
      if (depth === 0) return i;
    }
  }
  throw new Error(`unbalanced ${open}${close} starting at ${openIdx}`);
}

function splitTopLevel(text, sep = ",") {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const ch of text) {
    if ("<([{".includes(ch)) depth++;
    else if (">)]}".includes(ch)) depth--;
    if (ch === sep && depth === 0) {
      parts.push(current.trim());
      current = "";
    } else {
      current += ch;
    }
  }
  if (current.trim()) parts.push(current.trim());
  return parts;
}

// ── Rust source parsing (mirrors of install-command-execute.cjs) ────

function findPathConst(scopeSource) {
  const enumMatch = /pub enum Path\s*\{/.exec(scopeSource);
  if (!enumMatch) return null;
  const close = matchBrace(scopeSource, enumMatch.index + enumMatch[0].length - 1);
  const body = scopeSource.slice(enumMatch.index + enumMatch[0].length, close);
  const renames = [...body.matchAll(/#\[serde\(rename = "([^"]+)"\)\]/g)];
  const variantCount = splitTopLevel(normalize(body)).filter(Boolean).length;
  if (renames.length !== 1 || variantCount !== 1) return null;
  const structMatch = /pub struct Request\s*\{/.exec(scopeSource);
  if (!structMatch) return null;
  const structClose = matchBrace(
    scopeSource,
    structMatch.index + structMatch[0].length - 1,
  );
  const structBody = scopeSource.slice(
    structMatch.index + structMatch[0].length,
    structClose,
  );
  const fieldMatch = /pub (\w+)\s*:\s*Path\b/.exec(structBody);
  if (!fieldMatch) return null;
  return { field: fieldMatch[1], value: renames[0][1] };
}

function findTypeAliases(scopeSource) {
  const aliases = {};
  for (const m of scopeSource.matchAll(/pub type (\w+)\s*=\s*([^;]+);/g)) {
    aliases[m[1]] = m[2].trim();
  }
  return aliases;
}

function findLocalDefs(scopeSource) {
  const defs = new Set();
  for (const m of scopeSource.matchAll(/pub (?:struct|enum) (\w+)/g)) {
    defs.add(m[1]);
  }
  return defs;
}

function findReexports(scopeSource) {
  const out = {};
  for (const m of scopeSource.matchAll(
    /pub use (super(?:::\w+)*)::\{([^}]+)\}\s*;/gs,
  )) {
    for (const item of splitTopLevel(normalize(m[2]))) {
      const asMatch = /^(\w+) as (\w+)$/.exec(item);
      if (asMatch) out[asMatch[2]] = `${m[1]}::${asMatch[1]}`;
      else if (/^\w+$/.test(item)) out[item] = `${m[1]}::${item}`;
    }
  }
  for (const m of scopeSource.matchAll(
    /pub use (super(?:::\w+)*)::(\w+)(?: as (\w+))?\s*;/g,
  )) {
    out[m[3] ?? m[2]] = `${m[1]}::${m[2]}`;
  }
  return out;
}

function findExecuteFns(scopeSource) {
  const fns = [];
  const re = /pub async fn (execute\w*)\s*</g;
  let m;
  while ((m = re.exec(scopeSource)) !== null) {
    const genericsClose = matchBrace(scopeSource, re.lastIndex - 1, "<", ">");
    const parenOpen = scopeSource.indexOf("(", genericsClose);
    const parenClose = matchBrace(scopeSource, parenOpen, "(", ")");
    const arrow = scopeSource.indexOf("->", parenClose);
    const bodyOpen = scopeSource.indexOf("{", arrow);
    const bodyClose = matchBrace(scopeSource, bodyOpen);
    fns.push({
      name: m[1],
      returnType: normalize(scopeSource.slice(arrow + 2, bodyOpen)),
    });
  }
  return fns;
}

function resolveType(typeExpr, scope, modulePath, context) {
  const t = typeExpr.trim();
  if (t === "serde_json::Value" || t === "schemars::Schema") {
    return { kind: "json" };
  }
  if (t === "String") return { kind: "string" };
  const opt = /^Option<(.+)>$/.exec(t);
  if (opt) {
    return { ...resolveType(opt[1], scope, modulePath, context), optional: true };
  }
  if (t === "ResponseSchema" || t.endsWith("::ResponseSchema")) {
    return { kind: "json" };
  }
  if (t.includes("::")) {
    const segs = t.split("::").map((s) => s.trim());
    if (segs[0] === "crate") {
      return { kind: "schema", title: rustModuleTitle(segs.slice(1)) };
    }
    if (segs[0] === "super") {
      let base = modulePath.slice(0, -1);
      let i = 1;
      while (segs[i] === "super") {
        base = base.slice(0, -1);
        i++;
      }
      return {
        kind: "schema",
        title: rustModuleTitle([...base, ...segs.slice(i)]),
      };
    }
    throw new Error(`${context}: unsupported type path \`${t}\``);
  }
  if (scope.aliases[t] !== undefined) {
    return resolveType(scope.aliases[t], scope, modulePath, context);
  }
  if (scope.reexports[t] !== undefined) {
    return resolveType(scope.reexports[t], scope, modulePath, context);
  }
  if (scope.localDefs.has(t)) {
    return { kind: "schema", title: [...modulePath, t].join(".") };
  }
  throw new Error(`${context}: cannot resolve type \`${t}\``);
}

function rustModuleTitle(segs) {
  const typeName = segs[segs.length - 1];
  let moduleSegs = segs.slice(0, -1);
  if (
    moduleSegs.length > 0 &&
    fs.existsSync(path.join(RUST_SRC_DIR, ...moduleSegs) + ".rs")
  ) {
    moduleSegs = moduleSegs.slice(0, -1);
  }
  return [...moduleSegs, typeName].join(".");
}

function schemaModule(title) {
  const { dir, file } = titleToPath(title);
  const srcRelative = path.posix.join(dir, file);
  const abs = path.join(SRC_DIR, dir, `${file}.ts`);
  if (!fs.existsSync(abs)) return null;
  return { srcRelative, pascal: titleToPascal(title) };
}

// ── generation ──────────────────────────────────────────────────────

function main() {
  if (!fs.existsSync(RUST_COMMAND_DIR)) {
    console.error(
      `install-run-envelope: rust command dir missing: ${RUST_COMMAND_DIR}`,
    );
    process.exit(2);
  }

  // The cli's JSONL error envelope title, resolved from the Rust source
  // like install-command-execute does.
  const errorTitle = (() => {
    const errorRs = path.join(REPO_ROOT, "objectiveai-sdk-rs/src/cli/error.rs");
    const src = fs.readFileSync(errorRs, "utf8");
    const m = /#\[schemars\(rename = "([^"]+)"\)\]\s*pub struct Error\b/s.exec(
      src,
    );
    if (!m) {
      console.error(
        "install-run-envelope: could not find schemars rename for crate::cli::Error",
      );
      process.exit(2);
    }
    return m[1];
  })();
  const errorModule = schemaModule(errorTitle);
  if (!errorModule) {
    console.error(
      `install-run-envelope: zod module for \`${errorTitle}\` missing — run install-zod.cjs first`,
    );
    process.exit(2);
  }

  // Same scope discovery as install-command-execute.cjs.
  const scopeByKey = new Map();
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(abs);
      else if (entry.isFile() && entry.name.endsWith(".rs")) {
        const source = fs.readFileSync(abs, "utf8");
        if (
          !/pub async fn execute\w*\s*</.test(source) ||
          !/pub struct Request\b/.test(source)
        ) {
          continue;
        }
        const rel = path
          .relative(RUST_COMMAND_DIR, abs)
          .replace(/\\/g, "/")
          .replace(/\.rs$/, "");
        const key =
          path.posix.basename(rel) === "mod"
            ? path.posix.dirname(rel)
            : rel;
        if (key === ".") continue;
        scopeByKey.set(key, { source });
      }
    }
  })(RUST_COMMAND_DIR);

  const skipped = [];
  const imports = new Map(); // importPath → Set of names
  const addImport = (p, name) => {
    if (!imports.has(p)) imports.set(p, new Set());
    imports.get(p).add(name);
  };
  const envelopeTypes = []; // emitted type alias blocks (PluginRun side)
  const envelopeNames = []; // names for the PluginRun union
  const runTypes = []; // emitted type alias blocks (Run side)
  const runNames = []; // names for the Run union
  const mapEntries = []; // "path": { mode, … } lines

  addImport(errorModule.srcRelative, `${errorModule.pascal}Schema`);
  addImport(errorModule.srcRelative, `type ${errorModule.pascal}`);
  addImport("jsonValue", "JsonValueSchema");
  addImport("jsonValue", "type JsonValue");
  addImport("cli/command/agentArguments", "type CliCommandAgentArguments");
  addImport("cli/command/request", "type CliCommandRequest");

  for (const key of [...scopeByKey.keys()].sort()) {
    const scopeSegments = key.split("/");
    const rawScope = scopeByKey.get(key);
    const modulePath = ["cli", "command", ...scopeSegments];
    const scope = {
      aliases: findTypeAliases(rawScope.source),
      localDefs: findLocalDefs(rawScope.source),
      reexports: findReexports(rawScope.source),
    };

    const pathConst = findPathConst(rawScope.source);
    if (pathConst === null) {
      skipped.push(
        `${scopeSegments.join(" ")} — no \`Path\` discriminator on Request yet`,
      );
      continue;
    }
    const requestTitle = [...modulePath, "Request"].join(".");
    const requestModule = schemaModule(requestTitle);
    if (!requestModule) {
      skipped.push(
        `${scopeSegments.join(" ")} — schema \`${requestTitle}\` not generated by install-zod yet`,
      );
      continue;
    }

    // Only the canonical wire forms matter here: `execute` (the leaf's
    // primary form) and `execute_streaming` (the stream-flagged twin on
    // multi-variant leaves). The transform variants share the same
    // path_type but tee post-transform JSON — the listener detects
    // those per-request (jq/python set) and falls back to raw items.
    const fns = findExecuteFns(rawScope.source);
    const primary = fns.find((f) => f.name === "execute");
    const streamingTwin = fns.find((f) => f.name === "execute_streaming");
    if (!primary) {
      skipped.push(`${scopeSegments.join(" ")} — no plain \`execute\` fn`);
      continue;
    }

    /** Resolve one fn's payload → {streaming, schemaExpr, tsType} or null (skip). */
    const resolvePayload = (fn) => {
      const context = `${scopeSegments.join("/")} ${fn.name}`;
      const retMatch = /^Result<(.+), E::Error>$/.exec(fn.returnType);
      if (!retMatch) {
        throw new Error(`${context}: unrecognized return \`${fn.returnType}\``);
      }
      let payloadExpr = retMatch[1].trim();
      const streamMatch = /^E::Stream<(.+)>$/.exec(payloadExpr);
      const streaming = streamMatch !== null;
      if (streaming) payloadExpr = streamMatch[1].trim();
      const payload = resolveType(payloadExpr, scope, modulePath, context);
      let schemaExpr;
      let tsType;
      if (payload.kind === "json") {
        schemaExpr = "JsonValueSchema";
        tsType = "JsonValue";
      } else if (payload.kind === "string") {
        schemaExpr = "z.string()";
        tsType = "string";
      } else {
        const mod = schemaModule(payload.title);
        if (!mod) {
          skipped.push(
            `${scopeSegments.join(" ")} ${fn.name} — schema \`${payload.title}\` not generated by install-zod yet`,
          );
          return null;
        }
        addImport(mod.srcRelative, `${mod.pascal}Schema`);
        addImport(mod.srcRelative, `type ${mod.pascal}`);
        schemaExpr = `${mod.pascal}Schema`;
        tsType = mod.pascal;
      }
      if (payload.optional && payload.kind !== "json") {
        schemaExpr = `${schemaExpr}.nullable()`;
        tsType = `${tsType} | null`;
      }
      return {
        streaming,
        schemaExpr: `z.union([${errorModule.pascal}Schema, ${schemaExpr}])`,
        tsType: `${errorModule.pascal} | ${tsType}`,
      };
    };

    const primaryPayload = resolvePayload(primary);
    if (primaryPayload === null) continue;
    const twinPayload = streamingTwin ? resolvePayload(streamingTwin) : null;
    if (streamingTwin && twinPayload === null) continue;

    addImport(requestModule.srcRelative, `type ${requestModule.pascal}`);
    const baseName = scopeSegments.map(snakeToPascal).join("");
    const docPath = scopeSegments.join(" ");

    if (twinPayload) {
      // Multi-variant leaf: a unary primary + a streaming twin gated on
      // `dangerous_advanced.stream: true`. Two envelope shapes; the
      // listener picks per-request off that flag.
      runTypes.push(
        `/** \`${docPath}\` — unary form. */\n` +
          `export type ${baseName}Run = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  agentArguments: CliCommandAgentArguments;\n` +
          `  response: Promise<${primaryPayload.tsType}>;\n` +
          `};\n`,
        `/** \`${docPath}\` — streaming form (\`dangerous_advanced.stream: true\`). */\n` +
          `export type ${baseName}StreamingRun = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  agentArguments: CliCommandAgentArguments;\n` +
          `  response: RunStream<${twinPayload.tsType}>;\n` +
          `};\n`,
      );
      runNames.push(`${baseName}Run`, `${baseName}StreamingRun`);
      const streamName = `${baseName}StreamingRunEnvelope`;
      const unaryName = `${baseName}RunEnvelope`;
      envelopeTypes.push(
        `/** \`${docPath}\` — streaming form (\`dangerous_advanced.stream: true\`). */\n` +
          `export type ${streamName} = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  context: RunContext;\n` +
          `  response: RunStream<${twinPayload.tsType}>;\n` +
          `};\n`,
        `/** \`${docPath}\` — unary form. */\n` +
          `export type ${unaryName} = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  context: RunContext;\n` +
          `  response: Promise<${primaryPayload.tsType}>;\n` +
          `};\n`,
      );
      envelopeNames.push(streamName, unaryName);
      mapEntries.push(
        `  ${JSON.stringify(pathConst.value)}: {\n` +
          `    mode: "both",\n` +
          `    itemSchema: ${twinPayload.schemaExpr},\n` +
          `    responseSchema: ${primaryPayload.schemaExpr},\n` +
          `  },`,
      );
    } else if (primaryPayload.streaming) {
      runTypes.push(
        `/** \`${docPath}\` — streaming. */\n` +
          `export type ${baseName}Run = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  agentArguments: CliCommandAgentArguments;\n` +
          `  response: RunStream<${primaryPayload.tsType}>;\n` +
          `};\n`,
      );
      runNames.push(`${baseName}Run`);
      const name = `${baseName}RunEnvelope`;
      envelopeTypes.push(
        `/** \`${docPath}\` — streaming. */\n` +
          `export type ${name} = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  context: RunContext;\n` +
          `  response: RunStream<${primaryPayload.tsType}>;\n` +
          `};\n`,
      );
      envelopeNames.push(name);
      mapEntries.push(
        `  ${JSON.stringify(pathConst.value)}: {\n` +
          `    mode: "stream",\n` +
          `    itemSchema: ${primaryPayload.schemaExpr},\n` +
          `  },`,
      );
    } else {
      runTypes.push(
        `/** \`${docPath}\` — unary. */\n` +
          `export type ${baseName}Run = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  agentArguments: CliCommandAgentArguments;\n` +
          `  response: Promise<${primaryPayload.tsType}>;\n` +
          `};\n`,
      );
      runNames.push(`${baseName}Run`);
      const name = `${baseName}RunEnvelope`;
      envelopeTypes.push(
        `/** \`${docPath}\` — unary. */\n` +
          `export type ${name} = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  context: RunContext;\n` +
          `  response: Promise<${primaryPayload.tsType}>;\n` +
          `};\n`,
      );
      envelopeNames.push(name);
      mapEntries.push(
        `  ${JSON.stringify(pathConst.value)}: {\n` +
          `    mode: "unary",\n` +
          `    responseSchema: ${primaryPayload.schemaExpr},\n` +
          `  },`,
      );
    }
  }

  const importLines = ['import { z } from "zod";'];
  importLines.push(
    'import { type RunContext, type RunEnvelopeSpec, type RunStream } from "./pluginRuns";',
  );
  for (const [target, names] of [...imports.entries()].sort()) {
    const rel = relativeImport(OUT_FILE_SRC_REL, target);
    importLines.push(
      `import { ${[...names].sort().join(", ")} } from "${rel}";`,
    );
  }

  const unknownBlock =
    "/** Fallback for a broadcast run whose `path_type` this SDK build\n" +
    " * predates (or whose request failed validation): raw JSON items. */\n" +
    "export type UnknownRunEnvelope = {\n" +
    "  request: JsonValue;\n" +
    "  context: RunContext;\n" +
    "  response: RunStream<JsonValue>;\n" +
    "};\n";

  const transformedRunBlock =
    "/** A run whose request carries a jq/python output transform: its\n" +
    " * items are post-transform JSON with no static shape, so they stay\n" +
    " * raw (the request itself is the typed root aggregate). */\n" +
    "export type TransformedRun = {\n" +
    "  request: CliCommandRequest;\n" +
    "  agentArguments: CliCommandAgentArguments;\n" +
    "  response: RunStream<JsonValue>;\n" +
    "};\n";

  const runUnionBlock =
    "/** One daemon-broadcast run — the mirror of the Rust SDK's\n" +
    " * `cli::websocket_listener::Run`, consumed by `RunListener`.\n" +
    " * Discriminated purely off the request: narrow on\n" +
    " * `run.request.path_type` to type `run.response` — a `Promise` for\n" +
    " * unary leaves, a `RunStream` for streaming leaves (multi-variant\n" +
    " * leaves narrow further via the request's\n" +
    " * `dangerous_advanced.stream` flag). No unknown fallback: a run\n" +
    " * this build's types predate is skipped by the listener. */\n" +
    "export type Run =\n" +
    runNames.map((n) => `  | ${n}`).join("\n") +
    "\n  | TransformedRun;\n";

  const unionBlock =
    "/** One daemon-broadcast run, typed off its request's `path_type`.\n" +
    " * Narrow on `run.request.path_type` to type `run.response` — a\n" +
    " * `Promise` for unary leaves, a `RunStream` for streaming leaves\n" +
    " * (multi-variant leaves narrow further via the request's\n" +
    " * `dangerous_advanced.stream` flag). */\n" +
    "export type PluginRun =\n" +
    envelopeNames.map((n) => `  | ${n}`).join("\n") +
    "\n  | UnknownRunEnvelope;\n";

  const mapBlock =
    "/** Runtime `path_type → {mode, schemas}` table for the listener:\n" +
    " * items/responses validate as `CliError | <leaf type>` — the same\n" +
    " * unions the generated execute functions use. */\n" +
    "export const RUN_ENVELOPE_MAP: Readonly<Record<string, RunEnvelopeSpec>> = {\n" +
    mapEntries.join("\n") +
    "\n};\n";

  const content =
    GENERATED_HEADER +
    importLines.join("\n") +
    "\n\n" +
    envelopeTypes.join("\n") +
    "\n" +
    unknownBlock +
    "\n" +
    unionBlock +
    "\n" +
    runTypes.join("\n") +
    "\n" +
    transformedRunBlock +
    "\n" +
    runUnionBlock +
    "\n" +
    mapBlock;
  const outAbs = path.join(SRC_DIR, OUT_FILE_SRC_REL);
  fs.mkdirSync(path.dirname(outAbs), { recursive: true });
  fs.writeFileSync(outAbs, content);

  console.log(
    `install-run-envelope: generated ${envelopeNames.length} envelope + ${runNames.length} run type(s) across ${mapEntries.length} path(s)`,
  );
  if (skipped.length > 0) {
    console.warn(`install-run-envelope: SKIPPED ${skipped.length} scope(s):`);
    for (const s of skipped) console.warn(`  - ${s}`);
  }
}

