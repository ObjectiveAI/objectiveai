#!/usr/bin/env node
// Generates the viewer module's typed `execute` functions from the
// Rust SDK's CLI command tree.
//
// For every leaf execute-family function under
// objectiveai-sdk-rs/src/cli/command/** (`execute`, `execute_jq`,
// `execute_streaming`, …, including the ones inside each leaf's
// nested `request_schema` / `response_schema` modules), this script
// emits a mirrored TypeScript function under src/viewer/command/**:
//
//   - same arguments minus `executor` and `agent_arguments`
//     (so: `request`, and sometimes `jq`),
//   - same pre-call request mutations (jq set/clear, the
//     dangerous_advanced.stream flag) — parsed from the Rust body via
//     a bounded statement grammar that HARD-ERRORS on anything it
//     doesn't recognize, so Rust-side drift fails generation loudly,
//   - streaming fns return a `CliStream` of
//     z.union([CliOutputError, <Item>]) synchronously; unary fns
//     return a Promise of the same union (first stream item, rest
//     discarded),
//   - the wire value is the leaf request itself: requests are
//     self-describing via their single-variant `Path` enum field
//     (e.g. `"agents/get/request_schema"`), injected here so callers
//     never pass it. The host deserializes the JSON as the SDK's
//     `cli::command::Request` and lowers it to argv via
//     `into_command()` — Request→argv never exists in JS.
//
// Function names are the full command path + fn name, snake→camel,
// because the JS module surface is flat: `agents get execute` →
// `agentsGetExecute` / `agentsGetExecuteJq`;
// `agents get request_schema execute` → `agentsGetRequestSchemaExecute`.
//
// Skipping rules (reported, never silent): a fn is skipped when its
// scope has no `Path` discriminator yet, or when a referenced
// Request/Response zod module hasn't been generated by
// install-zod.cjs yet (i.e. the type isn't registered in the Rust
// json_schemas() registry). Re-running after the Rust side lands
// picks them up with no changes here.

const fs = require("fs");
const path = require("path");

const REPO_ROOT = path.resolve(__dirname, "../..");
const RUST_SRC_DIR = path.join(REPO_ROOT, "objectiveai-sdk-rs/src");
const RUST_COMMAND_DIR = path.join(RUST_SRC_DIR, "cli/command");
const SRC_DIR = path.resolve(__dirname, "../src");
const OUT_DIR = path.join(SRC_DIR, "viewer/command");

const GENERATED_HEADER =
  "// THIS FILE IS AUTO-GENERATED. DO NOT EDIT.\n" +
  "// Generated by scripts/install-viewer-execute.cjs from objectiveai-sdk-rs/src/cli/command/.\n";

// ── small helpers ───────────────────────────────────────────────────

/** "swiss_system" → "swissSystem" */
function snakeToCamel(s) {
  return s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
}

/** "swiss_system" → "SwissSystem" */
function snakeToPascal(s) {
  const c = snakeToCamel(s);
  return c[0].toUpperCase() + c.slice(1);
}

/** Mirror of install-zod.cjs `titleToPascal`. */
function titleToPascal(title) {
  return title
    .split(/[._]/)
    .filter(Boolean)
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join("");
}

/** Mirror of install-zod.cjs `titleToPath`. */
function titleToPath(title) {
  const parts = title.split(".");
  const typeName = parts.pop();
  const dir = parts.join("/");
  const file = typeName[0].toLowerCase() + typeName.slice(1);
  return { dir, file };
}

/** POSIX relative import from one src-relative file to another. */
function relativeImport(fromFile, toFile) {
  const fromDir = path.posix.dirname(fromFile);
  let rel = path.posix.relative(fromDir, toFile);
  if (!rel.startsWith(".")) rel = "./" + rel;
  return rel;
}

/** Strip `//` line comments and collapse whitespace runs. */
function normalize(rust) {
  return rust
    .replace(/\/\/[^\n]*/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** Find the index of the brace that closes the one at `openIdx`. */
function matchBrace(text, openIdx, open = "{", close = "}") {
  let depth = 0;
  for (let i = openIdx; i < text.length; i++) {
    if (text[i] === open) depth++;
    else if (text[i] === close) {
      depth--;
      if (depth === 0) return i;
    }
  }
  throw new Error(`unbalanced ${open}${close} starting at ${openIdx}`);
}

/** Split on commas at angle/paren/brace depth zero. */
function splitTopLevel(text, sep = ",") {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const ch of text) {
    if ("<([{".includes(ch)) depth++;
    else if (">)]}".includes(ch)) depth--;
    if (ch === sep && depth === 0) {
      parts.push(current.trim());
      current = "";
    } else {
      current += ch;
    }
  }
  if (current.trim()) parts.push(current.trim());
  return parts;
}

// ── Rust source parsing ─────────────────────────────────────────────

/**
 * The scope's `Path` discriminator: a single-variant
 * `pub enum Path { #[serde(rename = "…")] Variant }` plus a Request
 * struct field of type `Path` (named `path_type` today — detected by
 * TYPE so a rename tracks automatically). Returns
 * `{ field, value }`, or null when the scope has no discriminator.
 */
function findPathConst(scopeSource) {
  const enumMatch = /pub enum Path\s*\{/.exec(scopeSource);
  if (!enumMatch) return null;
  const close = matchBrace(scopeSource, enumMatch.index + enumMatch[0].length - 1);
  const body = scopeSource.slice(enumMatch.index + enumMatch[0].length, close);
  const renames = [...body.matchAll(/#\[serde\(rename = "([^"]+)"\)\]/g)];
  // A discriminator is a CONSTANT — exactly one variant.
  const variantCount = splitTopLevel(normalize(body)).filter(Boolean).length;
  if (renames.length !== 1 || variantCount !== 1) return null;
  const structMatch = /pub struct Request\s*\{/.exec(scopeSource);
  if (!structMatch) return null;
  const structClose = matchBrace(
    scopeSource,
    structMatch.index + structMatch[0].length - 1,
  );
  const structBody = scopeSource.slice(
    structMatch.index + structMatch[0].length,
    structClose,
  );
  const fieldMatch = /pub (\w+)\s*:\s*Path\b/.exec(structBody);
  if (!fieldMatch) return null;
  return { field: fieldMatch[1], value: renames[0][1] };
}

/** Local `pub type NAME = TARGET;` aliases in a scope. */
function findTypeAliases(scopeSource) {
  const aliases = {};
  for (const m of scopeSource.matchAll(/pub type (\w+)\s*=\s*([^;]+);/g)) {
    aliases[m[1]] = m[2].trim();
  }
  return aliases;
}

/** Local `pub struct NAME` / `pub enum NAME` definitions in a scope. */
function findLocalDefs(scopeSource) {
  const defs = new Set();
  for (const m of scopeSource.matchAll(/pub (?:struct|enum) (\w+)/g)) {
    defs.add(m[1]);
  }
  return defs;
}

/**
 * `pub use super::…` re-exports in a scope, e.g.
 * `pub use super::get::{ResponseManifest as ResponseItem, …};`
 * Maps local name → "super::get::ResponseManifest".
 */
function findReexports(scopeSource) {
  const out = {};
  for (const m of scopeSource.matchAll(
    /pub use (super(?:::\w+)*)::\{([^}]+)\}\s*;/gs,
  )) {
    for (const item of splitTopLevel(normalize(m[2]))) {
      const asMatch = /^(\w+) as (\w+)$/.exec(item);
      if (asMatch) out[asMatch[2]] = `${m[1]}::${asMatch[1]}`;
      else if (/^\w+$/.test(item)) out[item] = `${m[1]}::${item}`;
    }
  }
  for (const m of scopeSource.matchAll(
    /pub use (super(?:::\w+)*)::(\w+)(?: as (\w+))?\s*;/g,
  )) {
    out[m[3] ?? m[2]] = `${m[1]}::${m[2]}`;
  }
  return out;
}

/**
 * Extract every `pub async fn execute*` in a scope: name, params,
 * return payload, body.
 */
function findExecuteFns(scopeSource) {
  const fns = [];
  const re = /pub async fn (execute\w*)\s*</g;
  let m;
  while ((m = re.exec(scopeSource)) !== null) {
    const genericsClose = matchBrace(scopeSource, re.lastIndex - 1, "<", ">");
    const parenOpen = scopeSource.indexOf("(", genericsClose);
    const parenClose = matchBrace(scopeSource, parenOpen, "(", ")");
    const arrow = scopeSource.indexOf("->", parenClose);
    const bodyOpen = scopeSource.indexOf("{", arrow);
    const bodyClose = matchBrace(scopeSource, bodyOpen);
    fns.push({
      name: m[1],
      params: normalize(scopeSource.slice(parenOpen + 1, parenClose)),
      returnType: normalize(scopeSource.slice(arrow + 2, bodyOpen)),
      body: normalize(scopeSource.slice(bodyOpen + 1, bodyClose)),
    });
  }
  return fns;
}

/**
 * Parse the fn's params into the JS-facing list: drops `executor` and
 * `agent_arguments`, keeps `request` (+ `jq`). Hard-errors on
 * anything unrecognized.
 */
function parseParams(params, context) {
  const out = [];
  for (const raw of splitTopLevel(params)) {
    if (!raw) continue;
    const p = raw.replace(/^mut /, "");
    const colon = p.indexOf(":");
    const name = p.slice(0, colon).trim();
    const type = p.slice(colon + 1).trim();
    // A leading underscore is Rust's unused-binding marker (e.g.
    // `_jq` on leaves that accept-and-ignore the filter) — the JS
    // mirror keeps the same outward signature.
    const bare = name.replace(/^_/, "");
    if (bare === "executor" || bare === "agent_arguments") continue;
    if (bare === "request" && type === "Request") {
      out.push({ name: "request" });
    } else if (bare === "jq" && type === "String") {
      out.push({ name: "jq" });
    } else if (
      bare === "transform" &&
      (type === "Transform" || type === "crate::cli::command::Transform")
    ) {
      // The output transform (jq | python). `_transform`-named params
      // (leaves that accept-and-ignore it) strip to `transform` above.
      out.push({ name: "transform" });
    } else {
      throw new Error(`${context}: unrecognized param \`${raw}\``);
    }
  }
  return out;
}

/**
 * The bounded body grammar. Consumes known statement fragments off
 * the front of the normalized body and returns the mutation set +
 * which executor method finishes it. Hard-errors on residue.
 */
function parseBody(body, context) {
  const mutations = { jq: null, transform: null, stream: null };
  let rest = body;
  const fragments = [
    [/^request\.jq = None;\s*/, () => (mutations.jq = "clear")],
    [/^request\.jq = Some\(jq\);\s*/, () => (mutations.jq = "set")],
    [
      /^request\.base\.clear_transform\(\);\s*/,
      () => (mutations.transform = "clear"),
    ],
    [
      /^request\.base\.set_transform\(transform\);\s*/,
      () => (mutations.transform = "set"),
    ],
    [
      /^let mut advanced = request\.dangerous_advanced\.unwrap_or_default\(\); advanced\.stream = Some\(true\); request\.dangerous_advanced = Some\(advanced\);\s*/,
      () => (mutations.stream = "set"),
    ],
    [
      /^if let Some\(advanced\) = request\.dangerous_advanced\.as_mut\(\) \{ advanced\.stream = None; \}\s*/,
      () => (mutations.stream = "clear"),
    ],
  ];
  let progressed = true;
  while (progressed) {
    progressed = false;
    for (const [re, apply] of fragments) {
      const m = re.exec(rest);
      if (m) {
        apply();
        rest = rest.slice(m[0].length);
        progressed = true;
      }
    }
  }
  const trimmed = rest.trim();
  // Plain tail: the executor call is the fn's return expression.
  let tail = /^executor\.(execute|execute_one)\(request, agent_arguments\)\.await$/.exec(
    trimmed,
  );
  if (!tail) {
    // Re-serializing tail: jq-less leaves run typed and convert the
    // Response to JSON (`let resp: … = executor.execute_one(…).await?;
    // Ok(serde_json::to_value(resp).expect(…))`). Wire-wise identical
    // to a plain unary call; the declared return type (Value) already
    // carries the payload kind.
    tail = /^let resp\s*:\s*[\w:]+\s*=\s*executor\.(execute_one)\(request, agent_arguments\)\.await\?;\s*Ok\(serde_json::to_value\(resp\)\.expect\("[^"]*"\)\)$/.exec(
      trimmed,
    );
  }
  if (!tail) {
    throw new Error(
      `${context}: unrecognized body residue \`${trimmed}\` — extend the statement grammar in install-viewer-execute.cjs`,
    );
  }
  return { mutations, call: tail[1] };
}

// ── type resolution ─────────────────────────────────────────────────

/**
 * Resolve a Rust type expression (as written in a leaf scope) to one
 * of:
 *   { kind: "json" }                       — serde_json::Value / schemars::Schema
 *   { kind: "string" }                     — String
 *   { kind: "schema", title: "a.b.C" }     — a registered schema type
 * `modulePath` is the scope's Rust module path as segments, e.g.
 * ["cli","command","agents","get"] or
 * ["cli","command","agents","get","request_schema"].
 */
function resolveType(typeExpr, scope, modulePath, context) {
  const t = typeExpr.trim();
  if (t === "serde_json::Value" || t === "schemars::Schema") {
    return { kind: "json" };
  }
  if (t === "String") return { kind: "string" };
  const opt = /^Option<(.+)>$/.exec(t);
  if (opt) {
    // Option<X> → nullable payload (the cli prints `null` for None).
    return { ...resolveType(opt[1], scope, modulePath, context), optional: true };
  }
  // `cli::command::ResponseSchema` is a transparent newtype around
  // schemars::Schema whose JsonSchema impl delegates to
  // serde_json::Value (objectiveai-sdk-rs/src/cli/command/
  // response_schema.rs) — every spelling of it is opaque JSON.
  if (t === "ResponseSchema" || t.endsWith("::ResponseSchema")) {
    return { kind: "json" };
  }
  if (t.includes("::")) {
    const segs = t.split("::").map((s) => s.trim());
    if (segs[0] === "crate") {
      return { kind: "schema", title: rustModuleTitle(segs.slice(1)) };
    }
    if (segs[0] === "super") {
      let base = modulePath.slice(0, -1);
      let i = 1;
      while (segs[i] === "super") {
        base = base.slice(0, -1);
        i++;
      }
      return {
        kind: "schema",
        title: rustModuleTitle([...base, ...segs.slice(i)]),
      };
    }
    throw new Error(`${context}: unsupported type path \`${t}\``);
  }
  if (scope.aliases[t] !== undefined) {
    return resolveType(scope.aliases[t], scope, modulePath, context);
  }
  if (scope.reexports[t] !== undefined) {
    return resolveType(scope.reexports[t], scope, modulePath, context);
  }
  if (scope.localDefs.has(t)) {
    return { kind: "schema", title: [...modulePath, t].join(".") };
  }
  throw new Error(`${context}: cannot resolve type \`${t}\``);
}

/**
 * Title of a Rust type given its `crate::`-relative path segments
 * (type name last). Mirrors the repo's schemars-rename convention
 * (and the json_schema_coverage test): the title uses FOLDER segments
 * only — a type in `src/agent/response.rs` is `agent.GetAgentResponse`
 * (file-module segment dropped), while one in
 * `src/cli/command/agents/get/mod.rs` keeps every segment.
 */
function rustModuleTitle(segs) {
  const typeName = segs[segs.length - 1];
  let moduleSegs = segs.slice(0, -1);
  if (
    moduleSegs.length > 0 &&
    fs.existsSync(path.join(RUST_SRC_DIR, ...moduleSegs) + ".rs")
  ) {
    moduleSegs = moduleSegs.slice(0, -1);
  }
  return [...moduleSegs, typeName].join(".");
}

/** zod-module info for a schema title; null when not generated yet. */
function schemaModule(title) {
  const { dir, file } = titleToPath(title);
  const srcRelative = path.posix.join(dir, file);
  const abs = path.join(SRC_DIR, dir, `${file}.ts`);
  if (!fs.existsSync(abs)) return null;
  return { srcRelative, pascal: titleToPascal(title) };
}

// ── generation ──────────────────────────────────────────────────────

function main() {
  if (!fs.existsSync(RUST_COMMAND_DIR)) {
    console.error(
      `install-viewer-execute: rust command dir missing: ${RUST_COMMAND_DIR}`,
    );
    process.exit(2);
  }

  // The cli's JSONL error envelope — resolve its title from the Rust
  // source (schemars rename on `crate::cli::Error`), not a hard-coded
  // name, so a future rename tracks automatically.
  const errorTitle = (() => {
    const errorRs = path.join(REPO_ROOT, "objectiveai-sdk-rs/src/cli/error.rs");
    const src = fs.readFileSync(errorRs, "utf8");
    const m = /#\[schemars\(rename = "([^"]+)"\)\]\s*pub struct Error\b/s.exec(
      src,
    );
    if (!m) {
      console.error(
        "install-viewer-execute: could not find schemars rename for crate::cli::Error",
      );
      process.exit(2);
    }
    return m[1];
  })();
  const errorModule = schemaModule(errorTitle);
  if (!errorModule) {
    console.error(
      `install-viewer-execute: zod module for \`${errorTitle}\` missing — run install-zod.cjs first`,
    );
    process.exit(2);
  }

  // Walk every .rs file. A SCOPE is any module defining both
  // `pub struct Request` and a `pub async fn execute*` — under the
  // current layout that's a leaf directory's mod.rs, or one of its
  // request_schema / response_schema child directories' mod.rs.
  // (Plain `<leaf>.rs` files are also accepted for robustness.)
  // Dispatcher mod.rs files define `pub enum Request`, never a
  // struct, so the struct test excludes them.
  const scopeByKey = new Map(); // "agents/get" → { source }
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(abs);
      else if (entry.isFile() && entry.name.endsWith(".rs")) {
        const source = fs.readFileSync(abs, "utf8");
        if (
          !/pub async fn execute\w*\s*</.test(source) ||
          !/pub struct Request\b/.test(source)
        ) {
          continue;
        }
        const rel = path
          .relative(RUST_COMMAND_DIR, abs)
          .replace(/\\/g, "/")
          .replace(/\.rs$/, "");
        const key =
          path.posix.basename(rel) === "mod"
            ? path.posix.dirname(rel)
            : rel;
        if (key === ".") continue; // command-root mod.rs is a dispatcher
        scopeByKey.set(key, { source });
      }
    }
  })(RUST_COMMAND_DIR);

  // Group: a scope whose ancestor directory is also a scope (e.g.
  // agents/get/request_schema under agents/get) is a NESTED scope of
  // that root; everything else is a root leaf. One output file per
  // root leaf, containing its own + its nested scopes' functions.
  const leaves = [];
  for (const key of [...scopeByKey.keys()].sort()) {
    let ancestor = path.posix.dirname(key);
    let root = null;
    while (ancestor !== ".") {
      if (scopeByKey.has(ancestor)) root = ancestor;
      ancestor = path.posix.dirname(ancestor);
    }
    if (root === null) {
      leaves.push({ key, scopes: [{ segments: key.split("/"), ...scopeByKey.get(key) }] });
    } else {
      leaves.find((l) => l.key === root).scopes.push({
        segments: key.split("/"),
        ...scopeByKey.get(key),
      });
    }
  }

  const skipped = [];
  const generated = [];
  /** dir (posix, relative to OUT_DIR) → Set of child export names */
  const dirChildren = new Map();

  for (const leaf of leaves) {
    const relRust = leaf.key; // e.g. "agents/get"
    const outFileSrcRel = path.posix.join("viewer/command", `${relRust}.ts`);

    const imports = new Map(); // importPath → Set of names
    const addImport = (p, name) => {
      if (!imports.has(p)) imports.set(p, new Set());
      imports.get(p).add(name);
    };
    const fnsOut = [];

    for (const rawScope of leaf.scopes) {
      const scopeSegments = rawScope.segments;
      const modulePath = ["cli", "command", ...scopeSegments];
      const scope = {
        aliases: findTypeAliases(rawScope.source),
        localDefs: findLocalDefs(rawScope.source),
        reexports: findReexports(rawScope.source),
      };
      const executeFns = findExecuteFns(rawScope.source);
      if (executeFns.length === 0) continue;

      const pathConst = findPathConst(rawScope.source);
      if (pathConst === null) {
        skipped.push(
          `${scopeSegments.join(" ")} — no \`Path\` discriminator on Request yet`,
        );
        continue;
      }

      const requestTitle = [...modulePath, "Request"].join(".");
      const requestModule = schemaModule(requestTitle);
      if (!requestModule) {
        skipped.push(
          `${scopeSegments.join(" ")} — schema \`${requestTitle}\` not generated by install-zod yet`,
        );
        continue;
      }

      for (const fn of executeFns) {
        const context = `${scopeSegments.join("/")} ${fn.name}`;
        const params = parseParams(fn.params, context);
        const { mutations, call } = parseBody(fn.body, context);

        // Return payload.
        const retMatch = /^Result<(.+), E::Error>$/.exec(fn.returnType);
        if (!retMatch) {
          throw new Error(`${context}: unrecognized return \`${fn.returnType}\``);
        }
        let payloadExpr = retMatch[1].trim();
        const streamMatch = /^E::Stream<(.+)>$/.exec(payloadExpr);
        const streaming = streamMatch !== null;
        if (streaming !== (call === "execute")) {
          throw new Error(
            `${context}: return shape and executor call disagree`,
          );
        }
        if (streaming) payloadExpr = streamMatch[1].trim();
        const payload = resolveType(payloadExpr, scope, modulePath, context);

        let payloadSchemaExpr;
        let payloadTsType;
        if (payload.kind === "json") {
          addImport("jsonValue", "JsonValueSchema");
          addImport("jsonValue", "type JsonValue");
          payloadSchemaExpr = "JsonValueSchema";
          payloadTsType = "JsonValue";
        } else if (payload.kind === "string") {
          payloadSchemaExpr = "z.string()";
          payloadTsType = "string";
        } else {
          const mod = schemaModule(payload.title);
          if (!mod) {
            skipped.push(
              `${scopeSegments.join(" ")} ${fn.name} — schema \`${payload.title}\` not generated by install-zod yet`,
            );
            continue;
          }
          addImport(mod.srcRelative, `${mod.pascal}Schema`);
          addImport(mod.srcRelative, `type ${mod.pascal}`);
          payloadSchemaExpr = `${mod.pascal}Schema`;
          payloadTsType = mod.pascal;
        }
        if (payload.optional && payload.kind !== "json") {
          payloadSchemaExpr = `${payloadSchemaExpr}.nullable()`;
          payloadTsType = `${payloadTsType} | null`;
        }

        addImport(requestModule.srcRelative, `type ${requestModule.pascal}`);
        if (errorModule) {
          addImport(errorModule.srcRelative, `${errorModule.pascal}Schema`);
          addImport(errorModule.srcRelative, `type ${errorModule.pascal}`);
        }

        const fnName =
          snakeToCamel(scopeSegments.map(snakeToCamel).join("_")) +
          snakeToPascal(fn.name);
        // The caller never passes the discriminator — it's injected.
        const requestParamType = `Omit<${requestModule.pascal}, ${JSON.stringify(pathConst.field)}>`;
        // Every generated execute fn requires an `executor` (one of the
        // three executor classes) as its first parameter; the request +
        // optional transform follow (mirroring the Rust fn, which also takes
        // an executor first).
        const jsParams = [
          "executor: CommandExecutor",
          ...params.map((p) => {
            if (p.name === "request") return `request: ${requestParamType}`;
            if (p.name === "transform")
              return "transform: { jq: string } | { python: string }";
            return "jq: string";
          }),
        ].join(", ");

        // Wire value: mutations + injected discriminator.
        const fields = [`...request`];
        if (mutations.jq === "clear") fields.push("jq: undefined");
        if (mutations.jq === "set") fields.push("jq");
        // The transform pair (jq | python). Clear nulls both; set nulls
        // both then spreads the chosen one (python overrides jq is moot
        // — the param is exactly one variant).
        if (mutations.transform === "clear") {
          fields.push("jq: undefined", "python: undefined");
        }
        if (mutations.transform === "set") {
          fields.push("jq: undefined", "python: undefined", "...transform");
        }
        if (mutations.stream === "set") {
          fields.push(
            "dangerous_advanced: { ...(request.dangerous_advanced ?? {}), stream: true }",
          );
        }
        if (mutations.stream === "clear") {
          fields.push(
            "dangerous_advanced: request.dangerous_advanced ? { ...request.dangerous_advanced, stream: undefined } : request.dangerous_advanced",
          );
        }
        fields.push(
          `${pathConst.field}: ${JSON.stringify(pathConst.value)}`,
        );
        const wire = `{ ${fields.join(", ")} }`;

        const unionSchema = `z.union([${errorModule.pascal}Schema, ${payloadSchemaExpr}])`;
        const unionType = `${errorModule.pascal} | ${payloadTsType}`;
        const docPath = scopeSegments.join(" ");

        if (streaming) {
          fnsOut.push(
            `/** \`${docPath} ${fn.name}\` — streaming; mirror of the Rust fn of the same path. */\n` +
              `export function ${fnName}(${jsParams}): CliStream<${unionType}> {\n` +
              `  return new CliStream(executor.execute(${wire}), ${unionSchema});\n` +
              `}\n`,
          );
        } else {
          fnsOut.push(
            `/** \`${docPath} ${fn.name}\` — unary; first stream item, rest discarded. */\n` +
              `export async function ${fnName}(${jsParams}): Promise<${unionType}> {\n` +
              `  const stream = new CliStream(executor.execute(${wire}), ${unionSchema});\n` +
              `  const first = await stream.first();\n` +
              `  if (first === undefined) {\n` +
              `    throw new Error("${docPath}: cli produced no output before the end marker");\n` +
              `  }\n` +
              `  return first;\n` +
              `}\n`,
          );
        }
      }
    }

    if (fnsOut.length === 0) continue;

    // Assemble the leaf file.
    addImport("viewer/cliStream", "CliStream");
    addImport("cli/command/executor", "type CommandExecutor");
    const importLines = ['import { z } from "zod";'];
    for (const [target, names] of [...imports.entries()].sort()) {
      const rel = relativeImport(outFileSrcRel, target);
      importLines.push(
        `import { ${[...names].sort().join(", ")} } from "${rel}";`,
      );
    }
    const content =
      GENERATED_HEADER + importLines.join("\n") + "\n\n" + fnsOut.join("\n");
    const outAbs = path.join(SRC_DIR, outFileSrcRel);
    fs.mkdirSync(path.dirname(outAbs), { recursive: true });
    fs.writeFileSync(outAbs, content);
    generated.push(outFileSrcRel);

    // Track barrel entries.
    let rel = path.posix.dirname(relRust);
    let childName = path.posix.basename(relRust);
    for (;;) {
      const dirKey = rel === "." ? "" : rel;
      if (!dirChildren.has(dirKey)) dirChildren.set(dirKey, new Set());
      dirChildren.get(dirKey).add(childName);
      if (dirKey === "") break;
      childName = path.posix.basename(dirKey);
      rel = path.posix.dirname(dirKey);
    }
  }

  // Barrels: one index.ts per generated dir; subdir entries re-export
  // `<name>/index`, leaf entries `<name>`.
  for (const [dirKey, children] of dirChildren) {
    const lines = [...children].sort().map((name) => {
      const isDir = dirChildren.has(
        dirKey === "" ? name : path.posix.join(dirKey, name),
      );
      return `export * from "./${name}${isDir ? "/index" : ""}";`;
    });
    const indexAbs = path.join(OUT_DIR, dirKey, "index.ts");
    fs.mkdirSync(path.dirname(indexAbs), { recursive: true });
    fs.writeFileSync(indexAbs, GENERATED_HEADER + lines.join("\n") + "\n");
  }
  if (!dirChildren.has("")) {
    // Nothing generated (schemas not registered yet) — keep the tree
    // compiling with an empty barrel.
    fs.mkdirSync(OUT_DIR, { recursive: true });
    fs.writeFileSync(
      path.join(OUT_DIR, "index.ts"),
      GENERATED_HEADER + "export {};\n",
    );
  }

  console.log(
    `install-viewer-execute: generated ${generated.length} leaf module(s)`,
  );
  if (skipped.length > 0) {
    console.warn(
      `install-viewer-execute: SKIPPED ${skipped.length} scope(s)/fn(s):`,
    );
    for (const s of skipped) console.warn(`  - ${s}`);
  }
}

// Clean previous output before regenerating.
fs.rmSync(OUT_DIR, { recursive: true, force: true });
main();
