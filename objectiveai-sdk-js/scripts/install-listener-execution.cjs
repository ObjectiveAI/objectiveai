#!/usr/bin/env node
// Generates the cli/command module's typed `ListenerExecution` tree
// from the Rust SDK's CLI command tree — the JS mirror of
// objectiveai-sdk-rs's distributed `cli::command::*::ListenerExecution`
// (a struct per leaf, an enum per branch, the root enum in command.rs).
//
// For every leaf scope this script emits a `listenerExecution.ts`
// beside the scope's own request/response types (the same placement
// and naming conventions install-command-execute.cjs uses for
// `execute.ts`):
//
//   - unary leaves: `CliCommand<Scope>ListenerExecution =
//     { request, agentArguments, response: Promise<CliError | Response> }`;
//   - streaming leaves: the same with
//     `response: ResponseItemStream<CliError | ResponseItem>`;
//   - multi-variant leaves (a unary `execute` plus an
//     `execute_streaming` gated on `dangerous_advanced.stream: true`)
//     get BOTH — `…ListenerExecution` and
//     `…ListenerExecutionStreaming` — plus the
//     `…ListenerExecutionVariant` union the parent branch references,
//     exactly like the Rust `ListenerExecutionVariant` enums.
//
// Every branch (tier) dir gets its own `listenerExecution.ts` with the
// tier union (`CliCommandAgentsListenerExecution = …`), variant set
// copied from the tier's Rust `ListenerExecution` enum. The root
// `src/cli/command/listenerExecution.ts` carries the root union
// (`CliCommandListenerExecution`), the `Transformed` fallback member,
// and the runtime `path_type → mode` table
// (`CLI_COMMAND_LISTENER_EXECUTION_MODES`) the viewer `ViewerListener`
// dispatches with. Unknown runs have no fallback — the listener skips
// them, mirroring the Rust dispatch.
//
// Discovery accepts BOTH `pub struct Request` and `pub enum Request`
// leaves (e.g. `agents tags lookup`), matching the Rust tree. Skips
// (a leaf whose zod modules install-zod hasn't generated yet) are
// reported, never silent, and drop the corresponding union members.
// No zod, no validation — the types are structural claims over the
// wire; each scope's `generatedIndex.ts` gains the
// `export * from "./listenerExecution"` line the same way
// install-command-execute.cjs surfaces `execute.ts`. Runs AFTER
// install-zod.cjs (whose clean pass deletes this header-stamped
// output) and after install-command-execute.cjs in the package build
// script.

const fs = require("fs");
const path = require("path");

const REPO_ROOT = path.resolve(__dirname, "../..");
const RUST_SRC_DIR = path.join(REPO_ROOT, "objectiveai-sdk-rs/src");
const RUST_COMMAND_DIR = path.join(RUST_SRC_DIR, "cli/command");
const SRC_DIR = path.resolve(__dirname, "../src");

const GENERATED_HEADER =
  "// THIS FILE IS AUTO-GENERATED. DO NOT EDIT.\n" +
  "// Generated by scripts/install-listener-execution.cjs from objectiveai-sdk-rs/src/cli/command/.\n";

// ── small helpers (mirrors of install-command-execute.cjs) ──────────

function snakeToCamel(s) {
  return s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
}

function snakeToPascal(s) {
  const c = snakeToCamel(s);
  return c[0].toUpperCase() + c.slice(1);
}

function titleToPascal(title) {
  return title
    .split(/[._]/)
    .filter(Boolean)
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join("");
}

function titleToPath(title) {
  const parts = title.split(".");
  const typeName = parts.pop();
  const dir = parts.join("/");
  const file = typeName[0].toLowerCase() + typeName.slice(1);
  return { dir, file };
}

function relativeImport(fromFile, toFile) {
  const fromDir = path.posix.dirname(fromFile);
  let rel = path.posix.relative(fromDir, toFile);
  if (!rel.startsWith(".")) rel = "./" + rel;
  return rel;
}

function normalize(rust) {
  return rust
    .replace(/\/\/[^\n]*/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function matchBrace(text, openIdx, open = "{", close = "}") {
  let depth = 0;
  for (let i = openIdx; i < text.length; i++) {
    if (text[i] === open) depth++;
    else if (text[i] === close) {
      depth--;
      if (depth === 0) return i;
    }
  }
  throw new Error(`unbalanced ${open}${close} starting at ${openIdx}`);
}

function splitTopLevel(text, sep = ",") {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const ch of text) {
    if ("<([{".includes(ch)) depth++;
    else if (">)]}".includes(ch)) depth--;
    if (ch === sep && depth === 0) {
      parts.push(current.trim());
      current = "";
    } else {
      current += ch;
    }
  }
  if (current.trim()) parts.push(current.trim());
  return parts;
}

// ── Rust source parsing ─────────────────────────────────────────────

function findPathConst(scopeSource) {
  const enumMatch = /pub enum Path\s*\{/.exec(scopeSource);
  if (!enumMatch) return null;
  const close = matchBrace(scopeSource, enumMatch.index + enumMatch[0].length - 1);
  const body = scopeSource.slice(enumMatch.index + enumMatch[0].length, close);
  const renames = [...body.matchAll(/#\[serde\(rename = "([^"]+)"\)\]/g)];
  const variantCount = splitTopLevel(normalize(body)).filter(Boolean).length;
  if (renames.length !== 1 || variantCount !== 1) return null;
  return renames[0][1];
}

function findTypeAliases(scopeSource) {
  const aliases = {};
  for (const m of scopeSource.matchAll(/pub type (\w+)\s*=\s*([^;]+);/g)) {
    aliases[m[1]] = m[2].trim();
  }
  return aliases;
}

function findLocalDefs(scopeSource) {
  const defs = new Set();
  for (const m of scopeSource.matchAll(/pub (?:struct|enum) (\w+)/g)) {
    defs.add(m[1]);
  }
  return defs;
}

function findReexports(scopeSource) {
  const out = {};
  for (const m of scopeSource.matchAll(
    /pub use (super(?:::\w+)*)::\{([^}]+)\}\s*;/gs,
  )) {
    for (const item of splitTopLevel(normalize(m[2]))) {
      const asMatch = /^(\w+) as (\w+)$/.exec(item);
      if (asMatch) out[asMatch[2]] = `${m[1]}::${asMatch[1]}`;
      else if (/^\w+$/.test(item)) out[item] = `${m[1]}::${item}`;
    }
  }
  for (const m of scopeSource.matchAll(
    /pub use (super(?:::\w+)*)::(\w+)(?: as (\w+))?\s*;/g,
  )) {
    out[m[3] ?? m[2]] = `${m[1]}::${m[2]}`;
  }
  return out;
}

function findExecuteFns(scopeSource) {
  const fns = [];
  const re = /pub async fn (execute\w*)\s*</g;
  let m;
  while ((m = re.exec(scopeSource)) !== null) {
    const genericsClose = matchBrace(scopeSource, re.lastIndex - 1, "<", ">");
    const parenOpen = scopeSource.indexOf("(", genericsClose);
    const parenClose = matchBrace(scopeSource, parenOpen, "(", ")");
    const arrow = scopeSource.indexOf("->", parenClose);
    const bodyOpen = scopeSource.indexOf("{", arrow);
    fns.push({
      name: m[1],
      returnType: normalize(scopeSource.slice(arrow + 2, bodyOpen)),
    });
  }
  return fns;
}

/** Parse a branch's Rust `pub enum ListenerExecution` (the source of
 * truth for tier union variant sets): [{name, inner}] with `inner` the
 * tuple type path (e.g. `spawn::ListenerExecutionVariant`), or null. */
function parseListenerExecutionEnum(src) {
  const em = /pub enum ListenerExecution\s*\{/.exec(src);
  if (!em) return null;
  const close = matchBrace(src, em.index + em[0].length - 1);
  const body = src.slice(em.index + em[0].length, close);
  const variants = [];
  for (const m of body.matchAll(/^\s*([A-Z]\w*)\(([^)]+)\),?$/gm)) {
    variants.push({ name: m[1], inner: m[2].trim() });
  }
  return variants;
}

function resolveType(typeExpr, scope, modulePath, context) {
  const t = typeExpr.trim();
  if (t === "serde_json::Value" || t === "schemars::Schema") {
    return { kind: "json" };
  }
  if (t === "String") return { kind: "string" };
  const opt = /^Option<(.+)>$/.exec(t);
  if (opt) {
    return { ...resolveType(opt[1], scope, modulePath, context), optional: true };
  }
  if (t === "ResponseSchema" || t.endsWith("::ResponseSchema")) {
    return { kind: "json" };
  }
  if (t.includes("::")) {
    const segs = t.split("::").map((s) => s.trim());
    if (segs[0] === "crate") {
      return { kind: "schema", title: rustModuleTitle(segs.slice(1)) };
    }
    if (segs[0] === "super") {
      let base = modulePath.slice(0, -1);
      let i = 1;
      while (segs[i] === "super") {
        base = base.slice(0, -1);
        i++;
      }
      return {
        kind: "schema",
        title: rustModuleTitle([...base, ...segs.slice(i)]),
      };
    }
    throw new Error(`${context}: unsupported type path \`${t}\``);
  }
  if (scope.aliases[t] !== undefined) {
    return resolveType(scope.aliases[t], scope, modulePath, context);
  }
  if (scope.reexports[t] !== undefined) {
    return resolveType(scope.reexports[t], scope, modulePath, context);
  }
  if (scope.localDefs.has(t)) {
    return { kind: "schema", title: [...modulePath, t].join(".") };
  }
  throw new Error(`${context}: cannot resolve type \`${t}\``);
}

function rustModuleTitle(segs) {
  const typeName = segs[segs.length - 1];
  let moduleSegs = segs.slice(0, -1);
  if (
    moduleSegs.length > 0 &&
    fs.existsSync(path.join(RUST_SRC_DIR, ...moduleSegs) + ".rs")
  ) {
    moduleSegs = moduleSegs.slice(0, -1);
  }
  return [...moduleSegs, typeName].join(".");
}

function schemaModule(title) {
  const { dir, file } = titleToPath(title);
  const srcRelative = path.posix.join(dir, file);
  const abs = path.join(SRC_DIR, dir, `${file}.ts`);
  if (!fs.existsSync(abs)) return null;
  return { srcRelative, pascal: titleToPascal(title) };
}

/** The generated type name for a scope's ListenerExecution flavor:
 * `CliCommand<Segments><Suffix>` (title-pascal convention). */
function executionName(scopeSegments, suffix) {
  return (
    titleToPascal(["cli", "command", ...scopeSegments].join(".")) + suffix
  );
}

/** Append the surfacing line to a scope's generatedIndex.ts (the same
 * mechanism install-command-execute.cjs uses for execute.ts). */
function surface(dirAbs) {
  const genIndexAbs = path.join(dirAbs, "generatedIndex.ts");
  const exportLine = 'export * from "./listenerExecution";';
  if (fs.existsSync(genIndexAbs)) {
    const cur = fs.readFileSync(genIndexAbs, "utf-8");
    if (!cur.split(/\r?\n/).includes(exportLine)) {
      fs.writeFileSync(genIndexAbs, cur.replace(/\n*$/, "\n") + exportLine + "\n");
    }
  } else {
    fs.writeFileSync(genIndexAbs, GENERATED_HEADER + exportLine + "\n");
  }
}

// ── generation ──────────────────────────────────────────────────────

function main() {
  if (!fs.existsSync(RUST_COMMAND_DIR)) {
    console.error(
      `install-listener-execution: rust command dir missing: ${RUST_COMMAND_DIR}`,
    );
    process.exit(2);
  }

  // The cli's JSONL error envelope title — in-band error lines ride
  // every run, so every response type unions with it.
  const errorTitle = (() => {
    const errorRs = path.join(REPO_ROOT, "objectiveai-sdk-rs/src/cli/error.rs");
    const src = fs.readFileSync(errorRs, "utf8");
    const m = /#\[schemars\(rename = "([^"]+)"\)\]\s*pub struct Error\b/s.exec(
      src,
    );
    if (!m) {
      console.error(
        "install-listener-execution: could not find schemars rename for crate::cli::Error",
      );
      process.exit(2);
    }
    return m[1];
  })();
  const errorModule = schemaModule(errorTitle);
  if (!errorModule) {
    console.error(
      `install-listener-execution: zod module for \`${errorTitle}\` missing — run install-zod.cjs first`,
    );
    process.exit(2);
  }

  // Walk the tree: leaves (struct OR enum Request + a single-variant
  // Path + execute fns) and branches (a Rust ListenerExecution enum).
  const leafByKey = new Map(); // key → {source}
  const branchByKey = new Map(); // key ("" = root command.rs) → variants
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(abs);
      else if (entry.isFile() && entry.name.endsWith(".rs")) {
        const source = fs.readFileSync(abs, "utf8");
        const rel = path
          .relative(RUST_COMMAND_DIR, abs)
          .replace(/\\/g, "/")
          .replace(/\.rs$/, "");
        const key =
          path.posix.basename(rel) === "mod" ? path.posix.dirname(rel) : rel;
        const hasRequest = /pub (?:struct|enum) Request\s*[{(<]?/.test(source);
        if (
          findPathConst(source) !== null &&
          hasRequest &&
          /pub async fn execute\w*\s*</.test(source)
        ) {
          if (key === ".") continue;
          leafByKey.set(key, { source });
        } else {
          const variants = parseListenerExecutionEnum(source);
          if (variants !== null) {
            branchByKey.set(key === "command" ? "" : key, variants);
          }
        }
      }
    }
  })(RUST_COMMAND_DIR);

  const skipped = [];
  const skippedKeys = new Set();
  const modeEntries = []; // "path": mode lines
  let leafFiles = 0;
  let branchFiles = 0;

  // ── leaves ────────────────────────────────────────────────────────
  for (const key of [...leafByKey.keys()].sort()) {
    const scopeSegments = key.split("/");
    const rawScope = leafByKey.get(key);
    const modulePath = ["cli", "command", ...scopeSegments];
    const scope = {
      aliases: findTypeAliases(rawScope.source),
      localDefs: findLocalDefs(rawScope.source),
      reexports: findReexports(rawScope.source),
    };
    const pathValue = findPathConst(rawScope.source);

    const requestTitle = [...modulePath, "Request"].join(".");
    const requestModule = schemaModule(requestTitle);
    if (!requestModule) {
      skipped.push(
        `${scopeSegments.join(" ")} — schema \`${requestTitle}\` not generated by install-zod yet`,
      );
      skippedKeys.add(key);
      continue;
    }

    const fns = findExecuteFns(rawScope.source);
    const primary = fns.find((f) => f.name === "execute");
    const streamingTwin = fns.find((f) => f.name === "execute_streaming");
    if (!primary) {
      skipped.push(`${scopeSegments.join(" ")} — no plain \`execute\` fn`);
      skippedKeys.add(key);
      continue;
    }

    const outFileSrcRel = path.posix.join(
      "cli/command",
      ...scopeSegments,
      "listenerExecution.ts",
    );
    const imports = new Map();
    const addImport = (p, name) => {
      if (!imports.has(p)) imports.set(p, new Set());
      imports.get(p).add(name);
    };

    /** Resolve one fn's payload → {streaming, tsType} or null (skip). */
    const resolvePayload = (fn) => {
      const context = `${scopeSegments.join("/")} ${fn.name}`;
      const retMatch = /^Result<(.+), E::Error>$/.exec(fn.returnType);
      if (!retMatch) {
        throw new Error(`${context}: unrecognized return \`${fn.returnType}\``);
      }
      let payloadExpr = retMatch[1].trim();
      const streamMatch = /^E::Stream<(.+)>$/.exec(payloadExpr);
      const streaming = streamMatch !== null;
      if (streaming) payloadExpr = streamMatch[1].trim();
      const payload = resolveType(payloadExpr, scope, modulePath, context);
      let tsType;
      if (payload.kind === "json") {
        addImport("jsonValue", "type JsonValue");
        tsType = "JsonValue";
      } else if (payload.kind === "string") {
        tsType = "string";
      } else {
        const mod = schemaModule(payload.title);
        if (!mod) {
          skipped.push(
            `${scopeSegments.join(" ")} ${fn.name} — schema \`${payload.title}\` not generated by install-zod yet`,
          );
          return null;
        }
        addImport(mod.srcRelative, `type ${mod.pascal}`);
        tsType = mod.pascal;
      }
      if (payload.optional && payload.kind !== "json") {
        tsType = `${tsType} | null`;
      }
      return { streaming, tsType: `${errorModule.pascal} | ${tsType}` };
    };

    const primaryPayload = resolvePayload(primary);
    if (primaryPayload === null) {
      skippedKeys.add(key);
      continue;
    }
    const twinPayload = streamingTwin ? resolvePayload(streamingTwin) : null;
    if (streamingTwin && twinPayload === null) {
      skippedKeys.add(key);
      continue;
    }

    addImport(errorModule.srcRelative, `type ${errorModule.pascal}`);
    addImport("cli/command/agentArguments", "type CliCommandAgentArguments");
    addImport(requestModule.srcRelative, `type ${requestModule.pascal}`);
    if (primaryPayload.streaming || twinPayload) {
      addImport("viewer/viewerListener", "type ResponseItemStream");
    }

    const docPath = scopeSegments.join(" ");
    const name = executionName(scopeSegments, "ListenerExecution");
    const body = [];
    if (twinPayload) {
      const streamingName = executionName(
        scopeSegments,
        "ListenerExecutionStreaming",
      );
      const variantName = executionName(
        scopeSegments,
        "ListenerExecutionVariant",
      );
      body.push(
        `/** One \`/listen\` broadcast run of \`${docPath}\` in its unary form (the plain \`execute\`). */\n` +
          `export type ${name} = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  agentArguments: CliCommandAgentArguments;\n` +
          `  response: Promise<${primaryPayload.tsType}>;\n` +
          `};\n`,
        `/** One \`/listen\` broadcast run of \`${docPath}\` in its streaming form (\`execute_streaming\` — the request set \`dangerous_advanced.stream: true\`). */\n` +
          `export type ${streamingName} = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  agentArguments: CliCommandAgentArguments;\n` +
          `  response: ResponseItemStream<${twinPayload.tsType}>;\n` +
          `};\n`,
        `/** This leaf's multiple listener executions — discriminated per request off \`dangerous_advanced.stream\`; the parent branch union references this. */\n` +
          `export type ${variantName} =\n` +
          `  | ${name}\n` +
          `  | ${streamingName};\n`,
      );
      modeEntries.push(`  ${JSON.stringify(pathValue)}: "both",`);
    } else if (primaryPayload.streaming) {
      body.push(
        `/** One \`/listen\` broadcast run of \`${docPath}\`: the actual request, the producer's agent arguments, and the response-item stream. */\n` +
          `export type ${name} = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  agentArguments: CliCommandAgentArguments;\n` +
          `  response: ResponseItemStream<${primaryPayload.tsType}>;\n` +
          `};\n`,
      );
      modeEntries.push(`  ${JSON.stringify(pathValue)}: "stream",`);
    } else {
      body.push(
        `/** One \`/listen\` broadcast run of \`${docPath}\`: the actual request, the producer's agent arguments, and the unary response future. */\n` +
          `export type ${name} = {\n` +
          `  request: ${requestModule.pascal};\n` +
          `  agentArguments: CliCommandAgentArguments;\n` +
          `  response: Promise<${primaryPayload.tsType}>;\n` +
          `};\n`,
      );
      modeEntries.push(`  ${JSON.stringify(pathValue)}: "unary",`);
    }

    const importLines = [];
    for (const [target, names] of [...imports.entries()].sort()) {
      const rel = relativeImport(outFileSrcRel, target);
      importLines.push(
        `import { ${[...names].sort().join(", ")} } from "${rel}";`,
      );
    }
    const content =
      GENERATED_HEADER + importLines.join("\n") + "\n\n" + body.join("\n");
    const outAbs = path.join(SRC_DIR, outFileSrcRel);
    fs.mkdirSync(path.dirname(outAbs), { recursive: true });
    fs.writeFileSync(outAbs, content);
    surface(path.dirname(outAbs));
    leafFiles++;
  }

  // ── branches (tier unions + the root) ─────────────────────────────
  // Rust variant inner path → the scope key + generated type suffix.
  const innerToRef = (branchKey, inner) => {
    let segs = inner.split("::").map((s) => s.trim());
    const typeName = segs[segs.length - 1]; // ListenerExecution[Variant|Streaming]
    segs = segs.slice(0, -1);
    let base = branchKey === "" ? [] : branchKey.split("/");
    while (segs[0] === "super") {
      if (base.length > 0) base = base.slice(0, -1);
      segs = segs.slice(1);
    }
    const targetKey = [...base, ...segs].join("/");
    const suffix = typeName.replace(/^ListenerExecution/, "ListenerExecution");
    return { targetKey, suffix: typeName };
  };

  // Emit deepest-first so parents can check children's existence via
  // skippedKeys (a branch whose target leaf/branch was skipped drops
  // that union member).
  const branchKeys = [...branchByKey.keys()].sort(
    (a, b) => b.split("/").length - a.split("/").length,
  );
  for (const branchKey of branchKeys) {
    const variants = branchByKey.get(branchKey);
    const scopeSegments = branchKey === "" ? [] : branchKey.split("/");
    const outFileSrcRel = path.posix.join(
      "cli/command",
      ...scopeSegments,
      "listenerExecution.ts",
    );
    const imports = new Map();
    const addImport = (p, name) => {
      if (!imports.has(p)) imports.set(p, new Set());
      imports.get(p).add(name);
    };
    const members = [];
    for (const v of variants) {
      if (v.name === "Transformed") continue; // root fallback, emitted below
      const { targetKey, suffix } = innerToRef(branchKey, v.inner);
      if (skippedKeys.has(targetKey)) continue;
      const memberName = executionName(targetKey.split("/"), suffix);
      const memberFile = path.posix.join(
        "cli/command",
        ...targetKey.split("/"),
        "listenerExecution",
      );
      addImport(memberFile, `type ${memberName}`);
      members.push(memberName);
    }
    if (members.length === 0) {
      skippedKeys.add(branchKey);
      skipped.push(
        `${branchKey || "(root)"} — every child listener execution was skipped`,
      );
      continue;
    }

    const name = executionName(scopeSegments, "ListenerExecution");
    const docPath = scopeSegments.join(" ") || "cli command";
    let extraBlock = "";
    let extraMember = "";
    let modesBlock = "";
    if (branchKey === "") {
      addImport(errorModule.srcRelative, `type ${errorModule.pascal}`);
      addImport("cli/command/agentArguments", "type CliCommandAgentArguments");
      addImport("cli/command/request", "type CliCommandRequest");
      addImport("jsonValue", "type JsonValue");
      addImport("viewer/viewerListener", "type ResponseItemStream");
      extraBlock =
        `/** A run whose request carries a jq/python output transform: its items are post-transform JSON with no static shape, so they stay raw (the request itself is the typed root aggregate). */\n` +
        `export type ${name}Transformed = {\n` +
        `  request: CliCommandRequest;\n` +
        `  agentArguments: CliCommandAgentArguments;\n` +
        `  response: ResponseItemStream<${errorModule.pascal} | JsonValue>;\n` +
        `};\n\n`;
      extraMember = `\n  | ${name}Transformed`;
      modesBlock =
        "\n" +
        `/** Runtime \`path_type → mode\` table for the viewer \`ViewerListener\`. No validation — the types are structural claims over the wire. */\n` +
        `export const CLI_COMMAND_LISTENER_EXECUTION_MODES: Readonly<Record<string, "unary" | "stream" | "both">> = {\n` +
        modeEntries.join("\n") +
        "\n};\n";
    }
    const unionDoc =
      branchKey === ""
        ? `/** One daemon-broadcast run — the root of the JS \`ListenerExecution\` tree (the mirror of the Rust SDK's \`cli::command::ListenerExecution\`), yielded by the viewer \`ViewerListener\`. Narrow on \`run.request.path_type\`; multi-variant leaves narrow further via the request's \`dangerous_advanced.stream\` flag. Runs this build's types predate are skipped by the listener — no unknown fallback. */`
        : `/** \`/listen\` mirror of \`${docPath}\`'s request aggregate: one member per child listener execution. */`;
    const body =
      unionDoc +
      "\n" +
      `export type ${name} =\n` +
      members.map((m) => `  | ${m}`).join("\n") +
      extraMember +
      ";\n";

    const importLines = [];
    for (const [target, names] of [...imports.entries()].sort()) {
      const rel = relativeImport(outFileSrcRel, target);
      importLines.push(
        `import { ${[...names].sort().join(", ")} } from "${rel}";`,
      );
    }
    const content =
      GENERATED_HEADER +
      importLines.join("\n") +
      "\n\n" +
      extraBlock +
      body +
      modesBlock;
    const outAbs = path.join(SRC_DIR, outFileSrcRel);
    fs.mkdirSync(path.dirname(outAbs), { recursive: true });
    fs.writeFileSync(outAbs, content);
    surface(path.dirname(outAbs));
    branchFiles++;
  }

  console.log(
    `install-listener-execution: generated ${leafFiles} leaf + ${branchFiles} branch listener-execution module(s)`,
  );
  if (skipped.length > 0) {
    console.warn(
      `install-listener-execution: SKIPPED ${skipped.length} scope(s):`,
    );
    for (const s of skipped) console.warn(`  - ${s}`);
  }
}

/** Remove previously-generated listenerExecution.ts files (anything
 * we'd regenerate), gated on the auto-generated header — mirrors
 * install-command-execute.cjs's clean pass. */
function cleanGeneratedListenerExecutionFiles(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      cleanGeneratedListenerExecutionFiles(full);
    } else if (
      entry.name === "listenerExecution.ts" &&
      fs.readFileSync(full, "utf-8").startsWith("// THIS FILE IS AUTO-GENERATED")
    ) {
      fs.rmSync(full);
    }
  }
}

cleanGeneratedListenerExecutionFiles(path.join(SRC_DIR, "cli/command"));
