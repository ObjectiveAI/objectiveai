type Schema = map[string]any

// ---------------------------------------------------------------------------
// Naming helpers
// ---------------------------------------------------------------------------

var (
	reUpperUpper = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
	reLowerUpper = regexp.MustCompile(`([a-z0-9])([A-Z])`)
)

func toSnake(name string) string {
	s := reUpperUpper.ReplaceAllString(name, "${1}_${2}")
	s = reLowerUpper.ReplaceAllString(s, "${1}_${2}")
	return strings.ToLower(s)
}

// toPascal converts a dot/underscore/hyphen-separated title to
// PascalCase. "agent.openrouter.Agent" → "AgentOpenrouterAgent".
// Hyphens may appear in string-enum variant titles in future SDKs,
// so we accept them here too.
func toPascal(title string) string {
	parts := regexp.MustCompile(`[._-]`).Split(title, -1)
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		runes := []rune(p)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}
	return b.String()
}

// goFieldName converts a JSON property name to an exported Go field name.
func goFieldName(propName string) string {
	cleaned := strings.TrimLeft(propName, "$")
	if cleaned == "" {
		cleaned = "Val"
	}
	// Split on underscores, forward slashes, AND dots. Enum renames
	// like `"POST_/agent/completions"` (viewer.ApiCallSubType) and
	// variant titles like `"client_objectiveai_mcp.client_response.Response.Ok"`
	// (anyOf variants in tagged-enum schemas) must collapse to a
	// valid Go identifier (`POSTAgentCompletions`, `ClientObjectiveaiMcpClientResponseResponseOk`).
	parts := strings.FieldsFunc(cleaned, func(r rune) bool {
		return r == '_' || r == '/' || r == '.'
	})
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		upper := strings.ToUpper(p)
		switch upper {
		case "ID", "URL", "URI", "API", "HTTP", "HTTPS", "JSON", "XML", "SQL",
			"HTML", "CSS", "IP", "TCP", "UDP", "DNS", "SSH", "TLS", "SSL",
			"UUID", "MCP", "SDK", "RNG", "LLM":
			b.WriteString(upper)
		default:
			runes := []rune(p)
			runes[0] = unicode.ToUpper(runes[0])
			b.WriteString(string(runes))
		}
	}
	return b.String()
}

