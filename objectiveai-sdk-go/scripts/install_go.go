// generateValidateMethod generates a Validate() method for a struct.
// For variant structs with multiple variants, it also asserts exactly one is non-nil.
func generateValidateMethod(typeName string, variantFieldNames []string) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf("func (v %s) Validate() error {\n", typeName))

	if len(variantFieldNames) > 1 {
		// Multi-variant: assert exactly one non-nil
		b.WriteString("\tcount := 0\n")
		for _, fn := range variantFieldNames {
			b.WriteString(fmt.Sprintf("\tif v.%s != nil { count++ }\n", fn))
		}
		b.WriteString(fmt.Sprintf("\tif count != 1 {\n\t\treturn fmt.Errorf(\"%s: exactly one variant must be set, got %%d\", count)\n\t}\n", typeName))
	}

	b.WriteString("\treturn variantValidator.Struct(v)\n")
	b.WriteString("}\n")
	return b.String()
}

