func generateTypeCode(title string, schema Schema, allTitles map[string]bool) string {
	typeName := toPascal(title)
	var b strings.Builder

	// Case 1: Object with properties
	if schema["properties"] != nil {
		b.WriteString(generateStruct(typeName, schema, title, allTitles))
		b.WriteString("\n")
		b.WriteString(fmt.Sprintf("func (%s) SchemaTitle() string { return %q }\n", typeName, title))
		b.WriteString(generateValidateMethod(typeName, nil))
		if unmarshal := generateStrictUnmarshal(typeName, schema, title, allTitles); unmarshal != "" {
			b.WriteString("\n")
			b.WriteString(unmarshal)
		}
		// Structs with $ref embedding need custom MarshalJSON to merge
		// embedded and local fields (embedded MarshalJSON shadows local fields)
		if ref, ok := schema["$ref"].(string); ok {
			if properties, ok := schema["properties"].(map[string]any); ok && len(properties) > 0 {
				b.WriteString(generateEmbedMarshal(typeName, toPascal(ref), properties, title, allTitles))
			}
		}
		return b.String()
	}

	// Case 2: anyOf
	if anyOf, ok := schema["anyOf"].([]any); ok {
		nonNull, hasNull := splitNullVariants(anyOf)
		if hasNull && len(nonNull) == 1 {
			// Simple nullable — type definition
			goT := goType(nonNull[0], title, allTitles)
			if goT != "any" && !strings.HasPrefix(goT, "*") {
				goT = "*" + goT
			}
			desc, _ := schema["description"].(string)
			b.WriteString(goDocComment(desc, ""))
			b.WriteString(fmt.Sprintf("type %s %s\n\n", typeName, goT))
			b.WriteString(fmt.Sprintf("func (%s) SchemaTitle() string { return %q }\n", typeName, title))
		} else {
			// anyOf struct with variant fields
			b.WriteString(generateAnyOfStruct(typeName, anyOf, title, schema, allTitles, false))
			b.WriteString(fmt.Sprintf("func (%s) SchemaTitle() string { return %q }\n", typeName, title))
			b.WriteString("\n")
		}
		return b.String()
	}

	// Case 3: Root string enum → one variant per enum value
	if schema["type"] == "string" && schema["enum"] != nil {
		enumVals, _ := schema["enum"].([]any)
		var syntheticAnyOf []any
		for _, ev := range enumVals {
			s := fmt.Sprintf("%v", ev)
			syntheticAnyOf = append(syntheticAnyOf, Schema{
				"title": toPascal(s),
				"type":  "string",
				"enum":  []any{ev},
			})
		}
		b.WriteString(generateAnyOfStruct(typeName, syntheticAnyOf, title, schema, allTitles, true))
		b.WriteString(fmt.Sprintf("func (%s) SchemaTitle() string { return %q }\n", typeName, title))
		b.WriteString("\n")
		return b.String()
	}

	// Case 4a: $ref without properties → struct embedding the referenced type
	if ref, ok := schema["$ref"].(string); ok {
		desc, _ := schema["description"].(string)
		b.WriteString(goDocComment(desc, ""))
		b.WriteString(fmt.Sprintf("type %s struct {\n\t%s\n}\n\n", typeName, toPascal(ref)))
		b.WriteString(fmt.Sprintf("func (%s) SchemaTitle() string { return %q }\n", typeName, title))
		b.WriteString(generateValidateMethod(typeName, nil))
		return b.String()
	}

	// Case 4b: Object with no properties and additionalProperties: false →
	// closed empty struct (rather than the open OrderedMap that the
	// generic object-with-no-properties path would emit).
	if schema["type"] == "object" {
		if ap, ok := schema["additionalProperties"]; ok && ap == false {
			desc, _ := schema["description"].(string)
			b.WriteString(goDocComment(desc, ""))
			b.WriteString(fmt.Sprintf("type %s struct{}\n\n", typeName))
			b.WriteString(fmt.Sprintf("func (%s) SchemaTitle() string { return %q }\n", typeName, title))
			b.WriteString(fmt.Sprintf("\nfunc (%s) AdditionalProperties() bool { return false }\n", typeName))
			return b.String()
		}
	}

	// Case 4c: Non-anyOf, non-struct, non-enum, non-ref (primitive, array, map)
	goT := determinePrimitiveGoType(schema, title, allTitles)
	desc, _ := schema["description"].(string)
	b.WriteString(goDocComment(desc, ""))
	b.WriteString(fmt.Sprintf("type %s %s\n\n", typeName, goT))
	b.WriteString(fmt.Sprintf("func (%s) SchemaTitle() string { return %q }\n", typeName, title))
	if vt := orderedMapValueType(goT); vt != "" {
		b.WriteString(generateOrderedMapMethods(typeName, vt))
	}
	return b.String()
}

func determinePrimitiveGoType(schema Schema, title string, allTitles map[string]bool) string {
	if _, ok := schema["enum"]; ok {
		return "string"
	}
	if _, ok := schema["$ref"]; ok {
		return "JsonValue"
	}
	t, _ := schema["type"].(string)
	switch t {
	case "array":
		if items, ok := schema["items"].(map[string]any); ok {
			return "[]" + goType(items, title, allTitles)
		}
		return "[]JsonValue"
	case "object":
		if ap, ok := schema["additionalProperties"]; ok {
			if apMap, ok := ap.(map[string]any); ok {
				return "OrderedMap[string, " + goType(apMap, title, allTitles) + "]"
			}
			return "OrderedMap[string,JsonValue]"
		}
		return "OrderedMap[string,JsonValue]"
	case "string":
		return "string"
	case "integer":
		return goIntType(schema)
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	}
	return "JsonValue"
}

