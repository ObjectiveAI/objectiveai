func generateStruct(typeName string, schema Schema, selfTitle string, allTitles map[string]bool) string {
	properties, _ := schema["properties"].(map[string]any)
	var auxiliary strings.Builder
	var b strings.Builder

	// Type doc comment
	desc, _ := schema["description"].(string)
	b.WriteString(goDocComment(desc, ""))
	b.WriteString(fmt.Sprintf("type %s struct {\n", typeName))

	// Embed $ref type if present (adjacently-tagged: $ref + properties)
	if ref, ok := schema["$ref"].(string); ok {
		b.WriteString(fmt.Sprintf("\t%s\n", toPascal(ref)))
	}

	propNames := sortedKeys(properties)
	for _, propName := range propNames {
		// A property schema of `true` means "any value allowed" — emit
		// the field as JsonValue. (Schemars produces this for fields
		// whose Rust type is `serde_json::Value` with no other
		// constraints, e.g. JsonRpcRequest::id.) `false` means "no
		// value allowed", so skip the field entirely.
		var propSchema map[string]any
		switch v := properties[propName].(type) {
		case map[string]any:
			propSchema = v
		case bool:
			if !v {
				continue
			}
			propSchema = map[string]any{}
		default:
			continue
		}
		fieldName := goFieldName(propName)

		// Check if this field needs an inline variant struct (multi-variant anyOf)
		fieldType := resolveFieldTypeWithInline(propSchema, selfTitle, allTitles, typeName, fieldName, &auxiliary)

		// Field doc comment
		fieldDesc, _ := propSchema["description"].(string)
		b.WriteString(goDocComment(fieldDesc, "\t"))

		jsonTag := propName
		if oe, _ := propSchema["omitempty"].(bool); oe {
			jsonTag += ",omitempty"
		}

		tags := buildStructTags(jsonTag, propSchema, selfTitle, allTitles)
		b.WriteString(fmt.Sprintf("\t%s %s %s\n", fieldName, fieldType, tags))
	}
	b.WriteString("}\n")

	// additionalProperties method (only when explicitly set in schema)
	if ap, ok := schema["additionalProperties"]; ok {
		if ap == false {
			b.WriteString(fmt.Sprintf("\nfunc (%s) AdditionalProperties() bool { return false }\n", typeName))
		} else if ap == true {
			b.WriteString(fmt.Sprintf("\nfunc (%s) AdditionalProperties() bool { return true }\n", typeName))
		}
	}

	// Prepend any inline types before the struct
	return auxiliary.String() + b.String()
}

// resolveFieldTypeWithInline handles multi-variant anyOf by generating inline
// variant structs. Falls back to resolveFieldType for everything else.
func resolveFieldTypeWithInline(propSchema Schema, selfTitle string, allTitles map[string]bool, parentType string, fieldName string, aux *strings.Builder) string {
	// Get the constraint schema (strip nullable wrapper if present)
	cs := propSchema
	nullable := isNullable(propSchema)
	if nullable {
		cs = getNonNullVariant(propSchema)
	}

	// Check for multi-variant anyOf that would resolve to "any"
	if anyOf, ok := cs["anyOf"].([]any); ok {
		nonNull, _ := splitNullVariants(anyOf)
		if len(nonNull) >= 2 {
			// Generate an inline variant struct
			inlineName := parentType + fieldName
			inlineSchema := Schema{}
			if desc, ok := cs["description"].(string); ok {
				inlineSchema["description"] = desc
			}
			aux.WriteString(generateAnyOfStruct(inlineName, anyOf, selfTitle, inlineSchema, allTitles, false))
			if nullable {
				return "*" + inlineName
			}
			return inlineName
		}
	}

	// Check for array with items containing multi-variant anyOf
	if cs["type"] == "array" {
		if items, ok := cs["items"].(map[string]any); ok {
			if itemsAnyOf, ok := items["anyOf"].([]any); ok {
				nonNull, _ := splitNullVariants(itemsAnyOf)
				if len(nonNull) >= 2 {
					itemName := parentType + fieldName + "Item"
					if fieldName == "" {
						itemName = parentType + "Item"
					}
					itemSchema := Schema{}
					if desc, ok := items["description"].(string); ok {
						itemSchema["description"] = desc
					}
					aux.WriteString(generateAnyOfStruct(itemName, itemsAnyOf, selfTitle, itemSchema, allTitles, false))
					goT := "[]" + itemName
					if nullable {
						return "*" + goT
					}
					return goT
				}
			}
		}
	}

	// Check for object with additionalProperties containing multi-variant anyOf
	if cs["type"] == "object" {
		if ap, ok := cs["additionalProperties"].(map[string]any); ok {
			if apAnyOf, ok := ap["anyOf"].([]any); ok {
				nonNull, _ := splitNullVariants(apAnyOf)
				if len(nonNull) >= 2 {
					valName := parentType + fieldName + "Value"
					if fieldName == "" {
						valName = parentType + "Value"
					}
					valSchema := Schema{}
					if desc, ok := ap["description"].(string); ok {
						valSchema["description"] = desc
					}
					aux.WriteString(generateAnyOfStruct(valName, apAnyOf, selfTitle, valSchema, allTitles, false))
					goT := "OrderedMap[string, " + valName + "]"
					if nullable {
						return "*" + goT
					}
					return goT
				}
			}
		}
	}

	return resolveFieldType(propSchema, selfTitle, allTitles)
}

func resolveFieldType(propSchema Schema, selfTitle string, allTitles map[string]bool) string {
	if isNullable(propSchema) {
		nonNull := getNonNullVariant(propSchema)
		inner := goType(nonNull, selfTitle, allTitles)
		if inner == "any" || strings.HasPrefix(inner, "*") {
			return inner
		}
		return "*" + inner
	}
	return goType(propSchema, selfTitle, allTitles)
}

func buildStructTags(jsonTag string, propSchema Schema, selfTitle string, allTitles map[string]bool) string {
	var tags []string
	if jsonTag != "" {
		tags = append(tags, fmt.Sprintf("json:%q", jsonTag))
	}

	nullable := isNullable(propSchema)
	var cs Schema // constraint schema
	if nullable {
		cs = getNonNullVariant(propSchema)
	} else {
		cs = propSchema
	}

	// Build validate tag parts
	var validates []string
	if enumVals, ok := cs["enum"].([]any); ok {
		parts := make([]string, len(enumVals))
		for i, v := range enumVals {
			parts[i] = fmt.Sprintf("%v", v)
		}
		validates = append(validates, "oneof="+strings.Join(parts, " "))
	}
	if v, ok := cs["minimum"]; ok {
		validates = append(validates, "min="+formatTagNumber(v))
	}
	if v, ok := cs["maximum"]; ok {
		validates = append(validates, "max="+formatTagNumber(v))
	}

	// Array items / map value constraints via dive (recursive for nested arrays)
	// Each nesting level adds a "dive" before the final min/max constraints.
	cur := cs
	diveDepth := 0
	for {
		var next Schema
		if items, ok := cur["items"].(map[string]any); ok {
			next = items
		} else if ap, ok := cur["additionalProperties"].(map[string]any); ok {
			next = ap
		}
		if next == nil {
			break
		}
		diveDepth++
		if _, hasMin := next["minimum"]; hasMin {
			for i := 0; i < diveDepth; i++ {
				validates = append(validates, "dive")
			}
			validates = append(validates, "min="+formatTagNumber(next["minimum"]))
			if v, ok := next["maximum"]; ok {
				validates = append(validates, "max="+formatTagNumber(v))
			}
			break
		} else if _, hasMax := next["maximum"]; hasMax {
			for i := 0; i < diveDepth; i++ {
				validates = append(validates, "dive")
			}
			validates = append(validates, "max="+formatTagNumber(next["maximum"]))
			break
		}
		cur = next
	}

	if len(validates) > 0 {
		// Nullable fields need omitempty so the validator skips nil pointers
		if nullable {
			validates = append([]string{"omitempty"}, validates...)
		}
		tags = append(tags, fmt.Sprintf("validate:%q", strings.Join(validates, ",")))
	}

	// pattern tag
	if pat, ok := cs["pattern"].(string); ok {
		tags = append(tags, fmt.Sprintf("pattern:%q", pat))
	}

	// default tag
	if def, ok := cs["default"]; ok {
		tags = append(tags, fmt.Sprintf("default:%q", formatTagDefault(def)))
	}

	// Mark fields whose source schema was `{"type": "null"}` so the
	// roundtrip harness can re-emit `"type": "null"` (the Go type is
	// `JsonValue`, which would otherwise reconstruct to `{}`).
	if isSimpleNull(cs) {
		tags = append(tags, `nullType:"true"`)
	}

	if len(tags) == 0 {
		return ""
	}
	return "`" + strings.Join(tags, " ") + "`"
}

