// generateStrictUnmarshal generates UnmarshalJSON that rejects missing required fields.
// Required = non-pointer Go type. Returns empty string if no required fields.
func generateStrictUnmarshal(typeName string, schema Schema, selfTitle string, allTitles map[string]bool) string {
	properties, _ := schema["properties"].(map[string]any)
	if len(properties) == 0 {
		return ""
	}

	var required []string
	for _, propName := range sortedKeys(properties) {
		propSchema, ok := properties[propName].(map[string]any)
		if !ok {
			continue
		}
		var discard strings.Builder
		fieldType := resolveFieldTypeWithInline(propSchema, selfTitle, allTitles, typeName, goFieldName(propName), &discard)
		if !strings.HasPrefix(fieldType, "*") {
			jsonName := strings.Split(propName, ",")[0]
			required = append(required, jsonName)
		}
	}

	if len(required) == 0 {
		return ""
	}

	var b strings.Builder
	b.WriteString(fmt.Sprintf("func (v *%s) UnmarshalJSON(data []byte) error {\n", typeName))
	b.WriteString("\tvar raw map[string]json.RawMessage\n")
	b.WriteString("\tif err := json.Unmarshal(data, &raw); err != nil {\n\t\treturn err\n\t}\n")

	// Build required keys list
	b.WriteString("\tfor _, key := range []string{")
	for i, r := range required {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(fmt.Sprintf("%q", r))
	}
	b.WriteString("} {\n")
	b.WriteString("\t\tif _, ok := raw[key]; !ok {\n")
	b.WriteString(fmt.Sprintf("\t\t\treturn fmt.Errorf(\"%s: missing required field %%q\", key)\n", typeName))
	b.WriteString("\t\t}\n\t}\n")

	// Unmarshal — handle embedded types separately to avoid their UnmarshalJSON
	if ref, ok := schema["$ref"].(string); ok {
		embedType := toPascal(ref)
		b.WriteString(fmt.Sprintf("\tif err := json.Unmarshal(data, &v.%s); err != nil {\n\t\treturn err\n\t}\n", embedType))
		// Unmarshal local fields individually from raw
		for _, pn := range sortedKeys(properties) {
			fn := goFieldName(pn)
			b.WriteString(fmt.Sprintf("\tif rawField, ok := raw[%q]; ok {\n", pn))
			b.WriteString(fmt.Sprintf("\t\tif err := json.Unmarshal(rawField, &v.%s); err != nil {\n\t\t\treturn err\n\t\t}\n", fn))
			b.WriteString("\t}\n")
		}
	} else {
		b.WriteString(fmt.Sprintf("\ttype Alias %s\n", typeName))
		b.WriteString("\tvar alias Alias\n")
		b.WriteString("\tif err := json.Unmarshal(data, &alias); err != nil {\n\t\treturn err\n\t}\n")
		b.WriteString(fmt.Sprintf("\t*v = %s(alias)\n", typeName))
	}
	b.WriteString("\treturn nil\n")
	b.WriteString("}\n")

	return b.String()
}

// generateOrderedMapMethods generates a constructor and JSON marshal/unmarshal
// forwarding for a named type defined as OrderedMap[string, V].
// Go type definitions don't inherit methods, so we forward manually.
func generateOrderedMapMethods(typeName string, valueType string) string {
	var b strings.Builder
	omType := fmt.Sprintf("OrderedMap[string, %s]", valueType)
	pairType := fmt.Sprintf("orderedmap.Pair[string, %s]", valueType)

	// Constructor
	b.WriteString(fmt.Sprintf("func New%s(pairs ...%s) %s {\n", typeName, pairType, typeName))
	b.WriteString(fmt.Sprintf("\treturn %s(NewOrderedMap[string, %s](pairs...))\n", typeName, valueType))
	b.WriteString("}\n\n")

	// MarshalJSON
	b.WriteString(fmt.Sprintf("func (v %s) MarshalJSON() ([]byte, error) {\n", typeName))
	b.WriteString(fmt.Sprintf("\treturn %s(v).MarshalJSON()\n", omType))
	b.WriteString("}\n\n")

	// UnmarshalJSON
	b.WriteString(fmt.Sprintf("func (v *%s) UnmarshalJSON(data []byte) error {\n", typeName))
	b.WriteString(fmt.Sprintf("\treturn (*%s)(v).UnmarshalJSON(data)\n", omType))
	b.WriteString("}\n\n")

	return b.String()
}

// orderedMapValueType extracts the value type V from "OrderedMap[string,V]".
// Returns "" if the type is not an ordered map.
func orderedMapValueType(goT string) string {
	const prefix = "OrderedMap[string, "
	if strings.HasPrefix(goT, prefix) && strings.HasSuffix(goT, "]") {
		return goT[len(prefix) : len(goT)-1]
	}
	return ""
}

// generateEmbedMarshal generates MarshalJSON for structs that embed a type
// with its own MarshalJSON. Merges the embedded type's JSON with local fields.
func generateEmbedMarshal(typeName string, embedType string, properties map[string]any, selfTitle string, allTitles map[string]bool) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf("\nfunc (v %s) MarshalJSON() ([]byte, error) {\n", typeName))
	b.WriteString(fmt.Sprintf("\tbase, err := json.Marshal(v.%s)\n", embedType))
	b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	b.WriteString("\tvar merged map[string]json.RawMessage\n")
	b.WriteString("\tjson.Unmarshal(base, &merged)\n")
	// Marshal each local field individually
	for _, pn := range sortedKeys(properties) {
		fn := goFieldName(pn)
		nullable := false
		if ps, ok := properties[pn].(map[string]any); ok {
			nullable = isNullable(ps)
		}
		if nullable {
			b.WriteString(fmt.Sprintf("\tif v.%s != nil {\n", fn))
			b.WriteString(fmt.Sprintf("\t\tif raw, err := json.Marshal(v.%s); err == nil {\n\t\t\tmerged[%q] = raw\n\t\t}\n", fn, pn))
			b.WriteString("\t}\n")
		} else {
			b.WriteString(fmt.Sprintf("\tif raw, err := json.Marshal(v.%s); err == nil {\n\t\tmerged[%q] = raw\n\t}\n", fn, pn))
		}
	}
	b.WriteString("\treturn json.Marshal(merged)\n")
	b.WriteString("}\n")
	return b.String()
}

