func main() {
	entries, err := os.ReadDir(schemaDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading schema dir %s: %v\n", schemaDir, err)
		os.Exit(1)
	}

	schemas := map[string]Schema{}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(schemaDir, entry.Name()))
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error reading %s: %v\n", entry.Name(), err)
			os.Exit(1)
		}
		dec := json.NewDecoder(strings.NewReader(string(data)))
		dec.UseNumber()
		var schema Schema
		if err := dec.Decode(&schema); err != nil {
			fmt.Fprintf(os.Stderr, "Error parsing %s: %v\n", entry.Name(), err)
			os.Exit(1)
		}
		if title, ok := schema["title"].(string); ok {
			schemas[title] = schema
		}
	}

	fmt.Printf("Read %d schemas\n", len(schemas))

	allTitles := map[string]bool{}
	for t := range schemas {
		allTitles[t] = true
	}
	genericPrefixes = detectGenericPrefixes(allTitles)

	// Clean auto-generated files from the target directory.
	cleanGenerated(srcDir)

	// Group by file path
	type fileEntry struct {
		title  string
		schema Schema
	}
	fileGroups := map[string][]fileEntry{}
	for title, schema := range schemas {
		fp := titleToFilePath(title)
		fileGroups[fp] = append(fileGroups[fp], fileEntry{title, schema})
	}

	filePaths := make([]string, 0, len(fileGroups))
	for fp := range fileGroups {
		filePaths = append(filePaths, fp)
	}
	sort.Strings(filePaths)

	fmt.Printf("Generating %d .go files (single package)\n", len(filePaths))

	for _, fp := range filePaths {
		fes := fileGroups[fp]
		sort.Slice(fes, func(i, j int) bool { return fes[i].title < fes[j].title })

		var codes []string
		for _, fe := range fes {
			codes = append(codes, generateTypeCode(fe.title, fe.schema, allTitles))
		}

		fullCode := strings.Join(codes, "\n")
		needsJSON := strings.Contains(fullCode, "json.Marshal") || strings.Contains(fullCode, "json.Unmarshal") || strings.Contains(fullCode, "json.Number") || strings.Contains(fullCode, "json.RawMessage")
		needsFmt := strings.Contains(fullCode, "fmt.Errorf")
		needsTime := strings.Contains(fullCode, "time.Time")
		needsUUID := strings.Contains(fullCode, "uuid.UUID")
		needsOrderedMap := strings.Contains(fullCode, "orderedmap.")

		var file strings.Builder
		file.WriteString(generatedHeader)
		file.WriteString("package objectiveai\n")
		if needsJSON || needsFmt || needsTime || needsUUID || needsOrderedMap {
			file.WriteString("\nimport (\n")
			if needsJSON {
				file.WriteString("\t\"encoding/json\"\n")
			}
			if needsFmt {
				file.WriteString("\t\"fmt\"\n")
			}
			if needsTime {
				file.WriteString("\t\"time\"\n")
			}
			if needsUUID {
				file.WriteString("\t\"github.com/google/uuid\"\n")
			}
			if needsOrderedMap {
				file.WriteString("\torderedmap \"github.com/wk8/go-ordered-map/v2\"\n")
			}
			file.WriteString(")\n")
		}
		file.WriteString("\n")
		file.WriteString(fullCode)

		outPath := filepath.Join(srcDir, fp+".go")
		if err := os.WriteFile(outPath, []byte(file.String()), 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "Error writing %s: %v\n", outPath, err)
			os.Exit(1)
		}
	}

	// Emit validator registration for all OrderedMap instantiations.
	// Scan all generated code for OrderedMap[string, V] patterns.
	omRegex := regexp.MustCompile(`OrderedMap\[string,\s*([^\]]+?)\s*\]`)
	omTypes := map[string]bool{}
	for _, fp := range filePaths {
		data, _ := os.ReadFile(filepath.Join(srcDir, fp+".go"))
		for _, match := range omRegex.FindAllStringSubmatch(string(data), -1) {
			omTypes[match[1]] = true
		}
	}
	if len(omTypes) > 0 {
		var reg strings.Builder
		reg.WriteString(generatedHeader)
		reg.WriteString("package objectiveai\n\n")
		reg.WriteString("func init() {\n")
		reg.WriteString("\tRegisterOrderedMapTypes(variantValidator,\n")
		sortedOM := make([]string, 0, len(omTypes))
		for vt := range omTypes {
			sortedOM = append(sortedOM, vt)
		}
		sort.Strings(sortedOM)
		for _, vt := range sortedOM {
			reg.WriteString(fmt.Sprintf("\t\tOrderedMap[string, %s]{},\n", vt))
		}
		reg.WriteString("\t)\n")
		reg.WriteString("}\n")
		outPath := filepath.Join(srcDir, "orderedmap_registered.go")
		if err := os.WriteFile(outPath, []byte(reg.String()), 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "Error writing %s: %v\n", outPath, err)
			os.Exit(1)
		}
	}

	fmt.Printf("Generated %d type files\nDone!\n", len(filePaths))
}

func cleanGenerated(dir string) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return
	}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		if !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		fullPath := filepath.Join(dir, entry.Name())
		data, err := os.ReadFile(fullPath)
		if err != nil {
			continue
		}
		if len(data) >= 128 && strings.Contains(string(data[:128]), "THIS FILE IS AUTO-GENERATED") {
			os.Remove(fullPath)
		}
	}
}
