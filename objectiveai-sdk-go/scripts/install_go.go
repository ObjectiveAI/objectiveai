// goType converts a JSON schema node to a Go type string.
// $ref fields are now properly typed since everything is one package.
func goType(schema Schema, selfTitle string, allTitles map[string]bool) string {
	if schema == nil || len(schema) == 0 {
		return "JsonValue"
	}
	if ref, ok := schema["$ref"].(string); ok {
		if ref == "#" {
			return "*" + toPascal(selfTitle) // self-ref needs pointer to break infinite size
		}
		return toPascal(ref)
	}
	if _, ok := schema["enum"]; ok {
		return "string"
	}
	if anyOf, ok := schema["anyOf"].([]any); ok {
		return goTypeAnyOf(anyOf, selfTitle, allTitles)
	}
	if t, ok := schema["type"].(string); ok {
		return goTypeSingle(t, schema, selfTitle, allTitles)
	}
	if _, ok := schema["properties"]; ok {
		return "JsonValue"
	}
	return "JsonValue"
}

func goTypeAnyOf(anyOf []any, selfTitle string, allTitles map[string]bool) string {
	var nonNull []Schema
	hasNull := false
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}
		if isSimpleNull(m) {
			hasNull = true
		} else {
			nonNull = append(nonNull, m)
		}
	}
	if hasNull && len(nonNull) == 1 {
		inner := goType(nonNull[0], selfTitle, allTitles)
		if inner == "JsonValue" || strings.HasPrefix(inner, "*") {
			return inner
		}
		return "*" + inner
	}
	return "JsonValue"
}

func goTypeSingle(t string, schema Schema, selfTitle string, allTitles map[string]bool) string {
	switch t {
	case "string":
		if fmt_, ok := schema["format"].(string); ok {
			switch fmt_ {
			case "uuid":
				return "uuid.UUID"
			case "date-time":
				return "time.Time"
			}
		}
		return "string"
	case "integer":
		return goIntType(schema)
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "null":
		return "JsonValue"
	case "array":
		if items, ok := schema["items"].(map[string]any); ok {
			return "[]" + goType(items, selfTitle, allTitles)
		}
		return "[]JsonValue"
	case "object":
		if ap, ok := schema["additionalProperties"]; ok {
			if apMap, ok := ap.(map[string]any); ok {
				return "OrderedMap[string, " + goType(apMap, selfTitle, allTitles) + "]"
			}
			if ap == true {
				return "OrderedMap[string,JsonValue]"
			}
		}
		if _, ok := schema["properties"]; !ok {
			return "struct{}"
		}
		return "JsonValue"
	}
	return "JsonValue"
}

func goIntType(schema Schema) string {
	minVal, hasMin := getNumber(schema, "minimum")
	maxVal, hasMax := getNumber(schema, "maximum")
	if hasMin && hasMax {
		if minVal >= 0 && maxVal == math.MaxUint64 {
			return "uint64"
		}
		if minVal >= 0 && maxVal <= math.MaxUint32 {
			return "uint32"
		}
		if minVal >= 0 && maxVal <= math.MaxUint16 {
			return "uint16"
		}
		if minVal >= 0 && maxVal <= math.MaxUint8 {
			return "uint8"
		}
		if minVal >= math.MinInt8 && maxVal <= math.MaxInt8 {
			return "int8"
		}
		if minVal >= math.MinInt16 && maxVal <= math.MaxInt16 {
			return "int16"
		}
		if minVal >= math.MinInt32 && maxVal <= math.MaxInt32 {
			return "int32"
		}
	}
	return "int64"
}

func getNumber(schema Schema, key string) (float64, bool) {
	v, ok := schema[key]
	if !ok {
		return 0, false
	}
	switch n := v.(type) {
	case float64:
		return n, true
	case json.Number:
		f, _ := n.Float64()
		return f, true
	case int64:
		return float64(n), true
	}
	return 0, false
}

// ---------------------------------------------------------------------------
// Schema analysis
// ---------------------------------------------------------------------------

func isSimpleNull(v Schema) bool {
	return len(v) == 1 && v["type"] == "null"
}

func isNullable(propSchema Schema) bool {
	anyOf, ok := propSchema["anyOf"].([]any)
	if !ok {
		return false
	}
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if ok && isSimpleNull(m) {
			return true
		}
	}
	return false
}

func getNonNullVariant(propSchema Schema) Schema {
	anyOf, ok := propSchema["anyOf"].([]any)
	if !ok {
		return propSchema
	}
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}
		if !isSimpleNull(m) {
			return m
		}
	}
	return propSchema
}

func splitNullVariants(anyOf []any) (nonNull []Schema, hasNull bool) {
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}
		if isSimpleNull(m) {
			hasNull = true
		} else {
			nonNull = append(nonNull, m)
		}
	}
	return
}

