// generateAnyOfStruct generates a struct with nullable Variant1..VariantN fields,
// plus any needed VariantN sub-structs for inline object variants.
func generateAnyOfStruct(typeName string, anyOf []any, selfTitle string, schema Schema, allTitles map[string]bool, isEnum bool) string {
	var auxiliary strings.Builder // sub-structs generated before the main type
	var fields []string

	// Count non-null variants to determine if fields should be nullable
	nonNullCount := 0
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if ok && !isSimpleNull(m) {
			nonNullCount++
		}
	}
	singleVariant := nonNullCount == 1

	var variantFieldNames []string
	var variantFieldTypes []string // the Go type WITHOUT pointer prefix
	var variantValidateTags []string // validate tag value for each variant (empty if none)
	var variantIsPointer []bool // whether the field is a pointer type

	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}

		// Determine variant field name from schema title, falling back
		// to the single-value `type` discriminator (internally-tagged
		// enum variants without explicit titles — e.g. Ok/Error in a
		// `#[serde(tag = "type")]` enum where schemars 1.x emits no
		// per-variant title).
		variantTitle, _ := m["title"].(string)
		if variantTitle == "" {
			if props, ok := m["properties"].(map[string]any); ok {
				if typeProp, ok := props["type"].(map[string]any); ok {
					if enumVals, ok := typeProp["enum"].([]any); ok && len(enumVals) == 1 {
						if val, ok := enumVals[0].(string); ok {
							variantTitle = val
						}
					}
				}
			}
		}
		var fieldName, vStructName string
		if variantTitle != "" {
			fieldName = goFieldName(variantTitle)
			vStructName = typeName + fieldName
		} else {
			panic(fmt.Sprintf("variant in %s has no title", typeName))
		}

		variantDesc, _ := m["description"].(string)

		if isSimpleNull(m) {
			continue
		}

		// Determine Go type for the variant field
		var fieldType string
		if _, ok := m["properties"].(map[string]any); ok {
			// Inline object variant → generate a sub-struct + SchemaVariantTitle
			auxiliary.WriteString(generateInlineVariantStruct(vStructName, m, selfTitle, allTitles))
			auxiliary.WriteString(fmt.Sprintf("func (%s) SchemaVariantTitle() string { return %q }\n\n", vStructName, variantTitle))
			if singleVariant {
				fieldType = vStructName
			} else {
				fieldType = "*" + vStructName
			}
		} else if _, ok := m["$ref"].(string); ok {
			// $ref variant → use the referenced type directly (it has SchemaTitle)
			goT := goType(m, selfTitle, allTitles)
			if singleVariant {
				fieldType = goT
			} else if strings.HasPrefix(goT, "*") {
				fieldType = goT
			} else {
				fieldType = "*" + goT
			}
		} else if !isEnum {
			// Primitive variant → type definition + SchemaVariantTitle
			goT := resolveFieldTypeWithInline(m, selfTitle, allTitles, vStructName, "", &auxiliary)
			// Strip pointer — nullable is tracked on the parent field via nullable tag
			goT = strings.TrimPrefix(goT, "*")
			// If resolveFieldTypeWithInline already emitted a struct under
			// vStructName (nested anyOf case), don't emit `type X X` self-alias.
			if goT != vStructName {
				auxiliary.WriteString(fmt.Sprintf("type %s %s\n\n", vStructName, goT))
			}
			auxiliary.WriteString(fmt.Sprintf("func (%s) SchemaVariantTitle() string { return %q }\n\n", vStructName, variantTitle))
			// Go type definitions don't inherit methods from the underlying type,
			// so we forward marshal/unmarshal for special types.
			if goT == "JsonValue" {
				auxiliary.WriteString(fmt.Sprintf("func (v %s) MarshalJSON() ([]byte, error) { return json.Marshal(JsonValue(v)) }\n", vStructName))
				auxiliary.WriteString(fmt.Sprintf("func (v *%s) UnmarshalJSON(data []byte) error { return json.Unmarshal(data, (*JsonValue)(v)) }\n\n", vStructName))
			} else if vt := orderedMapValueType(goT); vt != "" {
				auxiliary.WriteString(generateOrderedMapMethods(vStructName, vt))
			}
			if singleVariant {
				fieldType = vStructName
			} else {
				fieldType = "*" + vStructName
			}
		} else {
			// Root enum variant → bare type
			goT := goType(m, selfTitle, allTitles)
			if singleVariant {
				fieldType = goT
			} else if goT == "any" || strings.HasPrefix(goT, "*") {
				fieldType = goT
			} else {
				fieldType = "*" + goT
			}
		}

		// Track for marshal/unmarshal generation
		variantFieldNames = append(variantFieldNames, fieldName)
		baseType := strings.TrimPrefix(fieldType, "*")
		variantFieldTypes = append(variantFieldTypes, baseType)
		variantIsPointer = append(variantIsPointer, strings.HasPrefix(fieldType, "*"))
		variantValidateTags = append(variantValidateTags, buildValidateValue(m))

		// Build variant field tags — prepend omitempty to validate
		// (nil variant fields must pass validation)
		var variantTags []string
		if constraintTags := buildStructTags("", m, selfTitle, allTitles); constraintTags != "" {
			inner := strings.TrimPrefix(strings.TrimSuffix(constraintTags, "`"), "`")
			// Prepend omitempty to validate tag so nil fields are skipped
			inner = strings.Replace(inner, `validate:"`, `validate:"omitempty,`, 1)
			variantTags = append(variantTags, inner)
		}
		// Preserve schemars's `type: "object"` stamp alongside a variant's
		// `$ref`. schemars adds this whenever the outer schema is committed
		// to being an object (a struct that flattens an untagged enum, or
		// an internally-tagged enum). The roundtrip harness reads this tag
		// to re-emit `"type": "object"` next to the `$ref`. Inline-struct
		// variants already emit `type: "object"` naturally; the marker is
		// only needed for the pure-$ref path.
		if t, _ := m["type"].(string); t == "object" {
			variantTags = append(variantTags, `outerObject:"true"`)
		}
		// Preserve the variant title from the source schema. Go field
		// names diverge from the title for acronyms ("Mcp" → "MCP" per
		// Go conventions); the roundtrip harness needs the original
		// title to emit a matching schema. Inline / primitive variants
		// already expose this via SchemaVariantTitle(), but $ref
		// variants don't — the field tag covers them.
		if variantTitle != "" && variantTitle != fieldName {
			variantTags = append(variantTags, fmt.Sprintf(`variantTitle:%q`, variantTitle))
		}
		var tagStr string
		if len(variantTags) > 0 {
			tagStr = "`" + strings.Join(variantTags, " ") + "`"
		}
		fields = append(fields, goDocComment(variantDesc, "\t")+fmt.Sprintf("\t%s %s %s", fieldName, fieldType, tagStr))
	}

	var b strings.Builder
	b.WriteString(auxiliary.String())
	desc, _ := schema["description"].(string)
	b.WriteString(goDocComment(desc, ""))
	b.WriteString(fmt.Sprintf("type %s struct {\n", typeName))
	for _, f := range fields {
		b.WriteString(f + "\n")
	}
	b.WriteString("}\n\n")

	// Build variant info for marshal/unmarshal generation
	var variants []variantInfo
	for i := range variantFieldNames {
		variants = append(variants, variantInfo{
			fieldName:   variantFieldNames[i],
			baseType:    variantFieldTypes[i],
			isPointer:   variantIsPointer[i],
			validateTag: variantValidateTags[i],
		})
	}

	// Generate MarshalJSON / UnmarshalJSON
	b.WriteString(generateVariantMarshal(typeName, variants, singleVariant))
	b.WriteString("\n")

	// Generate Validate
	if singleVariant {
		b.WriteString(generateValidateMethod(typeName, nil))
	} else {
		b.WriteString(generateValidateMethod(typeName, variantFieldNames))
	}

	return b.String()
}

// buildValidateValue returns the validate tag value for a schema (e.g., "oneof=low,min=0,max=100").
// Returns empty string if no validation constraints.
func buildValidateValue(schema Schema) string {
	var parts []string
	if enumVals, ok := schema["enum"].([]any); ok {
		vals := make([]string, len(enumVals))
		for i, v := range enumVals {
			vals[i] = fmt.Sprintf("%v", v)
		}
		parts = append(parts, "oneof="+strings.Join(vals, " "))
	}
	if v, ok := schema["minimum"]; ok {
		parts = append(parts, "min="+formatTagNumber(v))
	}
	if v, ok := schema["maximum"]; ok {
		parts = append(parts, "max="+formatTagNumber(v))
	}
	return strings.Join(parts, ",")
}

type variantInfo struct {
	fieldName   string
	baseType    string
	isPointer   bool
	validateTag string
}

// generateVariantMarshal generates MarshalJSON and UnmarshalJSON for variant structs.
func generateVariantMarshal(typeName string, variants []variantInfo, single bool) string {
	var b strings.Builder

	// MarshalJSON
	b.WriteString(fmt.Sprintf("func (v %s) MarshalJSON() ([]byte, error) {\n", typeName))
	if single {
		b.WriteString(fmt.Sprintf("\treturn json.Marshal(v.%s)\n", variants[0].fieldName))
	} else {
		for _, vi := range variants {
			b.WriteString(fmt.Sprintf("\tif v.%s != nil {\n\t\treturn json.Marshal(v.%s)\n\t}\n", vi.fieldName, vi.fieldName))
		}
		b.WriteString("\treturn []byte(\"null\"), nil\n")
	}
	b.WriteString("}\n\n")

	// UnmarshalJSON
	b.WriteString(fmt.Sprintf("func (v *%s) UnmarshalJSON(data []byte) error {\n", typeName))
	if single {
		vi := variants[0]
		if vi.isPointer {
			b.WriteString(fmt.Sprintf("\tvar val %s\n", vi.baseType))
			b.WriteString("\tif err := json.Unmarshal(data, &val); err != nil {\n\t\treturn err\n\t}\n")
			b.WriteString(fmt.Sprintf("\tv.%s = &val\n", vi.fieldName))
		} else {
			b.WriteString(fmt.Sprintf("\tif err := json.Unmarshal(data, &v.%s); err != nil {\n\t\treturn err\n\t}\n", vi.fieldName))
		}
		b.WriteString("\treturn v.Validate()\n")
	} else {
		for _, vi := range variants {
			b.WriteString(fmt.Sprintf("\t{\n\t\tvar try %s\n", vi.baseType))
			b.WriteString("\t\tif err := json.Unmarshal(data, &try); err == nil {\n")
			// Build a temporary instance with just this variant set, then validate
			b.WriteString(fmt.Sprintf("\t\t\tcandidate := %s{}\n", typeName))
			if vi.isPointer {
				b.WriteString(fmt.Sprintf("\t\t\tcandidate.%s = &try\n", vi.fieldName))
			} else {
				b.WriteString(fmt.Sprintf("\t\t\tcandidate.%s = try\n", vi.fieldName))
			}
			b.WriteString("\t\t\tif candidate.Validate() == nil {\n")
			b.WriteString(fmt.Sprintf("\t\t\t\t*v = candidate\n\t\t\t\treturn nil\n"))
			b.WriteString("\t\t\t}\n")
			b.WriteString("\t\t}\n\t}\n")
		}
		b.WriteString(fmt.Sprintf("\treturn fmt.Errorf(\"data did not match any variant of %s\")\n", typeName))
	}
	b.WriteString("}\n")

	return b.String()
}

// generateInlineVariantStruct generates a struct for an inline object anyOf variant.
// If the schema has a $ref, the referenced type is embedded (Go struct embedding = inheritance).
func generateInlineVariantStruct(structName string, schema Schema, selfTitle string, allTitles map[string]bool) string {
	props, _ := schema["properties"].(map[string]any)
	var auxiliary strings.Builder
	var b strings.Builder
	desc, _ := schema["description"].(string)
	b.WriteString(goDocComment(desc, ""))
	b.WriteString(fmt.Sprintf("type %s struct {\n", structName))

	// Embed $ref type if present (inheritance)
	if ref, ok := schema["$ref"].(string); ok {
		b.WriteString(fmt.Sprintf("\t%s\n", toPascal(ref)))
	}

	for _, pn := range sortedKeys(props) {
		ps, ok := props[pn].(map[string]any)
		if !ok {
			continue
		}
		fn := goFieldName(pn)
		ft := resolveFieldTypeWithInline(ps, selfTitle, allTitles, structName, fn, &auxiliary)
		fieldDesc, _ := ps["description"].(string)
		b.WriteString(goDocComment(fieldDesc, "\t"))
		jt := pn
		if oe, _ := ps["omitempty"].(bool); oe {
			jt += ",omitempty"
		}
		tags := buildStructTags(jt, ps, selfTitle, allTitles)
		b.WriteString(fmt.Sprintf("\t%s %s %s\n", fn, ft, tags))
	}
	b.WriteString("}\n")

	// additionalProperties method (only when explicitly set in schema)
	if ap, ok := schema["additionalProperties"]; ok {
		if ap == false {
			b.WriteString(fmt.Sprintf("\nfunc (%s) AdditionalProperties() bool { return false }\n", structName))
		} else if ap == true {
			b.WriteString(fmt.Sprintf("\nfunc (%s) AdditionalProperties() bool { return true }\n", structName))
		}
	}

	// Custom UnmarshalJSON for structs with embedding + local fields.
	// Go's json.Unmarshal gives the embedded type's UnmarshalJSON precedence,
	// which prevents the parent's own fields from being populated.
	if ref, ok := schema["$ref"].(string); ok && len(props) > 0 {
		embedType := toPascal(ref)
		b.WriteString(fmt.Sprintf("\nfunc (v *%s) UnmarshalJSON(data []byte) error {\n", structName))
		// Unmarshal into the embedded type
		b.WriteString(fmt.Sprintf("\tif err := json.Unmarshal(data, &v.%s); err != nil {\n\t\treturn err\n\t}\n", embedType))
		// Unmarshal local fields via anonymous struct
		b.WriteString("\tvar local struct {\n")
		for _, pn := range sortedKeys(props) {
			ps, ok := props[pn].(map[string]any)
			if !ok {
				continue
			}
			fn := goFieldName(pn)
			ft := resolveFieldType(ps, selfTitle, allTitles)
			jt := pn
			if oe, _ := ps["omitempty"].(bool); oe {
				jt += ",omitempty"
			}
			b.WriteString(fmt.Sprintf("\t\t%s %s `json:%q`\n", fn, ft, jt))
		}
		b.WriteString("\t}\n")
		b.WriteString("\tif err := json.Unmarshal(data, &local); err != nil {\n\t\treturn err\n\t}\n")
		for _, pn := range sortedKeys(props) {
			fn := goFieldName(pn)
			b.WriteString(fmt.Sprintf("\tv.%s = local.%s\n", fn, fn))
		}
		b.WriteString("\treturn nil\n}\n")

		// Custom MarshalJSON: same issue in reverse — the embedded type's
		// MarshalJSON only outputs its own fields, losing local fields.
		b.WriteString(fmt.Sprintf("\nfunc (v %s) MarshalJSON() ([]byte, error) {\n", structName))
		b.WriteString(fmt.Sprintf("\tbase, err := json.Marshal(v.%s)\n", embedType))
		b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		b.WriteString("\tvar merged map[string]json.RawMessage\n")
		b.WriteString("\tjson.Unmarshal(base, &merged)\n")
		for _, pn := range sortedKeys(props) {
			fn := goFieldName(pn)
			nullable := false
			if ps, ok := props[pn].(map[string]any); ok {
				nullable = isNullable(ps)
			}
			if nullable {
				b.WriteString(fmt.Sprintf("\tif v.%s != nil {\n", fn))
				b.WriteString(fmt.Sprintf("\t\tif raw, err := json.Marshal(v.%s); err == nil {\n\t\t\tmerged[%q] = raw\n\t\t}\n", fn, pn))
				b.WriteString("\t}\n")
			} else {
				b.WriteString(fmt.Sprintf("\tif raw, err := json.Marshal(v.%s); err == nil {\n\t\tmerged[%q] = raw\n\t}\n", fn, pn))
			}
		}
		b.WriteString("\treturn json.Marshal(merged)\n")
		b.WriteString("}\n")
	}

	// Strict UnmarshalJSON for required field checking (only when no embedding,
	// since embedding already generates its own custom UnmarshalJSON).
	if _, hasRef := schema["$ref"].(string); !hasRef {
		if unmarshal := generateStrictUnmarshal(structName, schema, selfTitle, allTitles); unmarshal != "" {
			b.WriteString("\n")
			b.WriteString(unmarshal)
		}
	}

	return auxiliary.String() + b.String()
}


