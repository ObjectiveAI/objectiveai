//go:build ignore

// install_command_execute.go
//
// Generates the cli/command typed `execute` functions for the Go SDK from the
// Rust SDK's CLI command tree — the Go port of
// objectiveai-sdk-py/scripts/install_command_execute.py (itself a port of the
// JS install-command-execute.cjs).
//
// For every leaf execute-family function under
// objectiveai-sdk-rs/src/cli/command/** (`execute`, `execute_transform`,
// `execute_streaming`, `execute_streaming_transform`, including the ones inside
// each leaf's nested request_schema / response_schema modules), this script
// emits one flat `cli_command_<path>_execute.go` file (package objectiveai)
// holding that scope's execute functions. Because the Go SDK is a single flat
// package, the functions are named by full path + Rust fn name in PascalCase
// (e.g. AgentsTagsApplyExecute, AgentsTagsApplyExecuteTransform,
// AgentsGetRequestSchemaExecute) and need NO cross-package imports — the
// Request/Response types, CliStream, CommandExecutor and the CliError union
// (handled internally by CliStream) all live in the same package.
//
// Each function:
//   - takes (ctx, executor CommandExecutor, request <LeafRequest>, [jq | transform]),
//     dropping the Rust `agent_arguments`,
//   - applies the same pre-call request mutations (jq set/clear, transform
//     set/clear, the dangerous_advanced.stream flag) parsed from the Rust body
//     via a bounded statement grammar that HARD-ERRORS on anything it doesn't
//     recognize, so Rust-side drift fails generation loudly,
//   - injects the self-describing `path_type` discriminator (callers never pass it),
//   - unary fns return (*<Response>, error); streaming fns return
//     (*CliStream[<Item>], error). A CliError envelope surfaces as the error.
//
// Skipping rules (reported, never silent): a scope is skipped when it has no
// `Path` discriminator yet, or when a referenced Request/Response/payload Go
// type hasn't been generated (its title isn't in objectiveai-json-schema/).
//
// Run order: install_go.go first (it generates the types tree), then this.

package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strings"
	"unicode"
)

var (
	repoRoot       string
	rustSrcDir     string
	rustCommandDir string
	schemaDir      string
	outDir         string
)

const generatedHeader = "// THIS FILE IS AUTO-GENERATED. DO NOT EDIT.\n" +
	"// Generated by scripts/install_command_execute.go from objectiveai-sdk-rs/src/cli/command/.\n"

func main() {
	// Resolve paths from THIS file's location (robust to CWD), like install_go.go:
	// <repo>/objectiveai-sdk-go/scripts/install_command_execute.go
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		fatal("cannot resolve source path via runtime.Caller")
	}
	sdkDir := filepath.Dir(filepath.Dir(thisFile)) // .../objectiveai-sdk-go
	repoRoot = filepath.Dir(sdkDir)
	rustSrcDir = filepath.Join(repoRoot, "objectiveai-sdk-rs", "src")
	rustCommandDir = filepath.Join(rustSrcDir, "cli", "command")
	schemaDir = filepath.Join(repoRoot, "objectiveai-json-schema")
	outDir = sdkDir // flat package: emit alongside the generated types

	if _, err := os.Stat(rustCommandDir); err != nil {
		fmt.Fprintf(os.Stderr, "install_command_execute: rust command dir missing: %s\n", rustCommandDir)
		os.Exit(2)
	}

	allTitles := loadTitles()
	cleanGenerated(outDir)

	scopes := collectScopes()
	var generated, skipped []string

	for _, key := range sortedKeys(scopes) {
		src := scopes[key]
		segments := strings.Split(key, "/")
		modulePath := append([]string{"cli", "command"}, segments...)
		scope := scopeInfo{
			aliases:   findTypeAliases(src),
			localDefs: findLocalDefs(src),
			reexports: findReexports(src),
		}
		fns := findExecuteFns(src)
		if len(fns) == 0 {
			continue
		}
		pathConst := findPathConst(src)
		if pathConst == nil {
			skipped = append(skipped, fmt.Sprintf("%s — no `Path` discriminator on Request yet", strings.Join(segments, " ")))
			continue
		}
		requestTitle := strings.Join(append(append([]string{}, modulePath...), "Request"), ".")
		if !allTitles[requestTitle] {
			skipped = append(skipped, fmt.Sprintf("%s — schema `%s` not generated yet", strings.Join(segments, " "), requestTitle))
			continue
		}
		requestType := toPascal(requestTitle)

		var fnsOut []string
		needsFmt := false // only unary fns use fmt.Errorf
		for _, fn := range fns {
			context := fmt.Sprintf("%s %s", strings.Join(segments, "/"), fn.name)
			params := parseParams(fn.params, context)
			mut, call := parseBody(fn.body, context)

			retM := reReturn.FindStringSubmatch(fn.returnType)
			if retM == nil {
				fatal(fmt.Sprintf("%s: unrecognized return `%s`", context, fn.returnType))
			}
			payloadExpr := strings.TrimSpace(retM[1])
			streamM := reStream.FindStringSubmatch(payloadExpr)
			streaming := streamM != nil
			if streaming != (call == "execute") {
				fatal(fmt.Sprintf("%s: return shape and executor call disagree", context))
			}
			if streaming {
				payloadExpr = strings.TrimSpace(streamM[1])
			}
			payload := resolveType(payloadExpr, scope, modulePath, context)

			var payloadRef string
			switch payload.kind {
			case "json":
				payloadRef = "JsonValue"
			case "string":
				payloadRef = "string"
			default: // schema
				if !allTitles[payload.title] {
					skipped = append(skipped, fmt.Sprintf("%s — schema `%s` not generated yet", context, payload.title))
					continue
				}
				payloadRef = toPascal(payload.title)
			}

			fnName := goFnName(segments, fn.name)
			docPath := strings.Join(segments, " ")
			body := buildWireBody(mut, params, pathConst)

			sigParams := []string{"ctx context.Context", "executor CommandExecutor", fmt.Sprintf("request %s", requestType)}
			for _, p := range params {
				switch p {
				case "jq":
					sigParams = append(sigParams, "jq string")
				case "transform":
					sigParams = append(sigParams, "transform map[string]string")
				}
			}
			sig := strings.Join(sigParams, ", ")

			if streaming {
				fnsOut = append(fnsOut, fmt.Sprintf(
					"// %s — `%s %s` (streaming); the typed CLI stream of %s.\n"+
						"func %s(%s) (*CliStream[%s], error) {\n"+
						"%s"+
						"\traw, err := executor.Execute(ctx, wire)\n"+
						"\tif err != nil {\n\t\treturn nil, err\n\t}\n"+
						"\treturn NewCliStream[%s](raw), nil\n}\n",
					fnName, docPath, fn.name, payloadRef,
					fnName, sig, payloadRef,
					body,
					payloadRef,
				))
			} else {
				needsFmt = true
				fnsOut = append(fnsOut, fmt.Sprintf(
					"// %s — `%s %s` (unary); the first stream item, rest discarded.\n"+
						"func %s(%s) (*%s, error) {\n"+
						"%s"+
						"\traw, err := executor.Execute(ctx, wire)\n"+
						"\tif err != nil {\n\t\treturn nil, err\n\t}\n"+
						"\tfirst, err := NewCliStream[%s](raw).First()\n"+
						"\tif err != nil {\n\t\treturn nil, err\n\t}\n"+
						"\tif first == nil {\n\t\treturn nil, fmt.Errorf(%q)\n\t}\n"+
						"\treturn first, nil\n}\n",
					fnName, docPath, fn.name,
					fnName, sig, payloadRef,
					body,
					payloadRef,
					docPath+": cli produced no output before the end marker",
				))
			}
		}

		if len(fnsOut) == 0 {
			continue
		}
		imports := "import (\n\t\"context\"\n)\n\n"
		if needsFmt {
			imports = "import (\n\t\"context\"\n\t\"fmt\"\n)\n\n"
		}
		content := generatedHeader + "package objectiveai\n\n" + imports +
			strings.Join(fnsOut, "\n")
		fileName := "cli_command_" + strings.Join(segments, "_") + "_execute.go"
		outPath := filepath.Join(outDir, fileName)
		must(os.WriteFile(outPath, []byte(content), 0o644))
		generated = append(generated, fileName)
	}

	fmt.Printf("install_command_execute: generated %d execute file(s)\n", len(generated))
	if len(skipped) > 0 {
		fmt.Printf("install_command_execute: SKIPPED %d scope(s)/fn(s):\n", len(skipped))
		for _, s := range skipped {
			fmt.Printf("  - %s\n", s)
		}
	}
}

// buildWireBody emits the wire-map setup: marshal the request, apply mutations,
// inject the discriminator. Mirrors the Python wire_lines, operating on a
// map[string]any (the Go analogue of model_dump).
func buildWireBody(mut mutations, params []string, pathConst *pathDiscriminator) string {
	var b strings.Builder
	b.WriteString("\twire, err := cliWire(request)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	switch mut.jq {
	case "clear":
		b.WriteString("\tdelete(wire, \"jq\")\n")
	case "set":
		b.WriteString("\twire[\"jq\"] = jq\n")
	}
	switch mut.transform {
	case "clear":
		b.WriteString("\tdelete(wire, \"jq\")\n\tdelete(wire, \"python\")\n")
	case "set":
		b.WriteString("\tdelete(wire, \"jq\")\n\tdelete(wire, \"python\")\n\tfor k, v := range transform {\n\t\twire[k] = v\n\t}\n")
	}
	switch mut.stream {
	case "set":
		b.WriteString("\t{\n\t\tadv := cliAdvanced(wire)\n\t\tadv[\"stream\"] = true\n\t\twire[\"dangerous_advanced\"] = adv\n\t}\n")
	case "clear":
		b.WriteString("\tif _, ok := wire[\"dangerous_advanced\"]; ok {\n\t\tadv := cliAdvanced(wire)\n\t\tdelete(adv, \"stream\")\n\t\twire[\"dangerous_advanced\"] = adv\n\t}\n")
	}
	b.WriteString(fmt.Sprintf("\twire[%q] = %q\n", pathConst.field, pathConst.value))
	_ = params
	return b.String()
}

// ── scope collection ─────────────────────────────────────────────────────────

type scopeInfo struct {
	aliases   map[string]string
	localDefs map[string]bool
	reexports map[string]string
}

func collectScopes() map[string]string {
	scopes := map[string]string{}
	must(filepath.Walk(rustCommandDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() || !strings.HasSuffix(path, ".rs") {
			return nil
		}
		src := readFile(path)
		if !reHasExecute.MatchString(src) || !reHasRequest.MatchString(src) {
			return nil
		}
		rel, err := filepath.Rel(rustCommandDir, path)
		must(err)
		rel = filepath.ToSlash(strings.TrimSuffix(rel, ".rs"))
		key := rel
		if filepath.Base(rel) == "mod" {
			key = filepath.ToSlash(filepath.Dir(rel))
		}
		if key == "." {
			return nil // command-root mod.rs is a dispatcher
		}
		scopes[key] = src
		return nil
	}))
	return scopes
}

// ── Rust source parsing (port of the Python helpers) ─────────────────────────

var (
	reLineComment = regexp.MustCompile(`//[^\n]*`)
	reWS          = regexp.MustCompile(`\s+`)

	reHasExecute = regexp.MustCompile(`pub async fn execute\w*\s*<`)
	reHasRequest = regexp.MustCompile(`pub struct Request\b`)

	rePathEnum   = regexp.MustCompile(`pub enum Path\s*\{`)
	reRename     = regexp.MustCompile(`#\[serde\(rename = "([^"]+)"\)\]`)
	rePathStruct = regexp.MustCompile(`pub struct Request\s*\{`)
	rePathField  = regexp.MustCompile(`pub (\w+)\s*:\s*Path\b`)

	reTypeAlias = regexp.MustCompile(`pub type (\w+)\s*=\s*([^;]+);`)
	reLocalDef  = regexp.MustCompile(`pub (?:struct|enum) (\w+)`)

	reReexportBrace  = regexp.MustCompile(`pub use (super(?:::\w+)*)::\{([^}]+)\}\s*;`)
	reReexportSingle = regexp.MustCompile(`pub use (super(?:::\w+)*)::(\w+)(?: as (\w+))?\s*;`)
	reReexportItemAs = regexp.MustCompile(`^(\w+) as (\w+)$`)
	reReexportItem   = regexp.MustCompile(`^\w+$`)

	reExecuteFn = regexp.MustCompile(`pub async fn (execute\w*)\s*<`)

	reReturn = regexp.MustCompile(`^Result<(.+), E::Error>$`)
	reStream = regexp.MustCompile(`^E::Stream<(.+)>$`)
	reOption = regexp.MustCompile(`^Option<(.+)>$`)
)

func normalize(rust string) string {
	rust = reLineComment.ReplaceAllString(rust, " ")
	rust = reWS.ReplaceAllString(rust, " ")
	return strings.TrimSpace(rust)
}

func matchBrace(text string, openIdx int, open, close byte) int {
	depth := 0
	for i := openIdx; i < len(text); i++ {
		switch text[i] {
		case open:
			depth++
		case close:
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	fatal(fmt.Sprintf("unbalanced %c%c starting at %d", open, close, openIdx))
	return -1
}

func splitTopLevel(text string, sep byte) []string {
	var parts []string
	depth := 0
	var current strings.Builder
	for i := 0; i < len(text); i++ {
		ch := text[i]
		switch ch {
		case '<', '(', '[', '{':
			depth++
		case '>', ')', ']', '}':
			depth--
		}
		if ch == sep && depth == 0 {
			if s := strings.TrimSpace(current.String()); s != "" {
				parts = append(parts, s)
			}
			current.Reset()
		} else {
			current.WriteByte(ch)
		}
	}
	if s := strings.TrimSpace(current.String()); s != "" {
		parts = append(parts, s)
	}
	return parts
}

type pathDiscriminator struct{ field, value string }

func findPathConst(src string) *pathDiscriminator {
	em := rePathEnum.FindStringIndex(src)
	if em == nil {
		return nil
	}
	close := matchBrace(src, em[1]-1, '{', '}')
	body := src[em[1]:close]
	renames := reRename.FindAllStringSubmatch(body, -1)
	variantCount := 0
	for _, p := range splitTopLevel(normalize(body), ',') {
		if p != "" {
			variantCount++
		}
	}
	if len(renames) != 1 || variantCount != 1 {
		return nil
	}
	sm := rePathStruct.FindStringIndex(src)
	if sm == nil {
		return nil
	}
	sclose := matchBrace(src, sm[1]-1, '{', '}')
	structBody := src[sm[1]:sclose]
	fm := rePathField.FindStringSubmatch(structBody)
	if fm == nil {
		return nil
	}
	return &pathDiscriminator{field: fm[1], value: renames[0][1]}
}

func findTypeAliases(src string) map[string]string {
	out := map[string]string{}
	for _, m := range reTypeAlias.FindAllStringSubmatch(src, -1) {
		out[m[1]] = strings.TrimSpace(m[2])
	}
	return out
}

func findLocalDefs(src string) map[string]bool {
	out := map[string]bool{}
	for _, m := range reLocalDef.FindAllStringSubmatch(src, -1) {
		out[m[1]] = true
	}
	return out
}

func findReexports(src string) map[string]string {
	out := map[string]string{}
	for _, m := range reReexportBrace.FindAllStringSubmatch(src, -1) {
		for _, item := range splitTopLevel(normalize(m[2]), ',') {
			if as := reReexportItemAs.FindStringSubmatch(item); as != nil {
				out[as[2]] = m[1] + "::" + as[1]
			} else if reReexportItem.MatchString(item) {
				out[item] = m[1] + "::" + item
			}
		}
	}
	for _, m := range reReexportSingle.FindAllStringSubmatch(src, -1) {
		local := m[3]
		if local == "" {
			local = m[2]
		}
		out[local] = m[1] + "::" + m[2]
	}
	return out
}

type executeFn struct {
	name, params, returnType, body string
}

func findExecuteFns(src string) []executeFn {
	var fns []executeFn
	for _, m := range reExecuteFn.FindAllStringSubmatchIndex(src, -1) {
		name := src[m[2]:m[3]]
		genericsOpen := m[1] - 1
		genericsClose := matchBrace(src, genericsOpen, '<', '>')
		parenOpen := strings.IndexByte(src[genericsClose:], '(') + genericsClose
		parenClose := matchBrace(src, parenOpen, '(', ')')
		arrow := strings.Index(src[parenClose:], "->") + parenClose
		bodyOpen := strings.IndexByte(src[arrow:], '{') + arrow
		bodyClose := matchBrace(src, bodyOpen, '{', '}')
		fns = append(fns, executeFn{
			name:       name,
			params:     normalize(src[parenOpen+1 : parenClose]),
			returnType: normalize(src[arrow+2 : bodyOpen]),
			body:       normalize(src[bodyOpen+1 : bodyClose]),
		})
	}
	return fns
}

// parseParams keeps request (+ jq / transform), drops executor / agent_arguments.
// Hard-errors on anything else. Returns the kept extra params ("jq"/"transform").
func parseParams(params, context string) []string {
	var out []string
	for _, raw := range splitTopLevel(params, ',') {
		if raw == "" {
			continue
		}
		p := strings.TrimPrefix(raw, "mut ")
		colon := strings.IndexByte(p, ':')
		if colon < 0 {
			fatal(fmt.Sprintf("%s: unrecognized param `%s`", context, raw))
		}
		name := strings.TrimSpace(p[:colon])
		typ := strings.TrimSpace(p[colon+1:])
		bare := strings.TrimLeft(name, "_")
		switch {
		case bare == "executor" || bare == "agent_arguments":
			continue
		case bare == "request" && typ == "Request":
			// request is always present; not added to extras
		case bare == "jq" && typ == "String":
			out = append(out, "jq")
		case bare == "transform" && (typ == "Transform" || typ == "crate::cli::command::Transform"):
			out = append(out, "transform")
		default:
			fatal(fmt.Sprintf("%s: unrecognized param `%s`", context, raw))
		}
	}
	return out
}

type mutations struct{ jq, transform, stream string }

var bodyFragments = []struct {
	re  *regexp.Regexp
	set func(*mutations)
}{
	{regexp.MustCompile(`^request\.jq = None;\s*`), func(m *mutations) { m.jq = "clear" }},
	{regexp.MustCompile(`^request\.jq = Some\(jq\);\s*`), func(m *mutations) { m.jq = "set" }},
	{regexp.MustCompile(`^request\.base\.clear_transform\(\);\s*`), func(m *mutations) { m.transform = "clear" }},
	{regexp.MustCompile(`^request\.base\.set_transform\(transform\);\s*`), func(m *mutations) { m.transform = "set" }},
	{regexp.MustCompile(`^let mut advanced = request\.dangerous_advanced\.unwrap_or_default\(\); advanced\.stream = Some\(true\); request\.dangerous_advanced = Some\(advanced\);\s*`), func(m *mutations) { m.stream = "set" }},
	{regexp.MustCompile(`^if let Some\(advanced\) = request\.dangerous_advanced\.as_mut\(\) \{ advanced\.stream = None; \}\s*`), func(m *mutations) { m.stream = "clear" }},
}

var (
	reBodyTail      = regexp.MustCompile(`^executor\.(execute|execute_one)\(request, agent_arguments\)\.await$`)
	reBodyTailWrap  = regexp.MustCompile(`^let resp\s*:\s*[\w:]+\s*=\s*executor\.(execute_one)\(request, agent_arguments\)\.await\?;\s*Ok\(serde_json::to_value\(resp\)\.expect\("[^"]*"\)\)$`)
)

// parseBody is the bounded body grammar — returns the mutation set + which
// executor method finishes it ("execute" => streaming, "execute_one" => unary).
// Hard-errors on residue, so Rust drift fails loudly.
func parseBody(body, context string) (mutations, string) {
	var mut mutations
	rest := body
	for progressed := true; progressed; {
		progressed = false
		for _, frag := range bodyFragments {
			if loc := frag.re.FindStringIndex(rest); loc != nil && loc[0] == 0 {
				frag.set(&mut)
				rest = rest[loc[1]:]
				progressed = true
			}
		}
	}
	trimmed := strings.TrimSpace(rest)
	if m := reBodyTail.FindStringSubmatch(trimmed); m != nil {
		return mut, m[1]
	}
	if m := reBodyTailWrap.FindStringSubmatch(trimmed); m != nil {
		return mut, m[1]
	}
	fatal(fmt.Sprintf("%s: unrecognized body residue `%s` — extend the statement grammar in install_command_execute.go", context, trimmed))
	return mut, ""
}

// ── type resolution ──────────────────────────────────────────────────────────

type resolved struct {
	kind     string // "json" | "string" | "schema"
	title    string
	optional bool
}

func rustModuleTitle(segs []string) string {
	typeName := segs[len(segs)-1]
	moduleSegs := segs[:len(segs)-1]
	if len(moduleSegs) > 0 {
		candidate := filepath.Join(append([]string{rustSrcDir}, moduleSegs...)...) + ".rs"
		if _, err := os.Stat(candidate); err == nil {
			moduleSegs = moduleSegs[:len(moduleSegs)-1]
		}
	}
	return strings.Join(append(append([]string{}, moduleSegs...), typeName), ".")
}

func resolveType(typeExpr string, scope scopeInfo, modulePath []string, context string) resolved {
	t := strings.TrimSpace(typeExpr)
	if t == "serde_json::Value" || t == "schemars::Schema" {
		return resolved{kind: "json"}
	}
	if t == "String" {
		return resolved{kind: "string"}
	}
	if m := reOption.FindStringSubmatch(t); m != nil {
		inner := resolveType(m[1], scope, modulePath, context)
		inner.optional = true
		return inner
	}
	if t == "ResponseSchema" || strings.HasSuffix(t, "::ResponseSchema") {
		return resolved{kind: "json"}
	}
	if strings.Contains(t, "::") {
		segs := strings.Split(t, "::")
		for i := range segs {
			segs[i] = strings.TrimSpace(segs[i])
		}
		switch segs[0] {
		case "crate":
			return resolved{kind: "schema", title: rustModuleTitle(segs[1:])}
		case "super":
			base := append([]string{}, modulePath[:len(modulePath)-1]...)
			i := 1
			for i < len(segs) && segs[i] == "super" {
				base = base[:len(base)-1]
				i++
			}
			return resolved{kind: "schema", title: rustModuleTitle(append(base, segs[i:]...))}
		default:
			fatal(fmt.Sprintf("%s: unsupported type path `%s`", context, t))
		}
	}
	if alias, ok := scope.aliases[t]; ok {
		return resolveType(alias, scope, modulePath, context)
	}
	if reexp, ok := scope.reexports[t]; ok {
		return resolveType(reexp, scope, modulePath, context)
	}
	if scope.localDefs[t] {
		return resolved{kind: "schema", title: strings.Join(append(append([]string{}, modulePath...), t), ".")}
	}
	fatal(fmt.Sprintf("%s: cannot resolve type `%s`", context, t))
	return resolved{}
}

// ── helpers ──────────────────────────────────────────────────────────────────

func goFnName(segments []string, rustFnName string) string {
	var b strings.Builder
	for _, seg := range segments {
		b.WriteString(pascalCase(seg))
	}
	b.WriteString(pascalCase(rustFnName))
	return b.String()
}

// pascalCase capitalizes each underscore-separated word: "execute_streaming" ->
// "ExecuteStreaming", "request_schema" -> "RequestSchema".
func pascalCase(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part == "" {
			continue
		}
		r := []rune(part)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

// toPascal mirrors install_go.go: split on [._-], capitalize each, concat.
// "cli.command.agents.tags.apply.Request" -> "CliCommandAgentsTagsApplyRequest".
var reTitleSep = regexp.MustCompile(`[._-]`)

func toPascal(title string) string {
	var b strings.Builder
	for _, p := range reTitleSep.Split(title, -1) {
		if p == "" {
			continue
		}
		r := []rune(p)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

var reSchemaTitle = regexp.MustCompile(`"title"\s*:\s*"((?:[^"\\]|\\.)*)"`)

func loadTitles() map[string]bool {
	titles := map[string]bool{}
	entries, err := os.ReadDir(schemaDir)
	must(err)
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		content := readFile(filepath.Join(schemaDir, e.Name()))
		if m := reSchemaTitle.FindStringSubmatch(content); m != nil {
			titles[m[1]] = true
		}
	}
	return titles
}

func cleanGenerated(dir string) {
	entries, err := os.ReadDir(dir)
	must(err)
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), "_execute.go") {
			continue
		}
		path := filepath.Join(dir, e.Name())
		head := readFile(path)
		if len(head) >= 30 && strings.HasPrefix(head, "// THIS FILE IS AUTO-GENERATED") {
			must(os.Remove(path))
		}
	}
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func readFile(path string) string {
	b, err := os.ReadFile(path)
	must(err)
	return string(b)
}

func must(err error) {
	if err != nil {
		fmt.Fprintf(os.Stderr, "install_command_execute: %v\n", err)
		os.Exit(1)
	}
}

func fatal(msg string) {
	fmt.Fprintf(os.Stderr, "install_command_execute: %s\n", msg)
	os.Exit(1)
}
