/** Recursively delete files containing the auto-generated marker,
 *  then prune empty directories bottom-up. */
function cleanGenerated(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      cleanGenerated(full);
    } else if (entry.isFile() && entry.name.endsWith(".ts")) {
      const head = Buffer.alloc(128);
      const fd = fs.openSync(full, "r");
      fs.readSync(fd, head, 0, 128, 0);
      fs.closeSync(fd);
      if (head.toString("utf-8").includes("THIS FILE IS AUTO-GENERATED")) {
        fs.unlinkSync(full);
      }
    }
  }
  // Remove directory if now empty
  if (fs.readdirSync(dir).length === 0) {
    fs.rmdirSync(dir);
  }
}

function main() {
  // Clean previously generated files and empty directories
  cleanGenerated(SRC_DIR);

  // Read all schema files
  const files = fs.readdirSync(SCHEMA_DIR).filter((f) => f.endsWith(".json"));
  const schemas = new Map(); // title -> schema object

  for (const file of files) {
    const content = JSON.parse(
      fs.readFileSync(path.join(SCHEMA_DIR, file), "utf-8")
    );
    if (content.title) {
      schemas.set(content.title, content);
    }
  }

  console.log(`Read ${schemas.size} schemas`);

  // Group schemas by output file path
  // key: "agent/agent" (relative to src/), value: [{ title, schema }]
  const fileGroups = new Map();

  for (const [title, schema] of schemas) {
    const { dir, file } = titleToPath(title);
    const filePath = dir ? `${dir}/${file}` : file;
    if (!fileGroups.has(filePath)) {
      fileGroups.set(filePath, []);
    }
    fileGroups.get(filePath).push({ title, schema });
  }

  console.log(`Generating ${fileGroups.size} .ts files`);

  // ---------------------------------------------------------------------------
  // Build file dependency graph and detect cycles
  // ---------------------------------------------------------------------------

  // First pass: collect refs for each file to build the dependency graph
  const fileRefMap = new Map(); // filePath -> Set<refFilePath>
  for (const [filePath, entries] of fileGroups) {
    const refs = new Set();
    for (const { title, schema } of entries) {
      collectRefs(schema, refs, title);
    }
    const depFiles = new Set();
    for (const ref of refs) {
      const { dir: refDir, file: refFile } = titleToPath(ref);
      const refPath = refDir ? `${refDir}/${refFile}` : refFile;
      if (refPath !== filePath) {
        depFiles.add(refPath);
      }
    }
    fileRefMap.set(filePath, depFiles);
  }

  // Find all files that participate in dependency cycles or have self-references.
  const filesInCycles = new Set();
  for (const [f, entries] of fileGroups) {
    // Check for self-referencing schemas ($ref === title)
    for (const { title, schema } of entries) {
      if (hasSelfRef(schema, title)) {
        filesInCycles.add(f);
        break;
      }
    }
    // Check for inter-file cycles via BFS
    if (!filesInCycles.has(f)) {
      const visited = new Set();
      const queue = [];
      for (const dep of fileRefMap.get(f) || []) {
        if (dep !== f) queue.push(dep);
      }
      while (queue.length > 0) {
        const v = queue.shift();
        if (v === f) { filesInCycles.add(f); break; }
        if (visited.has(v)) continue;
        visited.add(v);
        for (const w of fileRefMap.get(v) || []) {
          queue.push(w);
        }
      }
    }
  }

  // Mark ALL edges between cyclic files as lazy.
  const lazyEdges = new Set();
  for (const f of filesInCycles) {
    for (const dep of fileRefMap.get(f) || []) {
      if (filesInCycles.has(dep)) {
        lazyEdges.add(`${f}->${dep}`);
      }
    }
  }

  if (lazyEdges.size > 0) {
    console.log(`Found ${lazyEdges.size} circular dependency edge(s), using z.lazy()`);
  }

  // Build a set of titles whose refs are lazy (from a given file)
  const lazyRefTitles = new Map();
  for (const edge of lazyEdges) {
    const [fromFile, toFile] = edge.split("->");
    for (const { title, schema } of fileGroups.get(fromFile) || []) {
      const refs = new Set();
      collectRefs(schema, refs, title);
      for (const ref of refs) {
        const { dir: refDir, file: refFile } = titleToPath(ref);
        const refPath = refDir ? `${refDir}/${refFile}` : refFile;
        if (refPath === toFile) {
          if (!lazyRefTitles.has(fromFile)) lazyRefTitles.set(fromFile, new Set());
          lazyRefTitles.get(fromFile).add(ref);
        }
      }
    }
  }

  if (filesInCycles.size > 0) {
    console.log(`Found ${filesInCycles.size} file(s) in dependency cycles, using explicit types`);
  }

  // Build set of all titles in cyclic files (their schemas use z.ZodType<T>
  // annotation, so .extend() is unavailable — must use .and() instead).
  const cyclicTitles = new Set();
  for (const f of filesInCycles) {
    for (const { title } of fileGroups.get(f) || []) {
      cyclicTitles.add(title);
    }
  }

  // Track all directories that need index.ts files
  const allDirs = new Set();

  // Generate each .ts file
  for (const [filePath, entries] of fileGroups) {
    const refs = new Set();
    const lazyRefs = lazyRefTitles.get(filePath) || new Set();
    const exports = [];

    const fileInCycle = filesInCycles.has(filePath);

    for (const { title, schema } of entries) {
      const pascalName = titleToPascal(title);
      const zodCode = convertTopLevel(schema, refs, lazyRefs, title, cyclicTitles);
      // Add .meta({ title }) for top-level schema title
      const withTitle = `${zodCode}.meta({ title: ${JSON.stringify(title)} })`;

      if (fileInCycle) {
        // File is in a dependency cycle — z.infer can't resolve through
        // circular const type inference. Generate an explicit type from
        // the JSON schema and annotate with z.ZodType<T>.
        const canInterface = schema.properties && !schema.anyOf;
        if (canInterface) {
          const body = convertObjectTS(schema, title);
          exports.push(
            `export interface ${pascalName} ${body}\n` +
              `export const ${pascalName}Schema: z.ZodType<${pascalName}> = ${withTitle};`
          );
        } else {
          // For union types, extract Record/Array variants that reference
          // cyclic types as helper interfaces to break TS type alias recursion.
          const helpers = [];
          const tsType = convertTopLevelTSWithHelpers(schema, title, pascalName, helpers);
          const helperDecls = helpers.map((h) => h.decl).join("\n");
          exports.push(
            (helperDecls ? helperDecls + "\n" : "") +
              `export type ${pascalName} = ${tsType};\n` +
              `export const ${pascalName}Schema: z.ZodType<${pascalName}> = ${withTitle};`
          );
        }
      } else {
        exports.push(
          `export const ${pascalName}Schema = ${withTitle};\n` +
            `export type ${pascalName} = z.infer<typeof ${pascalName}Schema>;`
        );
      }
    }

    // Compute imports
    const imports = [];
    // Always need zod
    imports.push('import { z } from "zod";');

    // Add JsonValueSchema import if needed
    const needsJsonValue = refs.has(JSON_VALUE_REF);
    refs.delete(JSON_VALUE_REF);
    if (needsJsonValue) {
      const relPath = relativeImport(filePath, "jsonValue");
      if (fileInCycle) {
        imports.push(`import { JsonValueSchema, type JsonValue } from "${relPath}";`);
      } else {
        imports.push(`import { JsonValueSchema } from "${relPath}";`);
      }
    }

    // Group refs by their target file
    const refsByFile = new Map();
    for (const ref of refs) {
      // Skip self-references (refs within the same file)
      const { dir: refDir, file: refFile } = titleToPath(ref);
      const refPath = refDir ? `${refDir}/${refFile}` : refFile;
      if (refPath === filePath) continue;
      if (!refsByFile.has(refPath)) {
        refsByFile.set(refPath, []);
      }
      refsByFile.get(refPath).push(ref);
    }

    for (const [refPath, refTitles] of [...refsByFile.entries()].sort()) {
      const schemaNames = refTitles
        .map((t) => titleToPascal(t) + "Schema")
        .sort();
      const relPath = relativeImport(filePath, refPath);
      if (fileInCycle) {
        // Also import type names for use in explicit type definitions
        const typeNames = refTitles
          .map((t) => "type " + titleToPascal(t))
          .sort();
        imports.push(
          `import { ${[...schemaNames, ...typeNames].join(", ")} } from "${relPath}";`
        );
      } else {
        imports.push(
          `import { ${schemaNames.join(", ")} } from "${relPath}";`
        );
      }
    }

    const content =
      GENERATED_HEADER + imports.join("\n") + "\n\n" + exports.join("\n\n") + "\n";

    const fullPath = path.join(SRC_DIR, filePath + ".ts");
    const dir = path.dirname(fullPath);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(fullPath, content);

    // Track directories
    const parts = filePath.split("/");
    for (let i = 1; i <= parts.length - 1; i++) {
      allDirs.add(parts.slice(0, i).join("/"));
    }
  }

  // Generate generatedIndex.ts for each directory (deepest first so parents find child indexes).
  // If a directory has no hand-written index.ts, generate a simple one that re-exports generatedIndex.
  allDirs.add("");

  for (const dir of [...allDirs].sort((a, b) => b.length - a.length)) {
    const absDir = dir ? path.join(SRC_DIR, dir) : SRC_DIR;
    if (!fs.existsSync(absDir)) continue;

    const entries = fs.readdirSync(absDir, { withFileTypes: true });
    const exportLines = [];

    // Export subdirectories (that have an index.ts or generatedIndex.ts)
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      if (entry.isDirectory()) {
        const hasIndex = fs.existsSync(path.join(absDir, entry.name, "index.ts"))
          || fs.existsSync(path.join(absDir, entry.name, "generatedIndex.ts"));
        if (hasIndex) {
          exportLines.push(`export * from "./${entry.name}/index";`);
        }
      }
    }

    // Export auto-generated .ts files (skip index.ts, generatedIndex.ts, and test files)
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      if (
        entry.isFile() &&
        entry.name.endsWith(".ts") &&
        entry.name !== "index.ts" &&
        entry.name !== "generatedIndex.ts" &&
        !entry.name.endsWith(".test.ts")
      ) {
        const name = entry.name.replace(/\.ts$/, "");
        const fullFilePath = path.join(absDir, entry.name);
        const fileContent = fs.readFileSync(fullFilePath, "utf-8");
        if (fileContent.startsWith("// THIS FILE IS AUTO-GENERATED")) {
          exportLines.push(`export * from "./${name}";`);
        }
      }
    }

    if (exportLines.length > 0) {
      // Always write generatedIndex.ts
      const generatedIndexPath = path.join(absDir, "generatedIndex.ts");
      fs.writeFileSync(generatedIndexPath, GENERATED_HEADER + exportLines.join("\n") + "\n");

      // If no hand-written index.ts exists, generate a simple one
      const indexPath = path.join(absDir, "index.ts");
      if (!fs.existsSync(indexPath)) {
        fs.writeFileSync(indexPath, GENERATED_HEADER + `export * from "./generatedIndex";\n`);
      }
    }
  }

  console.log(`Generated barrel exports for ${allDirs.size} directories`);
  console.log("Done!");
}

main();
