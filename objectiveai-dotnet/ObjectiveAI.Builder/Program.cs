string GenerateFlattenedRefConverter(string pascalName, string refType, JsonElement propsEl, HashSet<string> usings)
{
    var sb = new StringBuilder();
    sb.AppendLine($"public class {pascalName}Converter : JsonConverter<{pascalName}>");
    sb.AppendLine("{");

    // Read: deserialize base type + local properties
    sb.AppendLine($"    public override {pascalName}? Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)");
    sb.AppendLine("    {");
    sb.AppendLine("        if (reader.TokenType == JsonTokenType.Null) { reader.Read(); return null; }");
    sb.AppendLine("        using var doc = JsonDocument.ParseValue(ref reader);");
    sb.AppendLine("        var raw = doc.RootElement.GetRawText();");
    sb.AppendLine($"        var baseObj = JsonSerializer.Deserialize<{refType}>(raw, options)!;");
    sb.AppendLine($"        var result = new {pascalName} {{ Base = baseObj }};");

    // Read each local property
    if (propsEl.ValueKind != JsonValueKind.Undefined)
    {
        foreach (var prop in propsEl.EnumerateObject().OrderBy(p => p.Name))
        {
            var propName = ToPascalCase(prop.Name);
            var (csType, isNullable) = ConvertPropertyType(prop.Value, usings);
            if (isNullable)
            {
                sb.AppendLine($"        if (doc.RootElement.TryGetProperty(\"{prop.Name}\", out var _{propName}El) && _{propName}El.ValueKind != JsonValueKind.Null)");
                sb.AppendLine($"            result.{propName} = JsonSerializer.Deserialize<{csType}>(_{propName}El.GetRawText(), options);");
            }
            else
            {
                sb.AppendLine($"        if (doc.RootElement.TryGetProperty(\"{prop.Name}\", out var _{propName}El))");
                sb.AppendLine($"            result.{propName} = JsonSerializer.Deserialize<{csType}>(_{propName}El.GetRawText(), options)!;");
            }
        }
    }

    sb.AppendLine("        return result;");
    sb.AppendLine("    }");
    sb.AppendLine();

    // Write: serialize base + merge local properties
    sb.AppendLine($"    public override void Write(Utf8JsonWriter writer, {pascalName} value, JsonSerializerOptions options)");
    sb.AppendLine("    {");
    sb.AppendLine("        if (value == null) { writer.WriteNullValue(); return; }");
    sb.AppendLine("        writer.WriteStartObject();");
    sb.AppendLine($"        using var baseDoc = JsonDocument.Parse(JsonSerializer.Serialize(value.Base, options));");
    sb.AppendLine("        foreach (var prop in baseDoc.RootElement.EnumerateObject())");
    sb.AppendLine("            prop.WriteTo(writer);");

    if (propsEl.ValueKind != JsonValueKind.Undefined)
    {
        foreach (var prop in propsEl.EnumerateObject().OrderBy(p => p.Name))
        {
            var propName = ToPascalCase(prop.Name);
            var (_, isNullable) = ConvertPropertyType(prop.Value, usings);
            if (isNullable)
            {
                sb.AppendLine($"        if (value.{propName} != null)");
                sb.AppendLine("        {");
                sb.AppendLine($"            writer.WritePropertyName(\"{prop.Name}\");");
                sb.AppendLine($"            JsonSerializer.Serialize(writer, value.{propName}, options);");
                sb.AppendLine("        }");
            }
            else
            {
                sb.AppendLine($"        writer.WritePropertyName(\"{prop.Name}\");");
                sb.AppendLine($"        JsonSerializer.Serialize(writer, value.{propName}, options);");
            }
        }
    }

    sb.AppendLine("        writer.WriteEndObject();");
    sb.AppendLine("    }");
    sb.AppendLine("}");
    return sb.ToString();
}

