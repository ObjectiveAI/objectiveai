// ===========================================================================
// Property emission
// ===========================================================================

void EmitProperties(StringBuilder sb, JsonElement propsEl, HashSet<string> usings, string? enclosingClassName = null)
{
    var props = propsEl.EnumerateObject().OrderBy(p => p.Name).ToList();
    for (int i = 0; i < props.Count; i++)
    {
        var prop = props[i];
        var propName = prop.Name;
        var propSchema = prop.Value;
        var propDesc = GetString(propSchema, "description");
        var csPropName = ToPascalCase(propName.TrimStart('$'));
        if (enclosingClassName != null && csPropName == enclosingClassName)
            csPropName += "Value";

        if (propDesc != null)
        {
            sb.AppendLine("    /// <summary>");
            foreach (var line in propDesc.Split('\n'))
                sb.AppendLine($"    /// {EscapeXml(line)}");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine($"    [Description({EscapeCSharpString(propDesc)})]");
        }

        sb.AppendLine($"    [JsonPropertyName(\"{propName}\")]");

        var (csType, isNullable) = ConvertPropertyType(propSchema, usings);

        // Detect inline anyOf and store as attribute
        if (propSchema.TryGetProperty("anyOf", out var propAnyOf))
        {
            var propVariants = propAnyOf.EnumerateArray().ToList();
            if (!isNullable && !IsNullable(propVariants))
            {
                // Non-nullable inline anyOf: store the full anyOf JSON
                sb.AppendLine($"    [JsonSchemaPropertyAnyOf({EscapeCSharpString(propAnyOf.GetRawText())})]");
            }
            else if (isNullable)
            {
                // Nullable property: check if the non-null variant has its own anyOf
                var nonNull = propVariants.FirstOrDefault(v => GetString(v, "type") != "null");
                if (nonNull.ValueKind != JsonValueKind.Undefined && nonNull.TryGetProperty("anyOf", out _))
                {
                    // Non-null variant has nested anyOf — store the non-null variant's full JSON
                    sb.AppendLine($"    [JsonSchemaPropertyAnyOf({EscapeCSharpString(nonNull.GetRawText())})]");
                }
            }
        }

        EmitPropertySchemaAttributes(sb, propSchema, isNullable, "    ");

        // omitempty
        if (propSchema.TryGetProperty("omitempty", out var oeEl) && oeEl.ValueKind == JsonValueKind.True)
        {
            sb.AppendLine("    [JsonSchemaOmitEmpty]");
        }

        // Default value
        string? defaultInit = null;
        if (propSchema.TryGetProperty("default", out var defaultEl))
        {
            defaultInit = ConvertDefaultValue(defaultEl, csType);
            var jsonDefault = defaultEl.GetRawText();
            sb.AppendLine($"    [JsonSchemaDefault({EscapeCSharpString(jsonDefault)})]");
            // If property name matches type name, enum member syntax won't compile in initializer
            if (defaultInit != null && csPropName == csType && defaultInit.StartsWith(csType + "."))
                defaultInit = "default!";
        }

        if (isNullable)
        {
            sb.AppendLine("    [JsonSchemaNullable]");
            var initValue = defaultInit ?? "null";
            if (csType.EndsWith("?"))
                sb.AppendLine($"    public {csType} {csPropName} {{ get; set; }} = {initValue};");
            else
                sb.AppendLine($"    public {csType}? {csPropName} {{ get; set; }} = {initValue};");
        }
        else
        {
            if (defaultInit != null)
                sb.AppendLine($"    public {csType} {csPropName} {{ get; set; }} = {defaultInit};");
            else
                sb.AppendLine($"    public {csType} {csPropName} {{ get; set; }} = default!;");
        }

        if (i < props.Count - 1)
            sb.AppendLine();
    }
}

// ---------------------------------------------------------------------------
// Variant constraint attribute emission
// ---------------------------------------------------------------------------

void EmitVariantConstraintAttributes(StringBuilder sb, VariantInfo info, string indent)
{
    // Range (minimum/maximum)
    if (info.Minimum != null || info.Maximum != null)
    {
        var parts = new List<string>();
        if (info.Minimum != null) parts.Add($"Minimum = {EscapeCSharpString(info.Minimum)}");
        if (info.Maximum != null) parts.Add($"Maximum = {EscapeCSharpString(info.Maximum)}");
        sb.AppendLine($"{indent}[JsonSchemaRange({string.Join(", ", parts)})]");
    }

    // Format
    if (info.Format != null && info.Format != "date-time")
        sb.AppendLine($"{indent}[JsonSchemaFormat(\"{info.Format}\")]");

    // Pattern
    if (info.Pattern != null)
    {
        sb.AppendLine($"{indent}[RegularExpression({EscapeCSharpString(info.Pattern)})]");
    }

    // Items constraints (for array variants)
    if (info.ItemsNullable)
        sb.AppendLine($"{indent}[JsonSchemaItemsNullable]");
    if (info.ItemsMinimum != null || info.ItemsMaximum != null)
    {
        var parts = new List<string>();
        if (info.ItemsMinimum != null) parts.Add($"Minimum = {EscapeCSharpString(info.ItemsMinimum)}");
        if (info.ItemsMaximum != null) parts.Add($"Maximum = {EscapeCSharpString(info.ItemsMaximum)}");
        sb.AppendLine($"{indent}[JsonSchemaItemsRange({string.Join(", ", parts)})]");
    }

    // additionalProperties
    if (info.AdditionalPropertiesFullJson != null)
    {
        sb.AppendLine($"{indent}[JsonSchemaAdditionalPropertiesSchema({EscapeCSharpString(info.AdditionalPropertiesFullJson)})]");
    }
    else if (info.AdditionalPropertiesSchema != null)
    {
        if (info.AdditionalPropertiesSchema == "false")
            sb.AppendLine($"{indent}[JsonSchemaAdditionalProperties(false)]");
        else
            sb.AppendLine($"{indent}[JsonSchemaAdditionalPropertiesSchema({EscapeCSharpString(info.AdditionalPropertiesSchema)})]");
    }

    // Items schema (for array variants with complex items)
    if (info.ItemsSchemaJson != null)
        sb.AppendLine($"{indent}[JsonSchemaItemsSchema({EscapeCSharpString(info.ItemsSchemaJson)})]");
}

// ---------------------------------------------------------------------------
// Property schema attributes
// ---------------------------------------------------------------------------

void EmitPropertySchemaAttributes(StringBuilder sb, JsonElement propSchema, bool isNullable, string indent)
{
    JsonElement constraintSource = propSchema;
    if (isNullable && propSchema.TryGetProperty("anyOf", out var anyOfEl))
    {
        var variants = anyOfEl.EnumerateArray().ToList();
        var nonNull = variants.FirstOrDefault(v => GetString(v, "type") != "null");
        if (nonNull.ValueKind != JsonValueKind.Undefined)
            constraintSource = nonNull;
    }

    EmitPropertyConstraintAttributes(sb, constraintSource, indent);

    if (constraintSource.TryGetProperty("type", out var typeEl))
    {
        if (typeEl.GetString() == "array")
            EmitArrayItemConstraintAttributes(sb, constraintSource, indent);
        else if (typeEl.GetString() == "object" && constraintSource.TryGetProperty("additionalProperties", out var apEl3) && apEl3.ValueKind == JsonValueKind.Object)
        {
            if (apEl3.TryGetProperty("minimum", out var apMinEl) || apEl3.TryGetProperty("maximum", out var apMaxEl))
            {
                var parts = new List<string>();
                if (apEl3.TryGetProperty("minimum", out apMinEl))
                    parts.Add($"Minimum = {EscapeCSharpString(apMinEl.GetRawText())}");
                if (apEl3.TryGetProperty("maximum", out apMaxEl))
                    parts.Add($"Maximum = {EscapeCSharpString(apMaxEl.GetRawText())}");
                sb.AppendLine($"{indent}[JsonSchemaItemsRange({string.Join(", ", parts)})]");
            }
        }
    }
}

void EmitPropertyConstraintAttributes(StringBuilder sb, JsonElement schema, string indent)
{
    if (schema.TryGetProperty("minimum", out var minEl2) || schema.TryGetProperty("maximum", out var maxEl2))
    {
        var parts = new List<string>();
        if (schema.TryGetProperty("minimum", out minEl2))
            parts.Add($"Minimum = {EscapeCSharpString(minEl2.GetRawText())}");
        if (schema.TryGetProperty("maximum", out maxEl2))
            parts.Add($"Maximum = {EscapeCSharpString(maxEl2.GetRawText())}");
        sb.AppendLine($"{indent}[JsonSchemaRange({string.Join(", ", parts)})]");
    }

    if (schema.TryGetProperty("pattern", out var patEl))
    {
        usings_add_dataannotations();
        sb.AppendLine($"{indent}[RegularExpression({EscapeCSharpString(patEl.GetString()!)})]");
    }

    if (schema.TryGetProperty("format", out var fmtEl))
    {
        var fmt = fmtEl.GetString()!;
        if (fmt != "date-time")
            sb.AppendLine($"{indent}[JsonSchemaFormat(\"{fmt}\")]");
    }

    if (schema.TryGetProperty("enum", out var enumEl))
    {
        var values = enumEl.EnumerateArray().Select(e => $"\"{e.GetString()!}\"").ToList();
        sb.AppendLine($"{indent}[JsonSchemaEnum({string.Join(", ", values)})]");
    }

    if (schema.TryGetProperty("additionalProperties", out var apEl2))
    {
        if (apEl2.ValueKind == JsonValueKind.True)
            sb.AppendLine($"{indent}[JsonSchemaAdditionalPropertiesSchema(\"true\")]");
        else if (apEl2.ValueKind == JsonValueKind.Object && apEl2.TryGetProperty("$ref", out var apRefEl2))
            sb.AppendLine($"{indent}[JsonSchemaAdditionalPropertiesSchema(\"$ref:{apRefEl2.GetString()}\")]");
    }
}

void EmitArrayItemConstraintAttributes(StringBuilder sb, JsonElement arraySchema, string indent, bool skipNullableAttr = false)
{
    if (!arraySchema.TryGetProperty("items", out var itemsEl)) return;

    if (itemsEl.TryGetProperty("anyOf", out var anyOfEl))
    {
        var variants = anyOfEl.EnumerateArray().ToList();
        if (IsNullable(variants))
        {
            if (!skipNullableAttr)
                sb.AppendLine($"{indent}[JsonSchemaItemsNullable]");
            var nonNull = variants.First(v => GetString(v, "type") != "null");
            if (nonNull.TryGetProperty("minimum", out var minEl3) || nonNull.TryGetProperty("maximum", out var maxEl3))
            {
                var parts = new List<string>();
                if (nonNull.TryGetProperty("minimum", out minEl3))
                    parts.Add($"Minimum = {EscapeCSharpString(minEl3.GetRawText())}");
                if (nonNull.TryGetProperty("maximum", out maxEl3))
                    parts.Add($"Maximum = {EscapeCSharpString(maxEl3.GetRawText())}");
                sb.AppendLine($"{indent}[JsonSchemaItemsRange({string.Join(", ", parts)})]");
            }
            return;
        }
    }

    var constraintEl = itemsEl;
    while (constraintEl.TryGetProperty("type", out var cTypeEl) && cTypeEl.GetString() == "array" && constraintEl.TryGetProperty("items", out var nestedItems))
        constraintEl = nestedItems;

    if (constraintEl.TryGetProperty("minimum", out var iminEl) || constraintEl.TryGetProperty("maximum", out var imaxEl))
    {
        var parts = new List<string>();
        if (constraintEl.TryGetProperty("minimum", out iminEl))
            parts.Add($"Minimum = {EscapeCSharpString(iminEl.GetRawText())}");
        if (constraintEl.TryGetProperty("maximum", out imaxEl))
            parts.Add($"Maximum = {EscapeCSharpString(imaxEl.GetRawText())}");
        sb.AppendLine($"{indent}[JsonSchemaItemsRange({string.Join(", ", parts)})]");
    }
}

