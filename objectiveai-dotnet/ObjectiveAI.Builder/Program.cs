string GenerateType(string title, JsonElement schema, HashSet<string> usings)
{
    var pascalName = TitleToClassName(title);
    var hasProperties = schema.TryGetProperty("properties", out var propsEl);
    var hasAnyOf = schema.TryGetProperty("anyOf", out var anyOfEl);
    var hasRef = schema.TryGetProperty("$ref", out _);
    var hasType = schema.TryGetProperty("type", out var typeEl);
    var description = GetString(schema, "description");

    // Case 1: anyOf at top level (union)
    if (hasAnyOf && !hasProperties && !hasRef)
    {
        var variants = anyOfEl.EnumerateArray().ToList();

        // Check if all variants are single-value string enums → C# enum (with descriptions)
        if (IsStringEnumAnyOf(variants))
        {
            return GenerateUnionClass(title, pascalName, description, variants, usings);
        }

        // Check for nullable (2 variants, one null) — top-level nullable
        if (IsNullable(variants))
        {
            var nonNull = variants.First(v => GetString(v, "type") != "null");
            return GenerateNullableWrapper(title, pascalName, description, nonNull, usings);
        }

        // General anyOf → union class
        return GenerateUnionClass(title, pascalName, description, variants, usings);
    }

    // Case 2: Object with properties
    if (hasProperties || (hasType && typeEl.GetString() == "object"))
    {
        // Check for $ref + properties (flattened ref model)
        if (hasRef)
        {
            return GenerateFlattenedRefModel(title, pascalName, description, schema, propsEl, usings);
        }
        return GenerateObjectClass(title, pascalName, description, schema, propsEl, usings);
    }

    // Case 3: flat enum (type: string + enum, no anyOf)
    if (schema.TryGetProperty("enum", out var enumEl) && hasType && typeEl.GetString() == "string")
    {
        var values = enumEl.EnumerateArray().Select(e => e.GetString()!).ToList();
        return GenerateSimpleEnum(title, pascalName, description, values, usings);
    }

    // Case 4: array
    if (hasType && typeEl.GetString() == "array")
    {
        return GenerateArrayWrapper(title, pascalName, description, schema, usings);
    }

    // Case 5: primitive or $ref
    return GeneratePrimitiveWrapper(title, pascalName, description, schema, usings);
}

// ===========================================================================
// Union class generation (Go-style: class with nullable variant properties)
// ===========================================================================

string GenerateUnionClass(string title, string pascalName, string? description, List<JsonElement> variants, HashSet<string> usings)
{
    usings.Add("System.Text.Json");

    var sb = new StringBuilder();
    var helperTypes = new StringBuilder();
    var variantInfos = new List<VariantInfo>();

    // Analyze each variant
    foreach (var variant in variants)
    {
        var info = AnalyzeVariant(pascalName, variant, usings, helperTypes);
        variantInfos.Add(info);
    }

    // Emit helper types (wrapper classes, inline classes) before the union class
    if (helperTypes.Length > 0)
    {
        sb.Append(helperTypes);
        sb.AppendLine();
    }

    // Emit the union class
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");
    sb.AppendLine($"[JsonConverter(typeof({pascalName}Converter))]");
    sb.AppendLine($"public partial class {pascalName}");
    sb.AppendLine("{");

    for (int i = 0; i < variantInfos.Count; i++)
    {
        var info = variantInfos[i];
        if (info.Description != null)
        {
            sb.AppendLine("    /// <summary>");
            foreach (var line in info.Description.Split('\n'))
                sb.AppendLine($"    /// {EscapeXml(line)}");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine($"    [Description({EscapeCSharpString(info.Description)})]");
        }

        // Build [JsonSchemaVariant] attribute
        var attrParts = new List<string> { EscapeCSharpString(info.Title) };
        if (info.Ref != null)
            attrParts.Add($"Ref = {EscapeCSharpString(info.Ref)}");
        if (info.Type != null)
            attrParts.Add($"Type = {EscapeCSharpString(info.Type)}");
        if (info.EnumValues != null)
            attrParts.Add($"Enum = new[] {{ {string.Join(", ", info.EnumValues.Select(EscapeCSharpString))} }}");
        sb.AppendLine($"    [JsonSchemaVariant({string.Join(", ", attrParts)})]");

        // Emit additional constraint attributes
        EmitVariantConstraintAttributes(sb, info, "    ");

        // Emit property
        sb.AppendLine($"    public {info.CsType} {info.PropertyName} {{ get; set; }}");

        if (i < variantInfos.Count - 1)
            sb.AppendLine();
    }

    sb.AppendLine("}");
    sb.AppendLine();

    // Emit converter
    sb.Append(GenerateConverterClass(pascalName, variantInfos, usings));

    return sb.ToString();
}

// ---------------------------------------------------------------------------
// Variant analysis
// ---------------------------------------------------------------------------

VariantInfo AnalyzeVariant(string unionPascalName, JsonElement variant, HashSet<string> usings, StringBuilder helperTypes)
{
    var variantTitle = GetString(variant, "title") ?? "Unknown";
    var variantDesc = GetString(variant, "description");
    var propName = ToPascalCase(variantTitle);
    // Avoid property name colliding with enclosing class name
    if (propName == unionPascalName)
        propName += "Value";
    var hasRef = variant.TryGetProperty("$ref", out var refEl);
    var hasType = variant.TryGetProperty("type", out var typeEl);
    var hasProps = variant.TryGetProperty("properties", out var propsEl);
    var hasEnum = variant.TryGetProperty("enum", out var enumEl);
    var hasAp = variant.TryGetProperty("additionalProperties", out var apEl);

    string? refTitle = hasRef ? refEl.GetString() : null;
    string? jsonType = hasType ? typeEl.GetString() : null;
    string[]? enumValues = hasEnum
        ? enumEl.EnumerateArray().Select(e => e.GetString()!).ToArray()
        : null;

    string? minimum = GetString(variant, "minimum") ?? (variant.TryGetProperty("minimum", out var minEl) ? minEl.GetRawText() : null);
    string? maximum = GetString(variant, "maximum") ?? (variant.TryGetProperty("maximum", out var maxEl) ? maxEl.GetRawText() : null);
    string? format = GetString(variant, "format");
    string? pattern = GetString(variant, "pattern");

    // Determine items constraints for arrays
    string? itemsMin = null, itemsMax = null;
    bool itemsNullable = false;
    if (jsonType == "array" && variant.TryGetProperty("items", out var itemsEl))
    {
        // Check for nullable items
        if (itemsEl.TryGetProperty("anyOf", out var itemsAnyOf))
        {
            var itemVariants = itemsAnyOf.EnumerateArray().ToList();
            if (IsNullable(itemVariants))
            {
                itemsNullable = true;
                var nonNull = itemVariants.First(v => GetString(v, "type") != "null");
                itemsMin = nonNull.TryGetProperty("minimum", out var imn) ? imn.GetRawText() : null;
                itemsMax = nonNull.TryGetProperty("maximum", out var imx) ? imx.GetRawText() : null;
            }
        }
        else
        {
            // Drill through nested arrays to find leaf constraints
            var leaf = itemsEl;
            while (leaf.TryGetProperty("type", out var lt) && lt.GetString() == "array" && leaf.TryGetProperty("items", out var ni))
                leaf = ni;
            itemsMin = leaf.TryGetProperty("minimum", out var lmn) ? lmn.GetRawText() : null;
            itemsMax = leaf.TryGetProperty("maximum", out var lmx) ? lmx.GetRawText() : null;
        }
    }

    // additionalProperties encoding
    string? apSchema = null;
    if (hasAp)
    {
        if (apEl.ValueKind == JsonValueKind.True)
            apSchema = "true";
        else if (apEl.ValueKind == JsonValueKind.False)
            apSchema = "false";
        else if (apEl.ValueKind == JsonValueKind.Object && apEl.TryGetProperty("$ref", out var apRef))
            apSchema = $"$ref:{apRef.GetString()}";
    }

    // --- Determine C# type ---

    // 1. $ref + type + properties → discriminated variant wrapper class
    if (hasRef && hasType && hasProps)
    {
        var wrapperName = $"{unionPascalName}{propName}";
        var baseType = ResolveRefType(refTitle!, usings);
        helperTypes.Append(GenerateWrapperClass(wrapperName, refTitle!, jsonType!, baseType, variantDesc, propsEl, usings));
        helperTypes.AppendLine();
        return new(variantTitle, variantDesc, propName, $"{wrapperName}?", refTitle, jsonType, enumValues,
            minimum, maximum, format, pattern, itemsMin, itemsMax, itemsNullable, apSchema, false, false, variant);
    }

    // 2. $ref + properties (no explicit type) → same as above with type "object"
    if (hasRef && hasProps)
    {
        var wrapperName = $"{unionPascalName}{propName}";
        var baseType = ResolveRefType(refTitle!, usings);
        helperTypes.Append(GenerateWrapperClass(wrapperName, refTitle!, "object", baseType, variantDesc, propsEl, usings));
        helperTypes.AppendLine();
        return new(variantTitle, variantDesc, propName, $"{wrapperName}?", refTitle, "object", enumValues,
            minimum, maximum, format, pattern, itemsMin, itemsMax, itemsNullable, apSchema, false, false, variant);
    }

    // 3. Pure $ref
    if (hasRef && !hasType && !hasProps)
    {
        var csType = ResolveRefType(refTitle!, usings);
        return new(variantTitle, variantDesc, propName, $"{csType}?", refTitle, null, null,
            null, null, null, null, null, null, false, null, false, false, variant);
    }

    // 4. type: string + enum → string
    if (jsonType == "string" && hasEnum)
    {
        return new(variantTitle, variantDesc, propName, "string?", null, "string", enumValues,
            minimum, maximum, format, pattern, null, null, false, null, false, false, variant);
    }

    // 5. type: string (no enum)
    if (jsonType == "string" && !hasEnum)
    {
        return new(variantTitle, variantDesc, propName, "string?", null, "string", null,
            minimum, maximum, format, pattern, null, null, false, null, false, false, variant);
    }

    // 6. type: integer
    if (jsonType == "integer")
    {
        var csIntType = ConvertIntegerType(variant);
        return new(variantTitle, variantDesc, propName, $"{csIntType}?", null, "integer", null,
            minimum, maximum, format, pattern, null, null, false, null, false, true, variant);
    }

    // 7. type: number
    if (jsonType == "number")
    {
        return new(variantTitle, variantDesc, propName, "double?", null, "number", null,
            minimum, maximum, format, pattern, null, null, false, null, false, true, variant);
    }

    // 8. type: boolean
    if (jsonType == "boolean")
    {
        return new(variantTitle, variantDesc, propName, "bool?", null, "boolean", null,
            null, null, null, null, null, null, false, null, false, true, variant);
    }

    // 9. type: array
    if (jsonType == "array")
    {
        var csArrayType = ConvertArrayType(variant, usings);
        // Check if items has inline anyOf that needs raw JSON storage
        string? itemsJson = null;
        if (variant.TryGetProperty("items", out var arrItemsEl))
        {
            if (arrItemsEl.TryGetProperty("anyOf", out var arrItemsAnyOf))
            {
                var arrItemVariants = arrItemsAnyOf.EnumerateArray().ToList();
                if (!IsNullable(arrItemVariants))
                    itemsJson = arrItemsEl.GetRawText();
            }
        }
        return new(variantTitle, variantDesc, propName, $"{csArrayType}?", null, "array", null,
            minimum, maximum, format, pattern, itemsMin, itemsMax, itemsNullable, null, false, false, variant,
            ItemsSchemaJson: itemsJson);
    }

    // 10. type: object + properties → inline object class
    if (jsonType == "object" && hasProps)
    {
        var inlineName = $"{unionPascalName}{propName}";
        helperTypes.Append(GenerateInlineObjectClass(inlineName, variantDesc, propsEl, apEl, hasAp, usings));
        helperTypes.AppendLine();
        return new(variantTitle, variantDesc, propName, $"{inlineName}?", null, "object", null,
            null, null, null, null, null, null, false, apSchema, false, false, variant);
    }

    // 11. type: object + additionalProperties → Dictionary
    if (jsonType == "object" && hasAp)
    {
        var csObjType = ConvertObjectType(variant, usings);
        // Check if additionalProperties has inline anyOf
        string? apFullJson = null;
        if (apEl.ValueKind == JsonValueKind.Object && apEl.TryGetProperty("anyOf", out _))
            apFullJson = apEl.GetRawText();
        return new(variantTitle, variantDesc, propName, $"{csObjType}?", null, "object", null,
            null, null, null, null, null, null, false, apSchema, false, false, variant,
            AdditionalPropertiesFullJson: apFullJson);
    }

    // 12. type: object (bare)
    if (jsonType == "object")
    {
        usings.Add("System.Text.Json");
        return new(variantTitle, variantDesc, propName, "Dictionary<string, JsonElement>?", null, "object", null,
            null, null, null, null, null, null, false, null, false, false, variant);
    }

    // 13. type: null → skip (shouldn't appear in top-level anyOf)
    if (jsonType == "null")
    {
        return new(variantTitle, variantDesc, propName, "object?", null, "null", null,
            null, null, null, null, null, null, false, null, true, false, variant);
    }

    // 14. Bare schema (no type, no $ref) → JsonElement
    usings.Add("System.Text.Json");
    return new(variantTitle, variantDesc, propName, "JsonElement?", null, null, null,
        null, null, null, null, null, null, false, null, true, true, variant);
}

// ---------------------------------------------------------------------------
// Wrapper class generation (for discriminated union variants: $ref + type + props)
// ---------------------------------------------------------------------------

string GenerateWrapperClass(string className, string refTitle, string jsonType, string baseTypeName, string? description, JsonElement propsEl, HashSet<string> usings)
{
    var sb = new StringBuilder();
    AppendDescription(sb, description);
    var wrapperAttrParts = new List<string> { EscapeCSharpString(refTitle) };
    wrapperAttrParts.Add($"Type = {EscapeCSharpString(jsonType)}");
    sb.AppendLine($"[JsonSchemaVariantWrapper({string.Join(", ", wrapperAttrParts)})]");
    sb.AppendLine($"public partial class {className}");
    sb.AppendLine("{");
    EmitProperties(sb, propsEl, usings, className);
    sb.AppendLine("}");
    return sb.ToString();
}

// ---------------------------------------------------------------------------
// Inline object class generation (for inline object variants)
// ---------------------------------------------------------------------------

string GenerateInlineObjectClass(string className, string? description, JsonElement propsEl, JsonElement apEl, bool hasAp, HashSet<string> usings)
{
    var sb = new StringBuilder();
    AppendDescription(sb, description);
    if (hasAp && apEl.ValueKind == JsonValueKind.False)
        sb.AppendLine("[JsonSchemaAdditionalProperties(false)]");
    sb.AppendLine($"public partial class {className}");
    sb.AppendLine("{");
    EmitProperties(sb, propsEl, usings, className);
    sb.AppendLine("}");
    return sb.ToString();
}

// ===========================================================================
// Converter generation
// ===========================================================================

string GenerateConverterClass(string pascalName, List<VariantInfo> variants, HashSet<string> usings)
{
    usings.Add("System.Text.Json");
    var sb = new StringBuilder();
    sb.AppendLine($"public class {pascalName}Converter : JsonConverter<{pascalName}>");
    sb.AppendLine("{");

    // --- Read method ---
    sb.AppendLine($"    public override {pascalName}? Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)");
    sb.AppendLine("    {");
    sb.AppendLine("        if (reader.TokenType == JsonTokenType.Null) { reader.Read(); return null; }");

    // Check if all variants are string enums → use string switch
    bool allStringEnum = variants.All(v => v.Type == "string" && v.EnumValues is { Length: > 0 });
    if (allStringEnum)
    {
        sb.AppendLine("        if (reader.TokenType != JsonTokenType.String)");
        sb.AppendLine($"            throw new JsonException(\"Expected string for {pascalName}\");");
        sb.AppendLine("        var str = reader.GetString()!;");
        sb.AppendLine("        return str switch");
        sb.AppendLine("        {");
        foreach (var v in variants)
        {
            sb.AppendLine($"            \"{v.EnumValues![0]}\" => new {pascalName} {{ {v.PropertyName} = \"{v.EnumValues[0]}\" }},");
        }
        sb.AppendLine($"            _ => throw new JsonException($\"Unknown variant of {pascalName}: {{str}}\")");
        sb.AppendLine("        };");
    }
    else
    {
        sb.AppendLine("        using var doc = JsonDocument.ParseValue(ref reader);");
        sb.AppendLine("        var el = doc.RootElement;");
        sb.AppendLine("        var raw = el.GetRawText();");
        sb.AppendLine();

        // Group variants by JSON value kind for efficient dispatch
        var stringVariants = variants.Where(v => v.Type == "string" && !v.IsBareSchema).ToList();
        var numberVariants = variants.Where(v => v.Type is "number" or "integer").ToList();
        var boolVariants = variants.Where(v => v.Type == "boolean").ToList();
        var objectVariants = variants.Where(v => v.Type == "object" || (v.Ref != null && v.Type != "string" && v.Type != "array")).ToList();
        var arrayVariants = variants.Where(v => v.Type == "array").ToList();
        var bareVariants = variants.Where(v => v.IsBareSchema).ToList();

        if (stringVariants.Count > 0)
        {
            sb.AppendLine("        if (el.ValueKind == JsonValueKind.String)");
            sb.AppendLine("        {");
            sb.AppendLine("            var str = el.GetString()!;");
            // If any have enum constraints, check them
            bool hasEnumVariants = stringVariants.Any(v => v.EnumValues != null);
            if (hasEnumVariants)
            {
                foreach (var v in stringVariants.Where(sv => sv.EnumValues != null))
                {
                    var enumCheck = string.Join(" || ", v.EnumValues!.Select(e => $"str == \"{e}\""));
                    sb.AppendLine($"            if ({enumCheck})");
                    sb.AppendLine($"                return new {pascalName} {{ {v.PropertyName} = str }};");
                }
            }
            // Plain string variants (no enum constraint)
            var plainStrings = stringVariants.Where(v => v.EnumValues == null).ToList();
            if (plainStrings.Count > 0)
            {
                sb.AppendLine($"            return new {pascalName} {{ {plainStrings[0].PropertyName} = str }};");
            }
            else if (hasEnumVariants)
            {
                // All string variants have enum constraints but none matched
                sb.AppendLine($"            throw new JsonException($\"No string variant of {pascalName} matched: {{str}}\");");
            }
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        if (numberVariants.Count > 0)
        {
            sb.AppendLine("        if (el.ValueKind == JsonValueKind.Number)");
            sb.AppendLine("        {");
            if (numberVariants.Count == 1)
            {
                var v = numberVariants[0];
                if (v.Type == "integer")
                    sb.AppendLine($"            return new {pascalName} {{ {v.PropertyName} = el.GetInt64() }};");
                else
                    sb.AppendLine($"            return new {pascalName} {{ {v.PropertyName} = el.GetDouble() }};");
            }
            else
            {
                // Multiple number variants — try integer first, then double
                var intVs = numberVariants.Where(v => v.Type == "integer").ToList();
                var dblVs = numberVariants.Where(v => v.Type == "number").ToList();
                if (intVs.Count > 0)
                {
                    sb.AppendLine("            if (el.TryGetInt64(out var intVal))");
                    sb.AppendLine($"                return new {pascalName} {{ {intVs[0].PropertyName} = intVal }};");
                }
                if (dblVs.Count > 0)
                {
                    sb.AppendLine($"            return new {pascalName} {{ {dblVs[0].PropertyName} = el.GetDouble() }};");
                }
            }
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        if (boolVariants.Count > 0)
        {
            sb.AppendLine("        if (el.ValueKind == JsonValueKind.True || el.ValueKind == JsonValueKind.False)");
            sb.AppendLine($"            return new {pascalName} {{ {boolVariants[0].PropertyName} = el.GetBoolean() }};");
            sb.AppendLine();
        }

        if (arrayVariants.Count > 0)
        {
            sb.AppendLine("        if (el.ValueKind == JsonValueKind.Array)");
            sb.AppendLine("        {");
            if (arrayVariants.Count == 1)
            {
                var v = arrayVariants[0];
                var innerType = v.CsType.TrimEnd('?');
                sb.AppendLine($"            var val = JsonSerializer.Deserialize<{innerType}>(raw, options);");
                sb.AppendLine($"            return new {pascalName} {{ {v.PropertyName} = val }};");
            }
            else
            {
                foreach (var v in arrayVariants)
                {
                    var innerType = v.CsType.TrimEnd('?');
                    sb.AppendLine($"            try {{ var val = JsonSerializer.Deserialize<{innerType}>(raw, options); if (val != null) return new {pascalName} {{ {v.PropertyName} = val }}; }}");
                    sb.AppendLine("            catch (JsonException) { }");
                }
            }
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        if (objectVariants.Count > 0)
        {
            sb.AppendLine("        if (el.ValueKind == JsonValueKind.Object)");
            sb.AppendLine("        {");
            int objIdx = 0;
            foreach (var v in objectVariants)
            {
                var innerType = v.CsType.TrimEnd('?');
                var enumChecks = GetEnumConstraintsForVariant(v);
                if (enumChecks.Count > 0)
                {
                    // Use a nested block to avoid variable name collisions
                    sb.AppendLine("            {");
                    sb.AppendLine($"                bool match{objIdx} = true;");
                    foreach (var ec in enumChecks)
                    {
                        sb.AppendLine($"                if (!(el.TryGetProperty(\"{ec.Field}\", out var c{objIdx}_{ec.Field}) && c{objIdx}_{ec.Field}.GetString() == \"{ec.Value}\"))");
                        sb.AppendLine($"                    match{objIdx} = false;");
                    }
                    sb.AppendLine($"                if (match{objIdx})");
                    sb.AppendLine("                {");
                    sb.AppendLine($"                    try {{ var val = JsonSerializer.Deserialize<{innerType}>(raw, options); if (val != null) return new {pascalName} {{ {v.PropertyName} = val }}; }}");
                    sb.AppendLine("                    catch (JsonException) { }");
                    sb.AppendLine("                }");
                    sb.AppendLine("            }");
                }
                else
                {
                    sb.AppendLine($"            try {{ var val{objIdx} = JsonSerializer.Deserialize<{innerType}>(raw, options); if (val{objIdx} != null) return new {pascalName} {{ {v.PropertyName} = val{objIdx} }}; }}");
                    sb.AppendLine("            catch (JsonException) { }");
                }
                objIdx++;
            }
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        if (bareVariants.Count > 0)
        {
            sb.AppendLine($"        return new {pascalName} {{ {bareVariants[0].PropertyName} = el.Clone() }};");
        }
        else
        {
            sb.AppendLine($"        throw new JsonException($\"Data did not match any variant of {pascalName}\");");
        }
    }
    sb.AppendLine("    }");
    sb.AppendLine();

    // --- Write method ---
    sb.AppendLine($"    public override void Write(Utf8JsonWriter writer, {pascalName} value, JsonSerializerOptions options)");
    sb.AppendLine("    {");
    sb.AppendLine("        if (value == null) { writer.WriteNullValue(); return; }");
    foreach (var v in variants)
    {
        sb.AppendLine($"        if (value.{v.PropertyName} != null)");
        sb.AppendLine("        {");
        if (v.Type == "string" && v.EnumValues != null)
        {
            sb.AppendLine($"            writer.WriteStringValue(value.{v.PropertyName});");
        }
        else if (v.Type == "string" && v.EnumValues == null)
        {
            sb.AppendLine($"            writer.WriteStringValue(value.{v.PropertyName});");
        }
        else if (v.Type == "integer")
        {
            if (v.CsType.StartsWith("ulong"))
                sb.AppendLine($"            writer.WriteNumberValue(value.{v.PropertyName}.Value);");
            else
                sb.AppendLine($"            writer.WriteNumberValue(value.{v.PropertyName}.Value);");
        }
        else if (v.Type == "number")
        {
            sb.AppendLine($"            writer.WriteNumberValue(value.{v.PropertyName}.Value);");
        }
        else if (v.Type == "boolean")
        {
            sb.AppendLine($"            writer.WriteBooleanValue(value.{v.PropertyName}.Value);");
        }
        else if (v.IsBareSchema && v.CsType == "JsonElement?")
        {
            sb.AppendLine($"            value.{v.PropertyName}.Value.WriteTo(writer);");
        }
        else
        {
            var innerType = v.CsType.TrimEnd('?');
            sb.AppendLine($"            JsonSerializer.Serialize(writer, value.{v.PropertyName}, options);");
        }
        sb.AppendLine("            return;");
        sb.AppendLine("        }");
    }
    sb.AppendLine("        writer.WriteNullValue();");
    sb.AppendLine("    }");

    sb.AppendLine("}");
    return sb.ToString();
}

// ---------------------------------------------------------------------------
// Enum constraint extraction for converter discrimination
// ---------------------------------------------------------------------------

List<EnumConstraint> GetEnumConstraintsForVariant(VariantInfo v)
{
    var constraints = new List<EnumConstraint>();

    // For discriminated variants (wrapper classes with $ref + type + properties),
    // check the properties of the variant itself
    if (v.OriginalVariant.TryGetProperty("properties", out var vProps))
    {
        foreach (var prop in vProps.EnumerateObject())
        {
            if (prop.Value.TryGetProperty("enum", out var enumEl) && enumEl.GetArrayLength() == 1)
            {
                constraints.Add(new(prop.Name, enumEl[0].GetString()!));
            }
        }
    }

    // For pure $ref variants, check the referenced schema's enum-constrained fields
    if (constraints.Count == 0 && v.Ref != null && schemas.TryGetValue(v.Ref, out var refSchema))
    {
        if (refSchema.TryGetProperty("properties", out var refProps))
        {
            foreach (var prop in refProps.EnumerateObject())
            {
                // Direct inline enum
                if (prop.Value.TryGetProperty("enum", out var enumEl) && enumEl.GetArrayLength() == 1)
                {
                    constraints.Add(new(prop.Name, enumEl[0].GetString()!));
                    continue;
                }
                // Follow $ref to enum type (e.g., "role": {"$ref": "AssistantRole"} where AssistantRole has enum: ["assistant"])
                if (prop.Value.TryGetProperty("$ref", out var propRef))
                {
                    var propRefTitle = propRef.GetString()!;
                    if (schemas.TryGetValue(propRefTitle, out var propRefSchema)
                        && propRefSchema.TryGetProperty("enum", out var refEnumEl)
                        && refEnumEl.GetArrayLength() == 1)
                    {
                        constraints.Add(new(prop.Name, refEnumEl[0].GetString()!));
                        continue;
                    }
                }
                // Also check inside nullable (anyOf with non-null having enum or $ref to enum)
                if (prop.Value.TryGetProperty("anyOf", out var anyOf))
                {
                    foreach (var av in anyOf.EnumerateArray())
                    {
                        if (av.TryGetProperty("enum", out var ae) && ae.GetArrayLength() == 1 && GetString(av, "type") != "null")
                        {
                            constraints.Add(new(prop.Name, ae[0].GetString()!));
                        }
                        else if (av.TryGetProperty("$ref", out var avRef))
                        {
                            var avRefTitle = avRef.GetString()!;
                            if (schemas.TryGetValue(avRefTitle, out var avRefSchema)
                                && avRefSchema.TryGetProperty("enum", out var avRefEnum)
                                && avRefEnum.GetArrayLength() == 1)
                            {
                                constraints.Add(new(prop.Name, avRefEnum[0].GetString()!));
                            }
                        }
                    }
                }
            }
        }
    }

    return constraints;
}

