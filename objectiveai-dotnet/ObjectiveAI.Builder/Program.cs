void AppendDescription(StringBuilder sb, string? description)
{
    if (description == null) return;
    sb.AppendLine("/// <summary>");
    foreach (var line in description.Split('\n'))
        sb.AppendLine($"/// {EscapeXml(line)}");
    sb.AppendLine("/// </summary>");
    sb.AppendLine($"[Description({EscapeCSharpString(description)})]");
}

string EscapeXml(string s) => s
    .Replace("&", "&amp;")
    .Replace("<", "&lt;")
    .Replace(">", "&gt;");

string EscapeCSharpString(string s)
{
    if (s.Contains('"') || s.Contains('\\') || s.Contains('\n') || s.Contains('\r'))
    {
        int maxQuotes = 0;
        int current = 0;
        foreach (var c in s)
        {
            if (c == '"') { current++; maxQuotes = Math.Max(maxQuotes, current); }
            else current = 0;
        }
        var delim = new string('"', maxQuotes + 3);
        return $"{delim}\n{s}\n{delim}";
    }
    return $"\"{s}\"";
}

