using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

// ---------------------------------------------------------------------------
// Paths
// ---------------------------------------------------------------------------

var repoRoot = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", ".."));
var schemaDir = Path.Combine(repoRoot, "objectiveai-json-schema");
var sdkDir = Path.Combine(repoRoot, "objectiveai-dotnet", "ObjectiveAI");
var generatedDir = Path.Combine(sdkDir, "Generated");

Console.WriteLine($"Schema dir: {schemaDir}");
Console.WriteLine($"Generated dir: {generatedDir}");

// ---------------------------------------------------------------------------
// Load schemas
// ---------------------------------------------------------------------------

var schemas = new Dictionary<string, JsonElement>();
foreach (var file in Directory.GetFiles(schemaDir, "*.json").OrderBy(f => f))
{
    var doc = JsonDocument.Parse(File.ReadAllText(file));
    var root = doc.RootElement;
    if (root.TryGetProperty("title", out var titleEl))
    {
        schemas[titleEl.GetString()!] = root.Clone();
    }
}
Console.WriteLine($"Read {schemas.Count} schemas");

var allTitles = new HashSet<string>(schemas.Keys);

// ---------------------------------------------------------------------------
// Generic prefix detection
// ---------------------------------------------------------------------------

var genericPrefixes = DetectGenericPrefixes(allTitles);
Console.WriteLine($"Detected {genericPrefixes.Count} generic prefixes");

// ---------------------------------------------------------------------------
// Detect ambiguous short names (same class name in multiple namespaces)
// ---------------------------------------------------------------------------

var namespaceTypeNames = new Dictionary<string, HashSet<string>>();
foreach (var title in allTitles)
{
    var ns = GetNamespaceForTitle(title);
    var shortName = TitleToClassName(title);
    if (!namespaceTypeNames.TryGetValue(ns, out var names))
    {
        names = [];
        namespaceTypeNames[ns] = names;
    }
    names.Add(shortName);
}

var ambiguousNames = namespaceTypeNames
    .SelectMany(kv => kv.Value.Select(n => (Name: n, Ns: kv.Key)))
    .GroupBy(x => x.Name)
    .Where(g => g.Select(x => x.Ns).Distinct().Count() > 1)
    .Select(g => g.Key)
    .ToHashSet();

// Also mark names that collide with their own namespace's last segment
// (e.g., class Expression in namespace ObjectiveAI.Functions.Expression)
foreach (var (ns, names) in namespaceTypeNames)
{
    var lastSegment = ns.Split('.').Last();
    if (names.Contains(lastSegment))
        ambiguousNames.Add(lastSegment);
}

Console.WriteLine($"Detected {ambiguousNames.Count} ambiguous short names");

// Per-file namespace — captured by ResolveRefType for collision detection
var currentNs = "ObjectiveAI";

// ---------------------------------------------------------------------------
// Clean generated directory
// ---------------------------------------------------------------------------

if (Directory.Exists(generatedDir))
    Directory.Delete(generatedDir, true);
Directory.CreateDirectory(generatedDir);

// ---------------------------------------------------------------------------
// Group schemas by output file
// ---------------------------------------------------------------------------

var fileGroups = new Dictionary<string, List<(string Title, JsonElement Schema)>>();
foreach (var (title, schema) in schemas)
{
    var (dirPath, fileName) = TitleToPath(title);
    var filePath = string.IsNullOrEmpty(dirPath) ? fileName : $"{dirPath}/{fileName}";
    if (!fileGroups.ContainsKey(filePath))
        fileGroups[filePath] = [];
    fileGroups[filePath].Add((title, schema));
}

Console.WriteLine($"Generating {fileGroups.Count} .cs files");

// ---------------------------------------------------------------------------
// Generate each file
// ---------------------------------------------------------------------------

foreach (var (filePath, entries) in fileGroups)
{
    var sb = new StringBuilder();
    sb.AppendLine("// THIS FILE IS AUTO-GENERATED. DO NOT EDIT.");
    sb.AppendLine("// Generated by ObjectiveAI.Builder from objectiveai-json-schema/.");
    sb.AppendLine();

    var ns = FilePathToNamespace(filePath);
    currentNs = ns;

    var usings = new HashSet<string>
    {
        "System.ComponentModel",
        "System.Text.Json.Serialization",
        "ObjectiveAI.Attributes"
    };

    var typeDefs = new List<string>();
    foreach (var (title, schema) in entries)
    {
        var code = GenerateType(title, schema, usings);
        typeDefs.Add(code);
    }

    foreach (var u in usings.OrderBy(u => u))
    {
        if (u != ns)
            sb.AppendLine($"using {u};");
    }
    sb.AppendLine();

    sb.AppendLine($"namespace {ns};");
    sb.AppendLine();

    sb.Append(string.Join("\n", typeDefs));

    var parts = filePath.Split('/');
    var outDir = parts.Length == 1 ? generatedDir : Path.Combine(generatedDir, Path.Combine(parts.Take(parts.Length - 1).ToArray()));
    Directory.CreateDirectory(outDir);
    var outFile = Path.Combine(outDir, parts.Last() + ".cs");
    File.WriteAllText(outFile, sb.ToString());
}

Console.WriteLine("Done!");

